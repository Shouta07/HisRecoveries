/* ── 公開の前に止めること ───────────────────────── */
{
  PRIVACY_ARTICLES.forEach((a, i) => {
    if (a.n !== i + 1) throw new Error(`プライバシーの条番号がずれています（第${a.n}条が${i + 1}番目）`);
    if (a.body.length === 0) throw new Error(`第${a.n}条（${a.title}）に本文がありません`);
    if (!a.lead) throw new Error(`第${a.n}条（${a.title}）に1行の説明がありません`);
  });

  const all =
    PRIVACY_ARTICLES.flatMap((a) => [a.title, a.lead, ...a.body]).join("\n") +
    PRIVACY_INTRO.join("\n");

  /* ── 畳んだ仕組みの記述が、残っていないこと ────────
     集めていないものを書くと、集めていると読まれる。 */
  for (const w of [
    "LINE", "トーク", "Google Meet", "オンライン相談", "回答者",
    "自動的に伏せ字", "画像は", "決済代行業者", "カード番号を",
  ]) {
    if (all.includes(w)) {
      throw new Error(`プライバシーに、畳んだ仕組みの記述「${w}」が残っています`);
    }
  }

  /* ── 取っていないものを「取る」と書かないこと ────── */
  if (!/氏名、電話番号、住所、生年月日、勤務先/.test(all)) {
    throw new Error("プライバシーに、取得しない情報が書かれていません");
  }
  for (const [re, why] of [
    [/入力していただく欄はありません/, "入力欄が無いこと"],
    [/決済の仕組み/, "決済の仕組みが無いこと"],
    [/位置情報/, "位置情報を求めないこと"],
  ] as [RegExp, string][]) {
    if (!re.test(all)) throw new Error(`プライバシーに、${why}が書かれていません`);
  }

  /* ── 連絡の扱いが、書いてあること ──────────────────
     ここが無いと、宿や自治体の方が送れない。 */
  for (const [re, why] of [
    [/公開されていない情報/, "未公開の情報を含む連絡の扱い"],
    [/第三者に開示せず/, "第三者へ開示しないこと"],
    [/事前にご本人の同意/, "使うときに同意を得ること"],
  ] as [RegExp, string][]) {
    if (!re.test(all)) throw new Error(`プライバシーに、${why}が書かれていません`);
  }

  /* ── 構想であることが、免責に書いてあること ──────── */
  if (!/実現を保証するものではありません/.test(all)) {
    throw new Error("プライバシーの免責に、構想であることが書かれていません");
  }

  /* ── 預け先を隠さず、使っていない先は書かないこと ── */
  if (!all.includes("Vercel")) {
    throw new Error("プライバシーに、委託先「Vercel」が書かれていません");
  }
  if (dbEnabled && !all.includes("Supabase")) {
    throw new Error("アクセス記録を Supabase へ入れているのに、委託先に書かれていません");
  }
  if (!dbEnabled && all.includes("Supabase")) {
    throw new Error("Supabase を使っていないのに、委託先として書かれています");
  }

  if (!/人工知能の学習に使用しません/.test(all)) {
    throw new Error("プライバシーに、学習に使わないことが書かれていません");
  }
  if (!all.includes(CO)) throw new Error("プライバシーに、事業者名が書かれていません");
  if (!all.includes(site.company.email)) {
    throw new Error("プライバシーに、問い合わせ先が書かれていません");
  }
}
