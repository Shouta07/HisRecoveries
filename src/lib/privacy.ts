/* ── 公開の前に止めること ─────────────────────────
   ここが緩むと、実際に集めているものと、
   書いてあることが、また食い違う。 */
{
  PRIVACY_ARTICLES.forEach((a, i) => {
    if (a.n !== i + 1) throw new Error(`プライバシーの条番号がずれています（第${a.n}条が${i + 1}番目）`);
    if (a.body.length === 0) throw new Error(`第${a.n}条（${a.title}）に本文がありません`);
    if (!a.lead) throw new Error(`第${a.n}条（${a.title}）に1行の説明がありません`);
  });

  const all =
    PRIVACY_ARTICLES.flatMap((a) => [a.title, a.lead, ...a.body]).join("\n") +
    PRIVACY_INTRO.join("\n");

  // ── 前の事業の文書に戻らないこと ────────────────
  // ここにあった語が1つでも出てきたら、
  // また別の事業の方針を載せている。
  for (const w of ["第一印象改善", "医療行為は行いません", "診断・治療は", "連携する医療機関", "当日のご案内"]) {
    if (all.includes(w)) {
      throw new Error(`プライバシーに、前の事業の記述「${w}」が残っています`);
    }
  }

  // ── 取っていないものを「取る」と書かないこと ────
  if (!/氏名、電話番号、住所、生年月日、勤務先/.test(all)) {
    throw new Error("プライバシーに、取得しない情報が書かれていません");
  }
  if (!all.includes("会員登録もありません")) {
    throw new Error("プライバシーに、会員登録が無いことが書かれていません");
  }
  if (!/カード番号を受け取ることも、保持することもありません/.test(all)) {
    throw new Error("プライバシーに、カード番号を保持しないことが書かれていません");
  }

  // ── 画像の扱い ──────────────────────────────────
  if (!all.includes(`${KEEP_DAYS}日`)) {
    throw new Error(`プライバシーに、画像を消すまでの日数（${KEEP_DAYS}日）が書かれていません`);
  }
  if (!all.includes(`${SIGNED_TTL}秒`)) {
    throw new Error(`プライバシーに、画像のリンクの有効時間（${SIGNED_TTL}秒）が書かれていません`);
  }
  if (!/外部から直接参照できない領域/.test(all)) {
    throw new Error("プライバシーに、画像を公開領域に置かないことが書かれていません");
  }

  /* ── 録音まわりは、実装とずれたら止める ──────────
     ここは一度ずれていた。
     「録音はしません」と書いたまま、通話を文字にする設計を進めていた。

     書いてある内容と、実際にやることが違うのがいちばんまずい。
     文字にする以上、次の4つは必ず書いてあること。 */
  {
    const MUST: [RegExp, string][] = [
      [/文字に書き起こ/, "通話を文字にすること"],
      [/双方が、その通話ごとに同意/, "両方の同意を毎回取ること"],
      [/利用せず、通話の終了後ただちに削除/, "同意が無いときに削除すること"],
      [/音声そのものは保存しません/, "音声を残さないこと"],
      [/書き起こした文章も削除/, "書き起こしも消すこと"],
      [/人工知能が推測したものは、事実と区別/, "推測と事実を分けること"],
      [/匿名の表示名/, "回答者が匿名で入ること"],
    ];
    for (const [re, what] of MUST) {
      if (!re.test(all)) {
        throw new Error(`プライバシーに、${what}が書かれていません`);
      }
    }
    // 古い約束が残っていないこと。
    // 「録音はしません」と「文字に書き起こします」は両立しない。
    if (/録音はしません/.test(all)) {
      throw new Error("プライバシーに「録音はしません」が残っています（文字起こしと両立しません）");
    }
  }

  // ── 預け先を隠さないこと ────────────────────────
  for (const v of ["Stripe", "Supabase", "Vercel", "Google"]) {
    if (!all.includes(v)) {
      throw new Error(`プライバシーに、委託先「${v}」が書かれていません`);
    }
  }

  // ── 学習に使わないと書いた以上、そう運用すること ──
  if (!/人工知能の学習に使用しません/.test(all)) {
    throw new Error("プライバシーに、相談内容を学習に使わないことが書かれていません");
  }

  // 会社名と問い合わせ先。
  if (!all.includes(CO)) throw new Error("プライバシーに、事業者名が書かれていません");
  if (!all.includes(site.company.email)) {
    throw new Error("プライバシーに、問い合わせ先が書かれていません");
  }
}
