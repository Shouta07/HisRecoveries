/* ── 公開の前に止めること ─────────────────────────
   判定も、前の商品のものだった。
   「通話を文字にすること」「回答者が匿名で入ること」が
   書かれていないと止める、という形。

   通話も回答者も無いので、書けば嘘になるものを要求していた。
   見るものを入れ替える。 */
{
  PRIVACY_ARTICLES.forEach((a, i) => {
    if (a.n !== i + 1) throw new Error(`プライバシーの条番号がずれています（第${a.n}条が${i + 1}番目）`);
    if (a.body.length === 0) throw new Error(`第${a.n}条（${a.title}）に本文がありません`);
    if (!a.lead) throw new Error(`第${a.n}条（${a.title}）に1行の説明がありません`);
  });

  const all =
    PRIVACY_ARTICLES.flatMap((a) => [a.title, a.lead, ...a.body]).join("\n") +
    PRIVACY_INTRO.join("\n");

  /* ── 前の文書に戻らないこと ──────────────────────
     1つでも出てきたら、また持っていない仕組みを書いている。 */
  for (const w of [
    "第一印象改善",
    "医療行為は行いません",
    "自動的に伏せ字",
    "Google Meet",
    "書き起こ",
    "匿名の表示名",
    "固有のリンク",
    "業務委託先である回答者",
  ]) {
    if (all.includes(w)) {
      throw new Error(`プライバシーに、持っていない仕組みの記述「${w}」が残っています`);
    }
  }

  // ── 取っていないものを「取る」と書かないこと ────
  if (!/氏名、電話番号、住所、生年月日、勤務先/.test(all)) {
    throw new Error("プライバシーに、取得しない情報が書かれていません");
  }
  if (!all.includes("会員登録もありません")) {
    throw new Error("プライバシーに、会員登録が無いことが書かれていません");
  }
  if (!/カード番号を受け取ることも、保持することもありません/.test(all)) {
    throw new Error("プライバシーに、カード番号を保持しないことが書かれていません");
  }

  /* ── 自動で伏せ字にする機能は、無い ────────────────
     ここが今回いちばん効く。
     「自動で伏せます」と書いてあると、読んだ人は
     旅券や搭乗券をそのまま送る。

     無いと言い切っていること、
     お客様ご自身でお願いしていること、両方を見る。 */
  if (!/自動的に伏せる仕組みはありません/.test(all)) {
    throw new Error("プライバシーに、自動で伏せる機能が無いことが書かれていません");
  }
  if (!/お客様ご自身で隠したうえで/.test(all)) {
    throw new Error("プライバシーに、伏せ字をお客様にお願いすることが書かれていません");
  }

  /* ── やりとりの場所が、書かれていること ────────────
     相談の中身は当社のサーバーではなく LINE にある。
     ここを書かないと、当社に消せないものを
     消せると思われる。 */
  for (const [re, what] of [
    [/LINEのサーバーを経由/, "LINEを経由すること"],
    [/同社の定めによります/, "LINE側の取扱いは同社の定めによること"],
    [/複製して保存する仕組みを設けていません/, "当社のデータベースへ入れないこと"],
  ] as [RegExp, string][]) {
    if (!re.test(all)) throw new Error(`プライバシーに、${what}が書かれていません`);
  }

  /* ── 預け先を隠さないこと ──────────────────────────
     Supabase は、設定されているときだけ書く。
     設定していないのに委託先として並べると、
     渡していない先を渡していると書くことになる。 */
  for (const v of ["Stripe", "Vercel", LINE_CO]) {
    if (!all.includes(v)) {
      throw new Error(`プライバシーに、委託先「${v}」が書かれていません`);
    }
  }
  if (dbEnabled && !all.includes("Supabase")) {
    throw new Error("アクセス記録を Supabase へ入れているのに、委託先に書かれていません");
  }
  if (!dbEnabled && all.includes("Supabase")) {
    throw new Error("Supabase を使っていないのに、委託先として書かれています");
  }

  // ── 学習に使わないと書いた以上、そう運用すること ──
  if (!/人工知能の学習に使用しません/.test(all)) {
    throw new Error("プライバシーに、相談内容を学習に使わないことが書かれていません");
  }

  // 会社名と問い合わせ先。
  if (!all.includes(CO)) throw new Error("プライバシーに、事業者名が書かれていません");
  if (!all.includes(site.company.email)) {
    throw new Error("プライバシーに、問い合わせ先が書かれていません");
  }
}
