// 希望する回答者の条件、画像、決済の記録。
// これだけ。schema.sql の consultations が持っている列と、
// consultation_images と payments に対応している。
//
// 増やしたら、ここも増やすこと。
// 列を足して、この文書を直さないのがいちばん危ない。
//
// ══════════════════════════════════════════════════
// 画像の日数を、書き写さない
// ══════════════════════════════════════════════════
// 「90日で消します」と書いて、実装が180日だと嘘になる。
