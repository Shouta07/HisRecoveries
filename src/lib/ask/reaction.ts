import { VERDICTS } from "./model";

// 女性の反応を、言葉だけで終わらせない。
//
// ══════════════════════════════════════════════════
// なぜ構造にするか
// ══════════════════════════════════════════════════
// いままで返ってくるのは、判定（このままでOK / 少し気になる /
// 変えた方がいい）と、自由に書いた文だけだった。
//
// 文は読む人には効くが、溜めても比べられない。
// 10件たまっても「だいたい好評」以上のことが言えない。
//
// 同じ尺度で答えてもらえば、溜めたものが効いてくる。
//   誘うのが早いと言われるのは、どの段階か
//   返信したくなると言われる文は、何が違うか
//
// ══════════════════════════════════════════════════
// 第一印象は、足さない
// ══════════════════════════════════════════════════
// 「第一印象（自然 / 少し気になる / 違和感がある）」を
// 足す案があったが、やめた。
//
// すでにある判定が、ほぼ同じことを聞いている。
//   このままでOK   ≒ 自然
//   少し気になる   ＝ 少し気になる
//   変えた方がいい ≒ 違和感がある
//
// 両方置くと、同じ人に同じことを2回聞くことになる。
// 答える側の手間が増えるうえ、2つの列はほぼ同じ動きをするので、
// 溜めても新しいことが分からない。
//
// ══════════════════════════════════════════════════
// 相手の気持ちを当てる尺度にしない
// ══════════════════════════════════════════════════
// 「脈あり度」は作らない。それは相手の気持ちの判定で、
// この製品が売っているものではない（利用規約 第12条）。
//
// 聞くのは、読んだ本人のことだけ。
//   自分には、この距離感がどう感じられたか
//   自分なら、返信したくなるか
// 主語が答える本人なので、本人にしか分からず、当てずっぽうにならない。
//
// ══════════════════════════════════════════════════
// 答えなくてよい
// ══════════════════════════════════════════════════
// 自己紹介文の相談に「距離感」を必須で聞くと、
// 関係ない設問に何かを選ばせることになる。
// それは埋まっているだけで、中身の無いデータになる。
//
// どちらも任意。答えが無いことは、無いままで持つ。

/** 送ろうとしているものの距離感。読んだ本人にどう感じられたか */
export type Distance = "ok" | "early" | "too_early";

export const DISTANCES: { id: Distance; label: string; hint: string }[] = [
  { id: "ok", label: "ちょうどいい", hint: "この距離で来たら、自然に受け取れる" },
  { id: "early", label: "少し早い", hint: "受け取れるが、少し急だと感じる" },
  { id: "too_early", label: "かなり早い", hint: "この段階で来ると、構えてしまう" },
];

export function isDistance(x: unknown): x is Distance {
  return typeof x === "string" && DISTANCES.some((d) => d.id === x);
}

/**
 * 返信したくなるか。1〜5。
 *
 * 「返信が来る確率」ではない。読んだ本人が、返したくなるかどうか。
 * 確率にすると当たり外れの話になる。
 */
export const REPLY_URGE_MIN = 1;
export const REPLY_URGE_MAX = 5;

export const REPLY_URGE_LABEL = "自分なら、返信したくなるか";
export const REPLY_URGE_ENDS = { low: "返さないと思う", high: "すぐ返したくなる" };

export function isReplyUrge(x: unknown): x is number {
  return (
    typeof x === "number" &&
    Number.isInteger(x) &&
    x >= REPLY_URGE_MIN &&
    x <= REPLY_URGE_MAX
  );
}

/* ── 公開の前に止めること ───────────────────────── */
{
  // 判定と、同じことを聞いていないこと。
  // 増やすたびに答える側の手間が増えるので、重なったら足さない。
  const verdictLabels = VERDICTS.map((v) => v.label);
  for (const d of DISTANCES) {
    if (verdictLabels.includes(d.label)) {
      throw new Error(`距離感「${d.label}」が、判定と同じことを聞いています`);
    }
  }

  // 相手の気持ちを当てる尺度にしない。
  // 主語は、答える本人であること。
  const MIND_READING = /脈あり|脈なし|本命|好かれ|嫌われ|気持ちを当て|成功率|確率/;
  const all = [
    ...DISTANCES.flatMap((d) => [d.label, d.hint]),
    REPLY_URGE_LABEL,
    REPLY_URGE_ENDS.low,
    REPLY_URGE_ENDS.high,
  ];
  for (const t of all) {
    if (MIND_READING.test(t)) {
      throw new Error(`反応の尺度「${t}」が、相手の気持ちの判定になっています`);
    }
  }

  // 3段であること。
  // 増やすと、答える側が迷って真ん中に寄る。
  if (DISTANCES.length !== 3) {
    throw new Error(`距離感が ${DISTANCES.length} 段あります（3段）`);
  }
  // 真ん中が無いこと（3段のうち、片側に寄った並びにしない）。
  if (DISTANCES[0].id !== "ok") {
    throw new Error("距離感の先頭が「ちょうどいい」ではありません");
  }

  // 1〜5であること。
  if (REPLY_URGE_MIN !== 1 || REPLY_URGE_MAX !== 5) {
    throw new Error("返信したくなる度は1〜5にしてください");
  }
  // 両端に言葉があること。数字だけだと、何を答えるのか分からない。
  if (!REPLY_URGE_ENDS.low || !REPLY_URGE_ENDS.high) {
    throw new Error("返信したくなる度の両端に、言葉がありません");
  }
}
