/**
 * まとめ買い（回数）の有効期限。買った日から。
 *
 * ══════════════════════════════════════════════════
 * 期限を作らない、をやめた
 * ══════════════════════════════════════════════════
 * ここは元々「期限を作らない」だった。
 * 急がせる商売にしないため、という理由で、それ自体は正しい。
 *
 * 変えたのは、残高に期限の無い回数券が
 * 資金決済法の「前払式支払手段（自家型）」そのものだから。
 * 未使用残高が基準日（3/31・9/30）に1,000万円を超えると、
 * 財務局への届出と、残高の半額の供託が要る。
 *
 * 発行日から6か月以内しか使えないものは、そもそも適用の外
 * （資金決済法4条2号／施行令4条2項）。
 * 180日にしておけば、この話が丸ごと発生しない。
 *
 * ══════════════════════════════════════════════════
 * 180日は、急かす長さではない
 * ══════════════════════════════════════════════════
 * 5回を180日なら、36日に1回のペース。
 * 「今週中に使わないと消えます」にはならない。
 *
 * 画面では、残りと一緒に期限を必ず出す。
 * 買うときにも出す（特商法の表記と、決済の直前）。
 * 黙って消すのがいちばん悪い。
 */
/**
 * 決済とレシートに出す、正式な商品名。
 *
 * ══════════════════════════════════════════════════
 * 画面の名前と、請求書の名前を分ける
 * ══════════════════════════════════════════════════
 * 画面では「文章・画像で確カメる」でいい。
 * 買う人はその言葉で選んでいる。
 *
 * しかし、カードの明細と領収書に「確カメる」とだけ出ると、
 * 1か月後に明細を見た本人が、何の請求か分からない。
 * 決済代行の審査担当者も、何を売っているのか読み取れない。
 *
 * どちらにも同じ意味が通る形にする。
 *   タシカメ｜文章・画像によるオンライン恋愛相談｜1回
 *   タシカメ｜オンライン恋愛相談（通話15分）｜5回パス
 *
 * ブランドの言い回し（確カメる）は、ここには入れない。
 */
const FORMAL_FAMILY: Record<Family, string> = {
  text: "文章・画像によるオンライン恋愛相談",
  call: "オンライン恋愛相談（通話15分）",
};

export function formalName(id: PlanId): string {
  const p = plan(id);
  const how = p.uses ? `${p.uses}回パス` : "1回";
  return `${NAME}｜${FORMAL_FAMILY[p.family]}｜${how}`;
}

export const PASS_VALID_DAYS = 180;

/** 期限の日付。買った日から PASS_VALID_DAYS 日後 */
export function passExpiresAt(paidAt: Date): Date {
  const d = new Date(paidAt);
  d.setDate(d.getDate() + PASS_VALID_DAYS);
  return d;
}


