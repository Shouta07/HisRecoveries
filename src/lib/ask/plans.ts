const FORMAL_FAMILY: Record<Family, string> = {
  text: "文章・画像によるオンライン恋愛相談",
  call: "オンライン恋愛相談（通話15分）",
};

export function formalName(id: PlanId): string {
  const p = plan(id);
  const how = p.uses ? `${p.uses}回パス` : "1回";
  return `${NAME}｜${FORMAL_FAMILY[p.family]}｜${how}`;
}

export const PASS_VALID_DAYS = 180;

/** 期限の日付。買った日から PASS_VALID_DAYS 日後 */
export function passExpiresAt(paidAt: Date): Date {
  const d = new Date(paidAt);
  d.setDate(d.getDate() + PASS_VALID_DAYS);
  return d;
}


/**
 * その人数を配るのに、最低いくら必要か。
 *
 * 回答者への下限（1人150円）×人数を、売価の6割以内に収める。
 * ここを割ると、売った時点で決済手数料と返金引当を賄えない。
 *
 * 980円 × 3人 なら 750円。通る。
 * 980円 × 5人 なら 1,250円。通らない（だから入口は3人）。
 */
export function MIN_PLAN_YEN(answers: number): number {
  return Math.ceil((150 * answers) / 0.6 / 10) * 10;
}

const BY_ID = new Map(PLANS.map((p) => [p.id, p]));

export function plan(id: PlanId): Plan {
  const p = BY_ID.get(id);
  if (!p) throw new Error(`未定義のプラン: ${id}`);
  return p;
}

export function isPlanId(x: unknown): x is PlanId {
  return typeof x === "string" && BY_ID.has(x as PlanId);
}

/** いま買えるものだけ */
export function sellable(): Plan[] {
  return PLANS.filter((p) => p.available);
}

/**
 * トップの料金に出すもの。
 *
 * 1つだけにする。
 * 最初から料金表を並べると、選ぶ前に読む量が増えて、
 * 「何に迷っているか」より先に「どれを買うか」を考えさせることになる。
 *
 * ほかの商品は、必要になった場面でだけ出す。
 *   話す      → 回答を見て「もう少し話したい」と思ったとき
 *   直す      → 引っかかった点が出たとき
 *   もう一度  → 直したあと
 * 買う人にファネルを見せない。次に要ることだけが出てくる。
 */
/**
 * トップの料金に出すもの。
 *
 * ここを画面が使っていないと、上限の判定が何も守らなくなる。
 * トップは topPlans()、/plans は PLANS を出す。
 */
export function topPlans(): Plan[] {
  return PLANS.filter((p) => p.onTop);
}

export function isSellable(id: unknown): id is PlanId {
  return isPlanId(id) && plan(id).available;
}

/** 何も指定されなかったときに選ばれるプラン（主力） */
export const DEFAULT_PLAN: PlanId = (
  sellable().find((p) => p.featured) ?? sellable()[0]
).id;

/** いちばん安い、買えるプラン。入口に出す */
export const ENTRY_PLAN: PlanId = [...sellable()].sort((a, b) => a.yen - b.yen)[0].id;

/**
 * 実際に請求する金額。
 *
 * 画面から来た金額は一切見ない。プランIDだけを受け取って、ここで引く。
 * 金額を受け取れる形にすると、1円で Checkout を作られる。
 *
 * オプションは持たない。値段の差は、商品そのものの深さで付ける
 * （見てもらう → 反応を見る → 会話を試す → 一人について決める → 本番を再現する）。
 */
export function priceOf(id: PlanId): number {
  return plan(id).yen;
}

/** そのプランで、年代以外の条件を指定してよいか */
export function allowsTargeting(id: PlanId): boolean {
  return plan(id).targeting;
}

/**
 * 指定された条件を、プランの範囲に丸める。
 * 指定できないプランで条件を送られても、黙って落とす。
 */
export function clampTargeting(
  id: PlanId,
  panelAge: PanelAge,
  attrs: AttrId[],
): { panelAge: PanelAge; attrs: AttrId[] } {
  if (allowsTargeting(id)) return { panelAge, attrs };
  return { panelAge: "any", attrs: [] };
}

/* ── 公開の前に止めること ───────────────────────── */
{
  if (PLANS.length === 0) throw new Error("プランが1つもありません");
  if (sellable().length === 0) throw new Error("買えるプランが1つもありません");

  for (const p of PLANS) {
    // 実在の人の時間を扱っているので、いくらでも下げてよいわけではない。
    // 下限は「下限の報酬で、人数分を払える額」。
    // ここを割ると、売った時点で回答者に払えない。
    const floor = MIN_PLAN_YEN(p.answers);
    if (p.yen < floor) {
      throw new Error(
        `プラン「${p.id}」が安すぎます（${p.yen}円）。${p.answers}人に払うには ${floor}円 以上が要ります`,
      );
    }
    if (!Number.isInteger(p.yen)) throw new Error(`プラン「${p.id}」の金額が整数ではありません`);
    // 保存できない人数を売らない。売ったあとに弾かれると、
    // 払ったのに配られない相談ができる。
    // 1対1で話す商品は、そもそも人数を集めないので対象外。
    if (!p.talk && !isPanelSize(p.answers)) {
      throw new Error(`プラン「${p.id}」の人数 ${p.answers} は保存できません（PANEL_SIZES 外）`);
    }
    if (p.talk && p.answers !== 1) {
      throw new Error(`プラン「${p.id}」は1対1です。人数は1にしてください`);
    }
    if (p.rounds < 1) throw new Error(`プラン「${p.id}」の回数が不正です`);
    // 金額だけ見せると高く感じる。何が返ってくるかを必ず持たせる。
    if (p.includes.length < 3) {
      throw new Error(`プラン「${p.id}」に、何が返ってくるかが書かれていません`);
    }
    // 対面を含むものを、手順が無いまま売らない。
    if (p.offline && p.available) {
      throw new Error(
        `プラン「${p.id}」は対面を含みます。受け入れ手順が用意できるまで available は false にしてください`,
      );
    }
  }

  // 深さは、家族ごとに1つ。
  //
  // 1回と5回分は、別の商品ではなく同じ商品の買い方。
  // 買い方の違いで「深さ」が変わることはない。
  // 前はSKUごとに深さを付けていて、
  // 1回売りを足した瞬間に「パックより1回売りのほうが深い」という
  // おかしな並びを強いられた。家族で見るように直した。
  {
    const byFamily = new Map<Family, Depth>();
    for (const p of PLANS) {
      const had = byFamily.get(p.family);
      if (had !== undefined && had !== p.depth) {
        throw new Error(
          `家族「${p.family}」の中で深さが食い違っています（${had} と ${p.depth}）`,
        );
      }
      byFamily.set(p.family, p.depth);
    }
    if (new Set(byFamily.values()).size !== byFamily.size) {
      throw new Error("別の家族が同じ深さになっています（選ぶ理由が消えます）");
    }
  }

  // 高いほど深いこと。家族どうしで、いちばん安い1回あたりで比べる。
  const perUse = (p: Plan) => (p.uses ? p.yen / p.uses : p.yen);
  {
    const cheapest = new Map<Family, { yen: number; depth: Depth }>();
    for (const p of PLANS) {
      const cur = cheapest.get(p.family);
      if (!cur || perUse(p) < cur.yen) cheapest.set(p.family, { yen: perUse(p), depth: p.depth });
    }
    const rows = [...cheapest.entries()].sort((a, b) => a[1].yen - b[1].yen);
    for (let i = 1; i < rows.length; i++) {
      if (rows[i][1].depth <= rows[i - 1][1].depth) {
        throw new Error(
          `家族「${rows[i][0]}」（1回 ¥${Math.round(rows[i][1].yen)}）は` +
            `「${rows[i - 1][0]}」（1回 ¥${Math.round(rows[i - 1][1].yen)}）より高いのに、` +
            `仕上げが浅くなっています`,
        );
      }
    }
  }

  // まとめ買いが、1回ずつ買うより高くならないこと。
  //
  // 「5回分のほうがお得」と書いて、実際は割高だった、をコードで止める。
  // 同じ家族の中で、いちばん安い1回売りと比べる。
  for (const pack of PLANS.filter((p) => p.uses)) {
    // お試し（中身が軽い入口）は外して比べる。
    // ¥980 の軽いものと、¥1,540 の通常のものを1回あたりで並べても、
    // 比べたことにならない。外してよい理由は、下の判定で確かめている。
    const singles = PLANS.filter((p) => p.family === pack.family && !p.uses && !p.trial);
    if (singles.length === 0) continue;
    const cheapestSingle = Math.min(...singles.map((p) => p.yen));
    if (perUse(pack) >= cheapestSingle) {
      throw new Error(
        `「${pack.name}」は1回あたり ¥${Math.round(perUse(pack))} で、` +
          `1回ずつ買う（¥${cheapestSingle}）より安くなっていません`,
      );
    }
  }

  /* ── お試しは、本当に軽いこと ──────────────────────
     まとめ買いの割安判定から外している以上、
     「軽い」が口だけにならないようにする。

     ここが通らなくなったら、外すのをやめるか、中身を軽くするか。
     どちらでもなく判定を消すのが、いちばんまずい。 */
  {
    const trials = PLANS.filter((p) => p.trial);
    if (trials.length > 1) {
      throw new Error(`お試しが ${trials.length} 個あります（1つまで）`);
    }
    for (const t of trials) {
      if (t.uses) throw new Error(`お試し「${t.id}」が、まとめ買いになっています`);
      const normals = PLANS.filter((p) => p.family === t.family && !p.uses && !p.trial);
      if (normals.length === 0) {
        throw new Error(`お試し「${t.id}」と比べる通常の1回売りがありません`);
      }
      for (const n of normals) {
        // 値段が安いこと。
        if (t.yen >= n.yen) {
          throw new Error(`お試し「${t.id}」（¥${t.yen}）が「${n.id}」（¥${n.yen}）より安くありません`);
        }
        // 返すものが少ないこと。同じものを安く売っているなら、
        // 高いほうを買う理由が無くなる。
        if (t.includes.length >= n.includes.length) {
          throw new Error(
            `お試し「${t.id}」が返すもの（${t.includes.length}個）が、` +
              `「${n.id}」（${n.includes.length}個）より少なくありません`,
          );
        }
        // 返すものが、通常の一部であること（勝手に別のものを足さない）。
        for (const x of t.includes) {
          if (!n.includes.includes(x)) {
            throw new Error(`お試し「${t.id}」に、「${n.id}」に無い「${x}」が入っています`);
          }
        }
      }
      // 指名はできない。できると、通常との差が値段だけになる。
      if (t.targeting) throw new Error(`お試し「${t.id}」で指名ができるようになっています`);
    }
  }

  // トップに出すのは5つまで。
  //
  // 段そのものが商品になった。
  //   見てもらう → 反応を見る → 会話を試す → 一人について決める → 本番を再現する
  // この並びを見せないと、値段の差が説明できない。
  //
  // 6つ目からは増やさない。増やすなら、どれかを畳む。
  // 実際、通話を15分と30分に分けたときに6つになったので、
  // 動画の商品（reaction）を onTop: false にして5つに戻した。
  if (topPlans().length > 5) {
    throw new Error(`トップの料金が ${topPlans().length} 個あります（5つまで）`);
  }
  if (topPlans().length === 0) throw new Error("トップに出すプランがありません");
  if (!topPlans()[0].available) {
    throw new Error("トップに出すプランが買えません");
  }
  // 1対1で話すものを、受け入れ手順が無いまま売らない。
  // 相手も実在の人なので、時間を決めた手順とその場を見る体制が要る。
  for (const p of PLANS) {
    if (p.talk && p.available) {
      throw new Error(
        `プラン「${p.id}」は1対1で話す商品です。受け入れ手順が用意できるまで available は false にしてください`,
      );
    }
  }
  // 再テストを謳う以上、2回以上聞くプランが要る。
  // 「直して、もう一度」は独立した商品ではなくなった。
  // 直し方と修正文は「女性目線レビュー」に含まれる。
  // 別の人にもう一度見てもらう工程を売るなら、そのときに
  // 値段と原価を作り直すこと（いまの ¥5,980 では原価が出ない）。

  // 目立たせるプランは1つ。2つあると、どれを選べばいいか分からない。
  if (PLANS.filter((p) => p.featured).length !== 1) {
    throw new Error("おすすめのプランは1つだけにしてください");
  }
  if (!plan(PLANS.find((p) => p.featured)!.id).available) {
    throw new Error("買えないプランをおすすめにしないでください");
  }

  // 専門用語を利用者の画面に出さない。
  // 「Human Validation」「C2C」「マーケットプレイス」は、こちらの説明の言葉。
  // 買う人が3秒で分かる必要があるので、名前と売り文句には入れない。
  const JARGON = [
    "C2C", "Human Validation", "マーケットプレイス", "プラットフォーム",
    "パネル", "アンケート", "リサーチ", "バリデーション", "モニター",
  ];
  const copy = PLANS.flatMap((p) => [p.name, p.tagline, ...p.includes, ...p.fits]);
  for (const t of copy) {
    const hit = JARGON.find((j) => t.includes(j));
    if (hit) {
      throw new Error(`画面の言葉に専門用語「${hit}」が入っています（通す／読まれる／確かめる で書く）`);
    }
    // 値段を否定する言葉を、買う人の画面に出さない。
    assertWeight(t, "商品の説明");
    // 安さで売らない。原価は答える女性への支払い。
    assertNotCheap(t, "商品の説明");
    // 怖がらせて売らない。渡すのは決めるための材料。
    assertNotScary(t, "商品の説明");
    // 誰が読むのかを濁さない。「人」と書くと、誰でもよくなる。
    assertWhoReads(t, "商品の説明");
    // 硬い言葉を混ぜない。読むのは29歳の会社員。
    assertPlain(t, "商品の説明");
  }

  // 声で話す商品の決まりごと。
  // 通話は1対1で、分数はサーバーが持つ。ここが崩れると時間を切れない。
  for (const p of PLANS) {
    if (p.callMinutes === undefined) continue;
    if (!p.talk) throw new Error(`プラン「${p.id}」に分数があるのに、話す商品になっていません`);
    if (p.answers !== 1) throw new Error(`プラン「${p.id}」は通話です。人数は1にしてください`);
    if (p.offline) throw new Error(`プラン「${p.id}」は通話です。対面と混ぜないでください`);
    // 何分かを、買う人の画面にも必ず書く。書いていないと、
    // 切れたときに「まだ話せると思っていた」になる。
    if (!p.includes.some((x) => x.includes(`${p.callMinutes}分`))) {
      throw new Error(`プラン「${p.id}」に「${p.callMinutes}分」と書かれていません`);
    }
    // 幅で書かない。幅があると、何分で切ってよいのかが決まらない。
    if (/〜\s*\d+分|\d+\s*〜\s*\d+/.test(p.tagline)) {
      throw new Error(`プラン「${p.id}」の分数が幅になっています（${p.tagline}）`);
    }
  }
  // 声の商品があること。
  //
  // 15分と30分の2本立てをやめて、15分だけにした。
  // 30分 ¥9,800 は、15分を ¥2,980 にした時点で
  // 「同じことが4倍」に見える並びになっていた。
  // 短く試してから深く、は回数（15分×5回）で作る。
  if (!PLANS.some((p) => p.callMinutes === 15)) {
    throw new Error("15分の通話プランがありません");
  }
  // 分数は15分だけ。増やすなら、原価と受け入れ手順を一緒に作ること。
  for (const p of PLANS) {
    if (p.callMinutes !== undefined && p.callMinutes !== 15) {
      throw new Error(`プラン「${p.id}」の分数（${p.callMinutes}分）は、まだ受け入れ手順がありません`);
    }
  }

  // 売っているものが4つであること。
  //
  // 商品を増やすのは簡単で、増えたぶんは必ず
  // 特商法・規約・Stripe・決済直前の画面へ書き写す必要がある。
  // 書き写し漏れが、実態と表示のずれになる。
  // 増やすときは、この数字も一緒に動かすこと。
  if (PLANS.length !== 5) {
    throw new Error(
      `商品が ${PLANS.length} 個あります（4個。増やすなら特商法・規約・Stripeの説明も一緒に直してください）`,
    );
  }
  // ══════════════════════════════════════════════
  // 声のまとめ買いを、時間の財布にしない
  // ══════════════════════════════════════════════
  // 「15分 × 5回」は、合計75分ではある。
  // しかし「75分の残高」として持たせてはいけない。
  //
  // 時間で持たせると、こうなる。
  //   「あと40分あるので、今日は40分で」
  //   → 受ける側は15分のつもりで枠を空けている
  //   → 予定が組めない。原価も読めない
  //
  // 1回ぶん＝15分の通話1本。ここは動かさない。
  // uses は回数であって、分ではない。
  // 名前と分数が合っていること。1回売りにも効かせる。
  //
  // 前はこの判定を、まとめ買いの判定と同じ塊に入れていた。
  // 塊の頭で `!p.uses` を continue していたので、
  // 1回売り（uses が無い）は名前を確かめないまま通っていた。
  // 「20分」と書いて中身が15分、を止められていなかった。
  for (const p of PLANS) {
    if (!p.callMinutes) continue;
    const m = p.name.match(/(\d+)\s*分/);
    if (m && Number(m[1]) !== p.callMinutes) {
      throw new Error(
        `プラン「${p.id}」の名前は「${p.name}」ですが、実際は ${p.callMinutes}分です`,
      );
    }
  }

  for (const p of PLANS) {
    if (!p.callMinutes || !p.uses) continue;
    // 分数 × 回数を、そのまま uses に入れていないこと。
    if (p.uses > 20) {
      throw new Error(
        `プラン「${p.id}」の uses が ${p.uses} です。` +
          `uses は回数で、分ではありません（${p.callMinutes}分 × ${p.uses}回）`,
      );
    }
    // 名前と中身が合っていること。
    // 「20分 × 5回」と書いてあるのに callMinutes が15、を止める。
    const m = p.name.match(/(\d+)\s*分/);
    if (m && Number(m[1]) !== p.callMinutes) {
      throw new Error(
        `プラン「${p.id}」の名前は「${p.name}」ですが、実際は ${p.callMinutes}分です`,
      );
    }
    const u = p.name.match(/(\d+)\s*回/);
    if (u && Number(u[1]) !== p.uses) {
      throw new Error(
        `プラン「${p.id}」の名前は「${p.name}」ですが、実際は ${p.uses}回です`,
      );
    }
    // 合計の分数を、商品名や売り文句に書かない。
    // 「合計75分」と書いた瞬間に、時間の財布として読まれる。
    const total = p.callMinutes * p.uses;
    for (const t of [p.name, p.tagline, p.value, ...p.includes]) {
      if (t.includes(`${total}分`)) {
        throw new Error(
          `プラン「${p.id}」に「${total}分」と書かれています。` +
            `1回 ${p.callMinutes}分 × ${p.uses}回です（時間の残高ではありません）`,
        );
      }
    }
  }

  // 正式な商品名。明細と審査で読めること。
  for (const p of PLANS) {
    const f = formalName(p.id);
    if (!f.startsWith(NAME)) throw new Error(`「${p.id}」の正式名が店名で始まっていません（${f}）`);
    // 何を売っているのかが、その1行で分かること。
    if (!f.includes("恋愛相談")) {
      throw new Error(`「${p.id}」の正式名に、何のサービスかが書かれていません（${f}）`);
    }
    // ブランドの言い回しは明細に出さない。
    if (/確カメ|確かめ/.test(f)) {
      throw new Error(`「${p.id}」の正式名にブランドの言い回しが入っています（${f}）`);
    }
    // 回数が分かること。
    if (p.uses && !f.includes(`${p.uses}回パス`)) {
      throw new Error(`「${p.id}」の正式名に回数が書かれていません（${f}）`);
    }
    // 通話は分数が分かること。
    if (p.callMinutes && !f.includes(`${p.callMinutes}分`)) {
      throw new Error(`「${p.id}」の正式名に分数が書かれていません（${f}）`);
    }
  }

  // 回数で売るものに、期限があること。
  // 期限の無い回数券は、資金決済法の前払式支払手段そのものになる。
  if (PASS_VALID_DAYS < 1 || PASS_VALID_DAYS > 180) {
    throw new Error(
      `まとめ買いの有効期限が ${PASS_VALID_DAYS} 日です（180日以内。超えると資金決済法の前払式支払手段に当たります）`,
    );
  }

  // 「5回答でいくら」と書かない。個数を売るとアンケートに見える。
  for (const p of PLANS) {
    if (/\d\s*回答/.test(p.tagline)) {
      throw new Error(`プラン「${p.id}」が回答の個数を売っています（仕上げの深さで書いてください）`);
    }
  }

  /* ── 検索結果に出る説明文と、売っているものを突き合わせる ──
     site.description は、サイト全体の schema.org・OGP・
     記事ページのメタ記述が全部読んでいる1行。
     買う前にいちばん多く読まれる場所なので、
     ここに実際と違う人数が出ていると、買う人が人数を誤解する。

     実際にそうなっていた（「女性3人に読んでもらう」と書いてあり、
     売っている4商品はどれも1人）。気づけなかったのは、
     説明文とプランが別のファイルにあって、誰も突き合わせていなかったから。
     人数を変えたら、ここで止まる。 */
  const answerCounts = new Set(PLANS.map((p) => p.answers));
  const where: [string, string][] = [
    ["サイトの説明文", site.description],
    ["1画面目の受け渡しの行", HERO_HOW],
  ];
  for (const [name, text] of where) {
    const hits = text.match(/女性\s*(\d+)\s*人/g) ?? [];
    for (const hit of hits) {
      const n = Number(hit.replace(/\D/g, ""));
      if (!answerCounts.has(n)) {
        throw new Error(
          `${name}が「${hit}」と言っていますが、売っているのは ${[...answerCounts].join("・")}人です`,
        );
      }
    }
  }
  const hits = site.description.match(/女性\s*(\d+)\s*人/g) ?? [];
  // 人数を一言も書かないのは良いが、書くなら合っていること。
  // 「1人」と書いてあるのに全プランが1人でない、という逆も止める。
  if (hits.length === 0 && /\d+\s*人の女性/.test(site.description)) {
    throw new Error("サイトの説明文の人数が、突き合わせられない書き方になっています");
  }
}
