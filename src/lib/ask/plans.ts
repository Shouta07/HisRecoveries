  // 段そのものが商品になった。
  //   見てもらう → 反応を見る → 会話を試す → 一人について決める → 本番を再現する
  // この並びを見せないと、値段の差が説明できない。
  //
  // 6つ目からは増やさない。増やすなら、どれかを畳む。
  // 実際、通話を15分と30分に分けたときに6つになったので、
  // 動画の商品（reaction）を onTop: false にして5つに戻した。
