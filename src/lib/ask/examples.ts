import { CATEGORIES, MIND_READING, type CategoryId } from "./model";

/* ══════════════════════════════════════════════════
   トップに並べる、相談の例
   ══════════════════════════════════════════════════

   ── なぜ書き出し（STARTERS）を使わないか ──────────
   STARTERS は、相談を書く欄に入れるための文。
     「この文面で送っていいか、見てほしいです。」
   丁寧で、文として終わっている。押すと欄に入って、そこから直せる。

   トップで並べたいのは、そういう文ではない。
   頭の中で鳴っている声のほうを並べたい。
     「このLINE、重い？」

   同じものを両方に使うと、どちらかが不自然になる。
   短い札はトップ、書き出しは相談の欄。分けて持つ。

   ── 「脈ありだと思う？」は入れない ────────────────
   相手の気持ちを当てる問いは売っていない（利用規約 第12条）。
   場面そのものは残して、主語だけ自分に変える。

     昨日のデート、どう思われた？   相手の気持ち。当てられない
     昨日の自分、どう映った？       読んだ本人にしか分からない

   答えるのは読んだ女性なので、後者なら本人の話になる。 */

export type Example = {
  /** 札に出す一言。頭の中の声のまま */
  q: string;
  /** どのカテゴリとして受け取るか */
  cat: CategoryId;
};

export const EXAMPLES: Example[] = [
  { q: "このLINE、重い？", cat: "message" },
  { q: "返信が遅い。追って送っていい？", cat: "message" },
  { q: "既読のまま返ってこない。待つ？", cat: "message" },
  { q: "敬語、そろそろ外していい？", cat: "message" },
  { q: "この写真とこの写真、どっちがいい？", cat: "photo" },
  { q: "自己紹介文、これで伝わる？", cat: "photo" },
  { q: "いま電話に誘うのは早い？", cat: "date" },
  { q: "初デート、この店でいい？", cat: "date" },
  { q: "次に誘うなら、いつがいい？", cat: "date" },
  { q: "昨日の自分、どう映った？", cat: "signal" },
  { q: "この話題、踏み込みすぎ？", cat: "distance" },
  { q: "家に誘うのは、まだ早い？", cat: "distance" },
];

/* ══════════════════════════════════════════════════
   何を確カメられるか（4つ）
   ══════════════════════════════════════════════════
   並べる順は、恋愛の進み方そのもの。
   写真・プロフィールで会う前、LINEでやりとり、誘って、会ったあと。

   4つにしているのは、1画面に2×2で収まるから。
   増やすと、どれを押すかを決める作業になる。 */

export type Topic = {
  id: CategoryId;
  /** 見出し。「◯◯を確カメる」で揃える */
  head: string;
  /** その場面の、いちばん多い一言 */
  voice: string;
};

export const TOPICS: Topic[] = [
  { id: "message", head: "LINEを確カメる", voice: "これ送って大丈夫？" },
  { id: "photo", head: "写真・プロフィールを確カメる", voice: "どっちの写真がいい？" },
  { id: "date", head: "誘い方を確カメる", voice: "今誘って早すぎない？" },
  // 「脈を確カメる」ではない。主語を自分にしてある（上に書いた理由）。
  { id: "signal", head: "デートのあとを確カメる", voice: "昨日の自分、どう映った？" },
];

/* ── 公開の前に止めること ───────────────────────── */
{
  // 相手の気持ちを当てる問いを売らない。
  // ここはトップのいちばん目立つところに出るので、
  // ラベルと同じ線を引いておく。
  for (const t of [
    ...EXAMPLES.map((e) => e.q),
    ...TOPICS.flatMap((t) => [t.head, t.voice]),
  ]) {
    if (MIND_READING.test(t)) {
      throw new Error(`相談の例「${t}」が、相手の気持ちの判定になっています`);
    }
  }

  // 札は短いこと。長いと読まずに通り過ぎる。
  // 横に並べるので、1枚が広いと3枚目から見えなくなる。
  for (const e of EXAMPLES) {
    if (e.q.length > 20) {
      throw new Error(`相談の例「${e.q}」が長すぎます（${e.q.length}字／20字まで）`);
    }
    // 問いの形であること。言い切ると、相談ではなく主張になる。
    if (!e.q.endsWith("？")) {
      throw new Error(`相談の例「${e.q}」が問いになっていません`);
    }
  }

  // 行き先が実在すること。押した先が無いと、そこで終わる。
  for (const x of [...EXAMPLES.map((e) => e.cat), ...TOPICS.map((t) => t.id)]) {
    const c = CATEGORIES.find((y) => y.id === x);
    if (!c) throw new Error(`相談の例の行き先「${x}」がありません`);
    if (!c.available) {
      throw new Error(`相談の例の行き先「${c.label}」は、まだ受け付けていません`);
    }
  }

  // 文字のことばかりにならないこと。
  // 全部が「この文面で…」だと、写真も見てもらえることが伝わらない。
  const kinds = new Set(EXAMPLES.map((e) => e.cat));
  if (kinds.size < 3) {
    throw new Error(`相談の例が ${kinds.size} 種類しかありません（3種類以上）`);
  }

  // 横に流して見せるので、少なすぎると流す意味が無い。
  if (EXAMPLES.length < 10) {
    throw new Error(`相談の例が ${EXAMPLES.length} 件しかありません（10件以上）`);
  }

  // 4つに絞ること。増やすと、どれを押すかを決める作業になる。
  if (TOPICS.length !== 4) {
    throw new Error(`確カメられることが ${TOPICS.length} 個あります（4個）`);
  }
  // 見出しは「確カメる」で揃える。ここだけ別の動詞にすると、
  // 何をしてもらえるのかが読むたびに変わる。
  for (const t of TOPICS) {
    if (!t.head.endsWith("を確カメる")) {
      throw new Error(`「${t.head}」が「◯◯を確カメる」になっていません`);
    }
  }
}
