import { plan, DEFAULT_PLAN } from "./plans";

// 画面の見本。
//
// ══════════════════════════════════════════════════
// 肯定的な回答ばかり並べない
// ══════════════════════════════════════════════════
// 前の見本は、こうだった。
//   「いいと思います！」
//   「好印象です！」
//   「送って大丈夫です！」
//
// これを見た人が、¥5,980 を払う理由は無い。
// 全部が「いいと思います」なら、聞く必要が無かったことになる。
//
// この製品にお金を払う理由は1つだけ。
//   自分では気づかなかった失敗の理由が、本番の前に見つかること。
//
// だから見本は、必ず何かが引っかかっているものにする。
// そして、引っかかったところを直した文面まで見せる。
//
// ══════════════════════════════════════════════════
// 売っていないものを、見本に出さない
// ══════════════════════════════════════════════════
// 前の見本は「直した案を別の3人に通したら3/3だった」で終わっていた。
// 直したものをもう一度別の人に通す工程は、いまの商品には入っていない
// （¥5,980 の原価に2巡目は載っていない）。
// 入っているのは、直し方と、そのまま使える修正文まで。
// 見本は、入っているものだけで終わらせる。
//
// ══════════════════════════════════════════════════
// ただし「必ず悪いところを探す」サービスにしない
// ══════════════════════════════════════════════════
// 問題が無ければ「このままで問題なさそう」も、ちゃんと結果。
// 粗探しが仕事になると、回答者は無理に難点を書くようになり、
// 書かれたほうは何を直せばいいのか分からなくなる。
//
// ══════════════════════════════════════════════════
// 無い数字を作らない
// ══════════════════════════════════════════════════
// 「失敗確率72%」のような数字は出さない。根拠が無い。
// 出すのは「3人中2人」だけ。数えられるものしか出さない。
//
// 5人がそう言った、を「女性全体がそう思う」と書かない。

export type DemoSay = {
  age: number;
  /** as_is / slight / change */
  verdict: "as_is" | "slight" | "change";
  say: string;
};

export type Demo = {
  /** 何を見てもらったか */
  subject: string;
  /** 出す直前のもの */
  before: string;
  /** 条件 */
  who: string[];
  says: DemoSay[];
  /** いちばん引っかかったところ */
  common: string;
  /** 直した案 */
  after: string;
  /** なぜそう直したか。修正文だけ渡されても、次に応用できない */
  why: string;
};

export const DEMO: Demo = {
  subject: "LINEのメッセージ",
  before: "また暇なときあったら教えて！",
  who: ["25〜29歳", "女性", "アプリ経験あり"],
  // 1回 = 1人。3人ではない（plans.ts の review を参照）。
  // そのぶん、1人が返すものを薄くしない。
  says: [
    {
      age: 27,
      verdict: "change",
      say: "「暇なとき」だと、相手に決めさせている感じがします。誘われた気がしないかも。",
    },
  ],
  common: "「暇なとき」が、相手任せに感じられる",
  after: "来週、水曜か金曜あたりでご飯どうですか？",
  why: "こちらから日を出すと、相手は「行く／行かない」だけ決めればよくなります。曜日を2つにしておくと、断りにもなりにくい。",
};

/** 何人がどう答えたか。見本の中で数え直す（手で書いた数を置かない） */
export function count(d: Demo, v: DemoSay["verdict"]): number {
  return d.says.filter((s) => s.verdict === v).length;
}

/* ── 公開の前に止めること ───────────────────────── */
{
  // 全部が「このままでOK」の見本を置かない。
  // それを見た人には、払う理由が無い。
  if (count(DEMO, "as_is") === DEMO.says.length) {
    throw new Error("見本が全部「このままでOK」です。払う理由が見えません");
  }
  // 2人以上いるなら、全部が否定でもいけない。粗探しのサービスに見える。
  // 1人のときは、この判定は置けない（どちらか1つしか選べないため）。
  // 代わりに「直した文面」と「なぜそう直したか」で、
  // 粗探しで終わっていないことを担保する（下の判定）。
  if (DEMO.says.length >= 2 && count(DEMO, "as_is") === 0) {
    throw new Error("見本に「このままでOK」が1つもありません（粗探しに見えます）");
  }
  // 直した案が、元と同じでは意味が無い。
  if (DEMO.after === DEMO.before) throw new Error("直した案が元のままです");
  // 修正文を渡すだけで終わらせない。なぜそう直したかが無いと、次に応用できない。
  if (!DEMO.why) throw new Error("直した理由が書かれていません（修正文だけでは次に使えません）");
  // 見本の人数が、売っている人数と違っていないこと。
  // ここがずれると、買ったあとに「見本より少ない」になる。
  if (DEMO.says.length !== plan(DEFAULT_PLAN).answers) {
    throw new Error(
      `見本が${DEMO.says.length}人ですが、${plan(DEFAULT_PLAN).name}は${plan(DEFAULT_PLAN).answers}人です`,
    );
  }
  // 共通点は、必ず1つ書く。ここが無いと、ただのコメント一覧になる。
  if (!DEMO.common) throw new Error("共通して言われた箇所が書かれていません");

  // 根拠の無い数字を出さない。
  const NUMBERS = /確率|成功率|失敗率|\d+%/;
  const all = [DEMO.common, DEMO.why, ...DEMO.says.map((s) => s.say)];
  for (const t of all) {
    if (NUMBERS.test(t)) {
      throw new Error(`見本に根拠の無い数字が入っています（${t}）`);
    }
  }
  // 3人の反応を、女性全体の総意にしない。
  const ALL_WOMEN = /女性はみんな|女性全体|女性というのは|女心/;
  for (const t of all) {
    if (ALL_WOMEN.test(t)) {
      throw new Error(`見本が女性全体の総意のように書かれています（${t}）`);
    }
  }
}
