// 画面の見本。
//
// ══════════════════════════════════════════════════
// 肯定的な回答ばかり並べない
// ══════════════════════════════════════════════════
// 前の見本は、こうだった。
//   「いいと思います！」
//   「好印象です！」
//   「送って大丈夫です！」
//
// これを見た人が、980円を払う理由は無い。
// 全部が「いいと思います」なら、聞く必要が無かったことになる。
//
// この製品にお金を払う理由は1つだけ。
//   自分では気づかなかった失敗の理由が、本番の前に見つかること。
//
// だから見本は、必ず何かが引っかかっているものにする。
// そして直して、もう一度通して、消えたところまで見せる。
//
// ══════════════════════════════════════════════════
// ただし「必ず悪いところを探す」サービスにしない
// ══════════════════════════════════════════════════
// 問題が無ければ「このままで問題なさそう」も、ちゃんと結果。
// 粗探しが仕事になると、回答者は無理に難点を書くようになり、
// 書かれたほうは何を直せばいいのか分からなくなる。
//
// ══════════════════════════════════════════════════
// 無い数字を作らない
// ══════════════════════════════════════════════════
// 「失敗確率72%」のような数字は出さない。根拠が無い。
// 出すのは「5人中3人」だけ。数えられるものしか出さない。
//
// 5人がそう言った、を「女性全体がそう思う」と書かない。

export type DemoSay = {
  age: number;
  /** as_is / slight / change */
  verdict: "as_is" | "slight" | "change";
  say: string;
};

export type Demo = {
  /** 何を見てもらったか */
  subject: string;
  /** 出す直前のもの */
  before: string;
  /** 条件 */
  who: string[];
  says: DemoSay[];
  /** 複数人が同じことを言った箇所 */
  common: string;
  /** 意見が分かれた箇所。無いこともある */
  split?: string;
  /** 直した案 */
  after: string;
  /** 直したあと、別の人に通した結果 */
  retest: { n: number; of: number; say: string };
};

export const DEMO: Demo = {
  subject: "LINEのメッセージ",
  before: "また暇なときあったら教えて！",
  who: ["25〜29歳", "女性", "アプリ経験あり"],
  says: [
    { age: 27, verdict: "change", say: "「暇なとき」だと、相手に決めさせている感じがします。誘われた気がしないかも。" },
    { age: 25, verdict: "change", say: "少し自信がなさそうに見えます。断られる前提で言っているような。" },
    { age: 29, verdict: "slight", say: "悪くはないけど、これだと返信を後回しにしちゃうと思います。" },
    { age: 26, verdict: "slight", say: "普通です。ただ、いつの話なのか分からないので予定が立てられません。" },
    { age: 28, verdict: "as_is", say: "私は特に気になりません。距離感としてはちょうどいいと思う。" },
  ],
  common: "「暇なとき」が、相手任せに感じられる",
  split: "絵文字を付けるかどうかは、意見が分かれました",
  after: "来週、水曜か金曜あたりでご飯どうですか？",
  retest: { n: 3, of: 3, say: "3人とも「自然になった」と答えました" },
};

/** 何人がどう答えたか。見本の中で数え直す（手で書いた数を置かない） */
export function count(d: Demo, v: DemoSay["verdict"]): number {
  return d.says.filter((s) => s.verdict === v).length;
}

/* ── 公開の前に止めること ───────────────────────── */
{
  // 全部が「このままでOK」の見本を置かない。
  // それを見た人には、払う理由が無い。
  if (count(DEMO, "as_is") === DEMO.says.length) {
    throw new Error("見本が全部「このままでOK」です。払う理由が見えません");
  }
  // 逆に、全部が否定でもいけない。粗探しのサービスに見える。
  if (count(DEMO, "as_is") === 0) {
    throw new Error("見本に「このままでOK」が1つもありません（粗探しに見えます）");
  }
  // 直した案が、元と同じでは意味が無い。
  if (DEMO.after === DEMO.before) throw new Error("直した案が元のままです");
  // 直したあとが、直す前より悪くなっていない。
  if (DEMO.retest.n < DEMO.retest.of) {
    throw new Error("直したあとの結果が全員一致していません（見本としては直り切った形にする）");
  }
  // 共通点は、必ず1つ書く。ここが無いと、ただのコメント一覧になる。
  if (!DEMO.common) throw new Error("共通して言われた箇所が書かれていません");

  // 根拠の無い数字を出さない。
  const NUMBERS = /確率|成功率|失敗率|\d+%/;
  const all = [DEMO.common, DEMO.split ?? "", DEMO.retest.say, ...DEMO.says.map((s) => s.say)];
  for (const t of all) {
    if (NUMBERS.test(t)) {
      throw new Error(`見本に根拠の無い数字が入っています（${t}）。出すのは「5人中3人」だけ`);
    }
  }
  // 5人の反応を、女性全体の総意にしない。
  const ALL_WOMEN = /女性はみんな|女性全体|女性というのは|女心/;
  for (const t of all) {
    if (ALL_WOMEN.test(t)) {
      throw new Error(`見本が女性全体の総意のように書かれています（${t}）`);
    }
  }
}
