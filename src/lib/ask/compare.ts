/**
 * 先に答える2つ。
 *
 * ══════════════════════════════════════════════════
 * 表では、この2つに勝てない
 * ══════════════════════════════════════════════════
 * 6列の表を出しても、スマホでは横に切れて読まれない。
 * 読まれないまま「友達でいいや」「AIでいいや」で閉じられる。
 *
 * この2つは、値段でもサービスの種類でもなく、
 * 「誰の目で見た反応か」で違う。そこだけ先に書く。
 *
 * ══════════════════════════════════════════════════
 * 相手を悪く書かない
 * ══════════════════════════════════════════════════
 * 友達に聞くのも、AIに聞くのも、ふつうに役に立つ。
 * 足りるときは足りる、と書いたうえで、足りないところを書く。
 * 「友達は当てにならない」と書いた時点で、こちらが疑われる。
 */
export const INSTEAD: {
  id: string;
  label: string;
  enough: string;
  short: string;
  why: string;
}[] = [
  {
    id: "friend",
    label: "友達に聞く",
    enough: "話を聞いてもらう。気持ちを整理する。",
    short: "相手側の目で見た反応は、返ってこない",
    why: "友達はあなたを知っています。知っているぶん、言いにくいことは言いません。同性の友達なら、そもそも相手側の目線ではありません。",
  },
  {
    id: "ai",
    label: "AIに聞く",
    enough: "文面を作る。考えをまとめる。たたき台を出す。",
    short: "返ってくるのは予測で、実際の反応ではない",
    why: "AIが返すのは「こう思われるだろう」です。実際に受け取った人が、どこで引っかかったかではありません。",
  },
];

/**
 * 表の上に必ず出す一文。
 *
 * 値段の差を「安い・高い」で読ませないための行。
 * 範囲が違うから金額のかたちも違う、という順で書く。
 */
export const COMPARE_SCOPE =
  "どれが良いかではなく、引き受けている範囲が違います。範囲が違うので、料金のかたちも違います。";

/** 表の下に必ず出す断り書き。消すとビルドが落ちる */
export const COMPARE_NOTE =
  "※ ほかの選び方は、一般的なかたちを書いたものです。料金も内容も、各社・各サービスで異なります。";

/* ── 公開の前に止めること ─────────────────────────
   比較は、こちらが有利になるほど危ない。
   数字と断定を、ここで機械的に止める。 */
{
  const ids = ALTERNATIVES.map((a) => a.id);
  if (ALTERNATIVES.filter((a) => a.us).length !== 1) {
    throw new Error("比較の表で、どれが自分たちか分からなくなっています");
  }

  for (const r of COMPARE) {
    for (const id of ids) {
      const v = r.cells[id];
      if (!v) throw new Error(`比較の「${r.label}」に ${id} の中身がありません`);

      // 自分たち以外の金額を書かない。出典が無いものは書けない。
      const other = !ALTERNATIVES.find((a) => a.id === id)?.us;
      if (other && /[¥￥]|\d+\s*(円|万|千)/.test(v)) {
        throw new Error(
          `比較の「${r.label}」で ${id} の金額を書いています（${v}）。出典のない金額は書けません`,
        );
      }

      // 相手を断定で悪く書かない。
      const UNFAIR =
        /できない|使えない|意味がない|役に立たない|劣る|ダメ|最悪|無駄|時代遅れ|やめたほうが|割に合わない|高すぎ/;
      if (other && UNFAIR.test(v)) {
        throw new Error(`比較の「${r.label}」で ${id} を断定で悪く書いています（${v}）`);
      }
    }
  }

  // 全部の行で自分たちが勝つ表は、読む人がいちばん信じない。
  // 「知られるか」は AI も同じ。ここが残っているかを見る。
  const tie = COMPARE.find((r) => r.id === "who_knows");
  if (!tie || !/知られない/.test(tie.cells.ai ?? "")) {
    throw new Error("比較が、こちらに都合よく片寄っています（勝てない行を消さないでください）");
  }

  if (!COMPARE_NOTE.includes("異なります")) {
    throw new Error("比較の断り書きが弱くなっています");
  }
  if (COMPARE.length < 4) throw new Error("比較の行が少なすぎます");

  // 値段の差を「安い・高い」で読ませないための一文が、消えていないこと。
  if (!/範囲が違う/.test(COMPARE_SCOPE)) {
    throw new Error("比較の前置きから「範囲が違う」が消えています");
  }
  if (/優れ|勝っ|上位|下位|安さ/.test(COMPARE_SCOPE)) {
    throw new Error(`比較の前置きが優劣の話になっています（${COMPARE_SCOPE}）`);
  }
  // 安さの言葉は voice.ts が持っている。ここで並べ直さない。
  assertNotCheap(COMPARE_SCOPE, "比較の前置き");
  for (const r of COMPARE) assertNotCheap(r.cells.us ?? "", `比較の「${r.label}」`);
  // 先に答える2つが、相手を悪く書いていないこと。
  // 「足りるとき」を書かずに短所だけ書くと、ただの否定になる。
  for (const x of INSTEAD) {
    if (!x.enough) throw new Error(`「${x.label}」で足りるときが書かれていません`);
    const UNFAIR2 = /当てにならない|意味がない|役に立たない|無駄|やめたほうが|信用できない/;
    for (const t of [x.short, x.why, x.enough]) {
      if (UNFAIR2.test(t)) {
        throw new Error(`「${x.label}」を断定で悪く書いています（${t}）`);
      }
    }
  }
  // 友達とAIの両方に答えていること。ここが実際の分かれ目。
  for (const must of ["friend", "ai"]) {
    if (!INSTEAD.some((x) => x.id === must)) {
      throw new Error(`先に答える2つから「${must}」が消えています`);
    }
  }

  // 「料金のかたち」の行は、必ず持っていること。
  // ここを消すと、値段の違いが説明されないまま表が出る。
  if (!COMPARE.some((r) => r.id === "price")) {
    throw new Error("比較に「料金のかたち」の行がありません");
  }
}
