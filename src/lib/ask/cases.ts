// こういう相談が来ます。
//
// ══════════════════════════════════════════════════
// 体験談にしない
// ══════════════════════════════════════════════════
// 見本では「27歳・ITエンジニア」「マッチはするけど、メッセージが噛み合ない…」
// のように、名前と年齢と職業が付いた声として並んでいた。
//
// それは体験談で、体験談は実在の利用者のものでないと書けない。
// 利用者はまだ0人なので、書けば作り話になる。
//
// なので年齢も職業も名前も付けない。
// 出すのは「どういう相談が来るか」という種類だけ。
// 悩みの言葉そのものは、種類の説明として使ってよい。
//
// ── 場面の写真は置かない ──────────────────────────
// 素材は 226×162 の切り抜きで、帯にすると顔が切れて髪だけが写る。
// 上に文面の箱を重ねるので、写真は箱の裏の模様にしかならなかった。
// 見せたいのは、送る文面と返ってくる言葉のほう。
//
// ── 返ってくる言葉の見本 ──────────────────────────
// 「何が返るのか」は、書いて説明するより1つ見せたほうが早い。
// ただし、これは画面の見本であって実際の回答ではない。
// 年代だけを付け、職業は付けない（顔写真の横に職業が並んだ時点で
// 実在の回答者の名簿に見える）。
//
// 全部が「このままでOK」になると、聞く必要が無かったことになる。
// 逆に全部が指摘だと、粗探しの道具に見える。
// どちらもビルド時に止める。

export type CaseSay = {
  /** 年代だけ。職業は付けない */
  age: number;
  verdict: Verdict;
  say: string;
};

/** 返ってくる修正案。感想だけで終わらせない */
export type CaseFix = {
  label: string;
  /** そのまま送れる形。「〜を意識しましょう」ではなく、文そのもの */
  text: string;
  /** どこを、なぜ変えたか */
  why: string[];
};

export type Case = {
  id: string;
  /** 相談の種類 */
  tag: string;
  /** その場面の見出し */
  scene: string;
  /**
   * そこで迷っている選択。問いの形のまま置く。
   *
   * 「メッセージを見てもらう」ではなく「この文面で送る？」。
   * 売っているのは添削ではなく、選ぶ前に確かめられることなので、
   * 場面の頭には必ず選択を置く。
   */
  decision: string;
  /** そのとき頭にあること */
  worry: string;
  /** 何を見てもらうのか */
  what: string;
  /**
   * 相談を出すときに、本人が書いている状況。
   *
   * ══════════════════════════════════════════════════
   * 文面だけ出しても、読むほうは答えられない
   * ══════════════════════════════════════════════════
   * 「明日楽しみにしてる！お店は19時でどう？」だけを見せられても、
   * 返せるのは「自然でいいと思います」までで終わる。
   * それは無料で誰にでも言えることで、払う理由にならない。
   *
   * 実際に来る相談には、そこに至るまでが付いている。
   * どこで知り合って、いま何往復目で、相手がどういう人で、
   * 何を気にしているか。そこまで読むから、返ってくるものが変わる。
   *
   * 見本でも、その形のまま見せる。
   */
  context?: string;
  /** 送るものの見本。名前も職業も住んでいる場所も付けない */
  draft: { label: string; text: string };
  /** 返ってくる言葉の見本 */
  says: CaseSay[];
  /**
   * そのまま使える修正案。
   *
   * 感想だけ返して終わると、次に何をすればいいのか分からないまま終わる。
   * 直した文そのものと、どこをなぜ変えたかまで返す。
   */
  fix?: CaseFix;
  /**
   * 反応を見たあと、この人が決めたこと。
   *
   * こちらが「こうしてください」と書く欄ではない。
   * 材料を見て本人が決める、という形を、見本の中でも崩さない。
   */
  decided: string;
  /** 相談に進むときのカテゴリ */
  category: string;
  /** いま受け付けているか */
  open: boolean;
};

