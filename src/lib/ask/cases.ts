/** 画面に出す相談の種類。受付前のものは混ぜない */
export const OPEN_CASES = CASES.filter((c) => c.open);

/* ── 公開の前に止めること ───────────────────────── */
{
  // 年齢・職業・名前を付けない。付いた時点で体験談になる。
  const PERSON = /\d+歳|エンジニア|営業|コンサル|公務員|経営企画|メーカー|看護師|美容系|事務職|大学生|会社員|さん」|さんの声/;
  for (const c of CASES) {
    for (const t of [c.tag, c.scene, c.decision, c.worry, c.what, c.draft.label, c.draft.text, c.decided]) {
      if (PERSON.test(t)) {
        throw new Error(
          `「${c.id}」に年齢や職業が入っています。利用者はまだ0人なので、体験談は書けません`,
        );
      }
    }
    // 回答の見本にも、職業は付けない（年代は says.age で別に持つ）
    for (const s of c.says) {
      if (PERSON.test(s.say)) {
        throw new Error(`「${c.id}」の回答の見本に、年齢か職業が入っています`);
      }
      if (/\d+\s*%|成功率|確率/.test(s.say)) {
        throw new Error(`「${c.id}」の回答の見本に、根拠のない数字が入っています`);
      }
    }
  }
  if (OPEN_CASES.length < 2) throw new Error("受け付けている相談の種類がありません");

  // 場面の頭は、必ず選択にする。
  // 「メッセージを見てもらう」だと、添削屋の品書きになる。
  for (const c of CASES) {
    if (!c.decision.endsWith("？")) {
      throw new Error(`「${c.id}」の分岐点が問いになっていません（${c.decision}）`);
    }
    if (!c.decided) throw new Error(`「${c.id}」に、決めたことが書かれていません`);
    // 決めるのは本人。こちらが指図する書き方にしない。
    if (/してください|すべき|必ず|正解は/.test(c.decided)) {
      throw new Error(`「${c.id}」の決めたことが、こちらの指図になっています（${c.decided}）`);
    }
    // 文字で答えられない問いを出さない。画像を受け取る口はまだ無い。
    if (c.open && /写真|画像|服|髪|スクショ/.test(c.decision)) {
      throw new Error(`「${c.id}」の分岐点は、文字だけでは答えられません（${c.decision}）`);
    }
  }

  // 恋愛の1か所だけを扱うサービスに見えないこと。
  // 文面だけなら添削屋で、それは「選ぶ前に確かめる」ではない。
  const scenes = new Set(OPEN_CASES.map((c) => c.category));
  if (scenes.size < 4) {
    throw new Error(
      `扱っている場面が${scenes.size}種類しかありません。恋愛の一部だけを扱うサービスに見えます`,
    );
  }

  // ══════════════════════════════════════════════
  // 看板に出す場面は、薄いまま置かない
  // ══════════════════════════════════════════════
  // トップに出るのは OPEN_CASES[0] の1つだけ。
  // ここが「明日楽しみにしてる！」の1行に
  // 「自然でいいと思います」が2つ返るだけだと、
  // 無料で誰にでも言えることを見せていることになる。
  //
  // 看板に出すものには、相談の背景と、そのまま送れる修正案まで持たせる。
  {
    const top = OPEN_CASES[0];
    if (!top.context) {
      throw new Error(
        `看板に出す場面「${top.id}」に、相談の背景がありません（文面だけ見せると、返せるのは当たり障りのない一言だけになります）`,
      );
    }
    if (top.context.length < 80) {
      throw new Error(`看板に出す場面「${top.id}」の背景が短すぎます（${top.context.length}文字）`);
    }
    if (!top.fix) {
      throw new Error(
        `看板に出す場面「${top.id}」に修正案がありません（感想だけ返すと、次に何をすればいいのか分からないまま終わります）`,
      );
    }
    if (top.fix.why.length < 2) {
      throw new Error(`「${top.id}」の修正案に、どこをなぜ変えたかが足りません`);
    }
    /* ── 見本の人数は、売っている人数と同じであること ──────
       ここは3件以上を「要求」していた。
       売っている商品はどれも1人なので、買う前にいちばん
       見られる場所で、来ないものを3つ見せていた。

       見栄えのために増やせないようにする。
       増やしたいなら、商品のほうを増やすこと。 */
    /* 看板は、おすすめの商品と同じ人数であること。
       「売っている人数のどれか」だと、お試し（1人）の人数でも通る。
       トップでいちばん見られる見本が、いちばん軽い商品の絵に
       なってしまうので、おすすめのほうに合わせる。 */
    const featured = PLANS.find((p) => p.featured) ?? PLANS[0];
    if (top.says.length !== featured.answers) {
      throw new Error(
        `看板に出す場面「${top.id}」は回答が ${top.says.length} 人ぶんですが、` +
          `おすすめの「${featured.id}」は ${featured.answers}人です`,
      );
    }
    // 反応が一言で終わっていないこと。
    // 「自然でいいと思います」だけなら、理由が無く、次に活かせない。
    for (const s of top.says) {
      if (s.say.length < 40) {
        throw new Error(
          `「${top.id}」の回答「${s.say}」が短すぎます。なぜそう感じたかまで書いてください`,
        );
      }
    }
    // 修正案が、指示ではなく文そのものであること。
    if (/しましょう|を意識|心がけ|ましょう。/.test(top.fix.text)) {
      throw new Error(
        `「${top.id}」の修正案が指示になっています（そのまま送れる文にしてください）`,
      );
    }
  }

  // 背景と修正案にも、体験談の印を入れない。
  for (const c of CASES) {
    const extra = [c.context ?? "", c.fix?.text ?? "", c.fix?.label ?? "", ...(c.fix?.why ?? [])];
    for (const t of extra) {
      if (PERSON.test(t)) {
        throw new Error(`「${c.id}」の背景か修正案に、年齢や職業が入っています`);
      }
    }
  }

  for (const c of OPEN_CASES) {
    if (!new Set(PLANS.map((p) => p.answers)).has(c.says.length)) {
      throw new Error(`「${c.id}」の回答が ${c.says.length} 人ぶんで、売っている人数と違います`);
    }
  }

  /* ── 3人に戻ったので、場面ごとの判定も戻した ──────────
     1人だったあいだは、場面ごとに判定が1つしか無く、
     「全部OKにしない」と「どこかにOKがある」が
     正面からぶつかるので、置き場所を分けていた。

     3人なら1つの場面の中で両方を満たせる。元に戻す。 */
  for (const c of OPEN_CASES) {
    if (c.says.every((x) => x.verdict === "as_is")) {
      throw new Error(`「${c.id}」の回答が全部「このままでOK」です。払う理由が消えます`);
    }
  }

  /* ── 割れることがあること ──────────────────────
     3人に見せる意味は、同じものでも受け取り方が違うと分かること。
     どの場面でも3人の判定が揃っていると、
     「3人に見せても結局1つの答えが出る」ように見える。
     それなら1人でいい、という話になる。 */
  if (!OPEN_CASES.some((c) => new Set(c.says.map((x) => x.verdict)).size > 1)) {
    throw new Error("どの場面でも3人の判定が揃っています。人数を増やす意味が見えません");
  }
  if (!OPEN_CASES.some((c) => c.says.some((s) => s.verdict === "as_is"))) {
    throw new Error("どの場面にも「このままでOK」がありません。粗探しの道具に見えます");
  }
}
