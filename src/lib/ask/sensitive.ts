import { assertPlain, assertNotScary } from "../voice";
import { NEVER } from "../responder/policy";
import { advisorWord } from "../who";

// 言いにくい相談。
//
// ══════════════════════════════════════════════════
// 何を売っているのか
// ══════════════════════════════════════════════════
// 距離の縮め方、触れ方、付き合う前の関係、性の価値観。
// 友達には聞きづらく、相手本人にはもっと聞きづらい。
// そこを、当事者ではない女性に聞けること。
//
// 売っているのは「答え」ではなく「相手側の受け取り方」。
// ここを外すと、ただの攻略法になる。
//
// ══════════════════════════════════════════════════
// これは成人向けの商売ではない
// ══════════════════════════════════════════════════
// 線はひとつ。
//
//   扱う   相談者と、相談者が気になっている相手との関係
//   扱わない 答える女性本人を、性的な対象にすること
//
// この線が引けていれば、ライブチャットにも疑似恋愛にもならない。
// 引けていなければ、どんな言葉で包んでも同じものになる。
//
// ══════════════════════════════════════════════════
// 答える側が、断れること
// ══════════════════════════════════════════════════
// 全員が受ける必要はない。受けたい人だけが受ける。
// 既定は「受けない」。自分で入れた人にだけ届く。
//
// 既定を「受ける」にして、嫌なら外してもらう形にはしない。
// 外し方を知らないまま届くことになる。
//
// ══════════════════════════════════════════════════
// 値段の理由
// ══════════════════════════════════════════════════
// 「性的な話題だから高い」ではない。
// 受けられる人が限られていて、返す前にこちらが目を通すから。
// 上がったぶんは、答える人の取り分を増やすほうに回す
// （economics.ts の SENSITIVE_YEN）。
// こちらの取り分だけ増やすなら、値段を上げる理由が無い。

/** 言いにくい相談で扱うこと */
export const SCOPE: { id: string; label: string; example: string }[] = [
  {
    id: "distance",
    label: "距離の縮め方",
    example: "この距離感は、女性から見てどう映りますか",
  },
  {
    id: "touch",
    label: "触れ方のタイミング",
    example: "どのくらいの間柄なら、自然だと感じますか",
  },
  {
    id: "before",
    label: "付き合う前の関係",
    example: "付き合う前にここまで踏み込むのは、どう感じますか",
  },
  {
    id: "values",
    label: "性の価値観の話し方",
    example: "この話題を、どう切り出されたら嫌ではないですか",
  },
  {
    id: "reading",
    label: "相手の反応の受け取り方",
    example: "乗り気なのか、合わせているだけなのか、どこで分かりますか",
  },
  {
    id: "tone",
    label: "下心の見え方",
    example: "このLINEは、下心が強く見えますか",
  },
];

/**
 * 相談の形。
 *
 * 主語が「相手」であること。
 * 「自分はどうすればいいか」ではなく
 * 「相手側からはどう見えるか」を聞く形にする。
 * ここが崩れると、正解を教えるサービスになる。
 */
export const ASK_SHAPE = {
  good: "この誘い方は、相手からどう見えますか",
  bad: "どうすれば付き合えますか",
  why: "返ってくるのは正解ではなく、女性が実際にどう受け取ったかです",
};

/**
 * 返ってくるもの。
 *
 * 感想で終わらせない。どこを見るか、急がないほうがいいのはどこか、
 * どう確かめるか、までを返す。
 */
export const RETURNS = [
  `${advisorWord()}から見た印象`,
  "相手の反応で見るところ",
  "急がないほうがいいサイン",
  "自然に確かめる方法",
  "言い方の例",
  "次にやること",
];

/**
 * これは頼めない。
 *
 * 答える女性本人を性的な対象にする行為。
 * 相談の中身ではなく、相手の扱い方の話なので、
 * 例外を作らない。
 */
export const NEVER_ASK = [
  "答える女性本人の身体や性経験について聞くこと",
  "答える女性本人と性的なやりとりをしようとすること",
  "性的な画像や動画を送ること",
  "連絡先やSNSを聞くこと、渡そうとすること",
  "タシカメの外で会おうとすること",
  "答える女性本人の容姿を採点すること",
];

/** 破ったときにどうなるか。曖昧にしない */
export const BREACH = [
  "その場で回答・通話を終わります",
  "そのぶんの返金はありません",
  "以後お使いいただけなくなります",
];

/**
 * 同意してもらう一文。
 *
 * 長い規約を読ませない。守ってほしいのはこれだけ。
 */
export const CONSENT =
  "相談できるのは、あなたと気になっている相手との関係についてです。答える女性本人への性的な言動はできません。";

/**
 * 1回の相談で、5回パスを何回分使うか。
 *
 * 2回分にしているのは、受けられる人が限られていて、
 * 返す前にこちらが目を通すから。
 * その分は、答える人の取り分に回す。
 */
export const PASS_COST = 2;

/** そのカテゴリは、言いにくい相談として扱うか */
export function isSensitive(category: string | null | undefined): boolean {
  return category === "distance";
}

/** そのカテゴリで、パスを何回分使うか */
export function passCost(category: string | null | undefined): number {
  return isSensitive(category) ? PASS_COST : 1;
}

/* ── 公開の前に止めること ─────────────────────────
   ここは、書き方ひとつで別の商売になる場所。
   言葉のほうを機械で見張る。 */
{
  // 攻略の言葉を入れない。1つでも入ったら落とす。
  // 「どうすれば落とせるか」を売った時点で、相手の同意が前提から外れる。
  const CONQUEST =
    /攻略|落と[すしせさそ]|堕と[すしせさそ]|抱く|ヤれ|ヤり|確実にいけ|操る|落ちる女|チョロ|即り|お持ち帰り|その気にさせ|落ちやすい/;
  // 答える女性本人を対象にする言い方を、案内の側に入れない。
  const AT_RESPONDER = /あなたとしたい|あなたの身体|あなたの経験|回答者と楽し/;

  const copy = [
    ...SCOPE.flatMap((s) => [s.label, s.example]),
    ASK_SHAPE.good,
    ASK_SHAPE.why,
    ...RETURNS,
    CONSENT,
  ];

  for (const t of copy) {
    const hit = t.match(CONQUEST);
    if (hit) {
      throw new Error(
        `言いにくい相談の文に「${hit[0]}」が入っています。相手の同意が前提から外れます（${t}）`,
      );
    }
    if (AT_RESPONDER.test(t)) {
      throw new Error(`言いにくい相談の文が、答える女性本人を対象にしています（${t}）`);
    }
    assertPlain(t, "言いにくい相談");
    assertNotScary(t, "言いにくい相談");
  }

  // 相談の形が「相手からどう見えるか」であること。
  // 「どうすれば〜できるか」を良い例にした時点で、正解を売る商売になる。
  if (!/どう(見え|感じ|受け取)/.test(ASK_SHAPE.good)) {
    throw new Error(`相談の形が、相手の受け取り方を聞く形になっていません（${ASK_SHAPE.good}）`);
  }
  if (!/どうすれば|どうしたら/.test(ASK_SHAPE.bad)) {
    throw new Error("悪い例が、正解を求める形になっていません（対比が効きません）");
  }

  // 頼めないことの一覧から、いちばん大事な3つが消えていないこと。
  for (const must of ["本人", "画像", "連絡先"]) {
    if (!NEVER_ASK.some((n) => n.includes(must))) {
      throw new Error(`頼めないことの一覧から「${must}」が消えています`);
    }
  }
  // 破ったときにどうなるかを、必ず書く。
  if (BREACH.length < 3) throw new Error("破ったときにどうなるかが足りません");

  // 同意の一文に、線が両方書かれていること。
  // 「何を相談できるか」と「何はできないか」の両方。
  if (!CONSENT.includes("相手との関係")) {
    throw new Error("同意の一文に、何を相談できるのかが書かれていません");
  }
  if (!CONSENT.includes("性的な言動はできません")) {
    throw new Error("同意の一文に、答える女性本人への線が書かれていません");
  }

  // 返すものが、感想で終わっていないこと。
  if (!RETURNS.some((r) => r.includes("次にやること"))) {
    throw new Error("言いにくい相談の返却に「次にやること」がありません");
  }

  // 使う回数。1回分にすると、受けられる人を限る理由も、
  // 取り分を増やす原資も無くなる。
  if (PASS_COST < 2) throw new Error("言いにくい相談の消費回数が少なすぎます");

  // 答える側の約束に、「受けると決めた人にだけ届く」が残っていること。
  //
  // これはこのファイルの外（responder/policy.ts）の話だが、
  // ここから見ておく。あちらを書き換えただけで既定が変わると、
  // 受けると決めていない人に届く。
  {
    const text = NEVER.map((n) => `${n.what}${n.why}`).join("");
    if (!/受けると決めた/.test(text)) {
      throw new Error(
        "答える側の約束から「受けると決めた人にだけ届く」が消えています（既定で届く形になります）",
      );
    }
    if (!/既定では届きません/.test(text)) {
      throw new Error("答える側の約束から「既定では届きません」が消えています");
    }
  }
}
