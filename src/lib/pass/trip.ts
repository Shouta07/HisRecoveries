import { PAYMENT_RATE, REFUND_RATE, MISC_COST_YEN, AI_COST_YEN, ANSWER_REWARD, MARGIN_FLOOR } from "../cost";

import { anyAskOpen } from "../who";

/* ══════════════════════════════════════════════════
   旅パス
   ══════════════════════════════════════════════════

   ── 月額をやめた ────────────────────────────────
   マチアプ版は月額だった。相手が同時に何人もいて、
   毎月続くものだったから。

   旅は違う。年に1回か2回で、終わりがある。
   月額にすると、旅が終わったあとも払い続けることになって、
   いちばん最初に解約される。

   買う単位を、旅に合わせる。
   出発日を入れた時点で買えて、帰国＋7日で終わる。
   終わるものに終わる値段を付けるほうが、気持ちよく払える。

   ── ガイドブック1冊ぶん ────────────────────────
   ¥1,480。書店のガイドブックが ¥1,500〜2,000。
   初めての一人旅で、その値段は「保険」として迷わず出る額。

   ここを ¥2,980 にすると、比べる相手がガイドブックから
   旅行会社のサポートに変わる。そちらとは戦えない。

   ── 確カメるは、まだ含めない ────────────────────
   ご指示では「3回確カメる」を含む形だった。
   数えたら、床を割る。

     ¥1,480 で確カメる3回  40.7%  ← 床（50%）割れ
     ¥1,480 で確カメる1回  74.5%
     ¥1,480 で確カメる0回  91.4%
     3回を守るなら ¥1,797 以上

   それ以前に、答える人がまだ0人（who.ts の askOpen）。
   マチアプ版は「月3回、実在する異性に確カメられる」と
   書いたまま回答者0人で、買った人が最初に使おうとして
   止まる形になっていた。同じことを繰り返さない。

   都市ごとに人がそろったら、ASK_INCLUDED を1から足していく。
   足した瞬間に、下の判定が採算を見る。 */

export const TRIP_PASS_YEN = 1480;

/** 旅パスに含まれる、確カメるの回数。人がそろうまでは0 */
export const ASK_INCLUDED = anyAskOpen ? 1 : 0;

/** 帰国から何日まで使えるか */
export const PASS_TAIL_DAYS = 7;

/**
 * 年パス。
 *
 * ══════════════════════════════════════════════════
 * 「年3回以上なら得」は、計算が合わない
 * ══════════════════════════════════════════════════
 *   旅パス3回 = ¥4,440  < 年パス ¥4,980   旅パスのほうが安い
 *   旅パス4回 = ¥5,920  > 年パス ¥4,980   ここで初めて得
 *
 * 画面には「年4回以上」と書く。
 * 下の判定が、値段を動かしたときに言い方とずれたら止める。
 *
 * 無理に推さない。年に4回も海外へ一人で行く人は、
 * もうこの製品の対象（初めて〜3回目）ではない。
 */
export const YEAR_PASS_YEN = 4980;

/** 年パスが得になる旅の回数 */
export const YEAR_BREAK_EVEN = Math.floor(YEAR_PASS_YEN / TRIP_PASS_YEN) + 1;

/* ── 無料でできること ─────────────────────────────
   1旅・10記録まで。

   マチアプ版は「2人・10記録」だった。
   1人だと「並ぶ」が体験できないので2人にしていた。

   旅は1つで足りる。1回の旅の中で、準備から帰国まで
   記録がたまっていく体験ができれば、良さは伝わる。
   2旅ぶん無料にすると、年1回の人は一生払わない。 */
export const FREE_TRIPS = 1;
export const FREE_RECORDS = 10;

/** 旅パス1回ぶんの限界利益率 */
export function tripMargin(asks = ASK_INCLUDED): number {
  const v =
    TRIP_PASS_YEN * PAYMENT_RATE +
    TRIP_PASS_YEN * REFUND_RATE +
    MISC_COST_YEN +
    AI_COST_YEN +
    ANSWER_REWARD * asks;
  return (TRIP_PASS_YEN - v) / TRIP_PASS_YEN;
}

/** 確カメるを何回まで含められるか（床を守れる上限） */
export function maxAsksWithinFloor(): number {
  let n = 0;
  while (tripMargin(n + 1) >= MARGIN_FLOOR) n += 1;
  return n;
}

export const INCLUDED: string[] = [
  "その旅の記録は、何件でも",
  "前回の続きから、AIに相談できる",
  "今日やることが分かる",
  "行った結果まで残る",
  ...(ASK_INCLUDED > 0
    ? [`行ったばかりの人に、${ASK_INCLUDED}回確カメる`]
    : []),
];

/* ── 公開の前に止めること ───────────────────────── */
{
  /* ── ガイドブックの値段を超えないこと ────────────
     超えると、比べる相手がガイドブックから
     旅行会社のサポートに変わる。そちらとは戦えない。 */
  if (TRIP_PASS_YEN > 2000) {
    throw new Error(
      `旅パスが ¥${TRIP_PASS_YEN.toLocaleString()} です。` +
        `ガイドブック1冊（¥1,500〜2,000）を超えると、比べる相手が変わります`,
    );
  }

  /* ── 床を割らないこと ────────────────────────── */
  {
    const m = tripMargin();
    if (m < MARGIN_FLOOR) {
      throw new Error(
        `旅パスの限界利益率が ${(m * 100).toFixed(1)}% です（${Math.round(MARGIN_FLOOR * 100)}% 以上）。` +
          `確カメるを含められるのは ${maxAsksWithinFloor()} 回までです`,
      );
    }
  }

  /* ── 売っていないものを、含まれるものに書かないこと ──
     答える人が0人のあいだ、確カメるを「含む」と書かない。
     マチアプ版がここで嘘をついていた。 */
  {
    const says = INCLUDED.some((t) => t.includes("確カメ"));
    if (!anyAskOpen && says) {
      throw new Error("確カメるがまだ開いていないのに、含まれるものに書かれています");
    }
    if (anyAskOpen && ASK_INCLUDED > 0 && !says) {
      throw new Error("確カメるが開いているのに、含まれるものに書かれていません");
    }
  }

  /* 使い放題に読めないこと。
     「記録は何件でも」は旅1回ぶんの話なので、そう書く。 */
  for (const t of INCLUDED) {
    if (/無制限|制限なし|使い放題|いくらでも/.test(t)) {
      throw new Error(`旅パスの説明「${t}」が、使い放題になっています`);
    }
  }

  /* ── 年パスの損益分岐 ──────────────────────────
     旅パスを動かしたときに、画面の「年◯回以上」とずれたら止める。 */
  {
    if (YEAR_PASS_YEN <= TRIP_PASS_YEN) {
      throw new Error("年パスが、旅パス1回より安くなっています");
    }
    const n = YEAR_BREAK_EVEN;
    if (TRIP_PASS_YEN * (n - 1) >= YEAR_PASS_YEN) {
      throw new Error(`年パスの損益分岐が合っていません（旅${n - 1}回で既に年パスのほうが安い）`);
    }
    if (TRIP_PASS_YEN * n <= YEAR_PASS_YEN) {
      throw new Error(`年パスの損益分岐が合っていません（旅${n}回でも年パスのほうが高い）`);
    }
    /* 対象（初めて〜3回目）から外れる売り方にしないこと。
       年2回で得になる値段にすると、慣れた人向けの商品になる。 */
    if (n < 3) {
      throw new Error(`年パスが旅${n}回で得になります。対象は初めて〜3回目の人です`);
    }
  }

  /* ── 無料の範囲 ────────────────────────────────
     1旅で足りる。2旅ぶん無料にすると、年1回の人は一生払わない。 */
  if (FREE_TRIPS !== 1) {
    throw new Error(`無料が ${FREE_TRIPS} 旅です。1旅にしてください（年1回の人が一生払わなくなります）`);
  }
  if (FREE_RECORDS < 5 || FREE_RECORDS > 20) {
    throw new Error(`無料の記録が ${FREE_RECORDS} 件です（5〜20件）`);
  }

  /* 帰国後も、少しは使えること。
     帰国した瞬間に閉じると、「行った結果まで残る」が嘘になる。 */
  if (PASS_TAIL_DAYS < 3) {
    throw new Error(`帰国後 ${PASS_TAIL_DAYS} 日で終わります。行った結果を残す時間がありません`);
  }
}
