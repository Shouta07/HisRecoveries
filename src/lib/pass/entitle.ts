import { advisorWord } from "../who";
import { koiEnabled } from "../koi/gate";
/* ══════════════════════════════════════════════════
   月額に、何がどれだけ含まれるか
   ══════════════════════════════════════════════════

   ── 青天井にしない ──────────────────────────────
   月額 ¥1,980 に「恋亀と話し放題」と「女性3人に確カメる」を
   両方入れると、使われるほど赤字になる。

   内訳（決済手数料3.6%・返金引当3%・雑費を引いたあと）

     全員が毎月「確カメる」を使う
       人件費 ¥750 → 粗利50%を守ると、音声に使えるのは月 ¥100
     半分が使う
       人件費 ¥375 → 音声に使えるのは月 ¥475

   音声は時間で金がかかる。上限が無いと、
   いちばん使う人がいちばん損をさせる形になる。

   ── 使い放題とは書かない ────────────────────────
   書かなければ守れる。書いてから絞ると、嘘になる。
   画面には「月◯分まで」と出す。

   ── 足りなくなったら、止めずに知らせる ────────────
   上限に当たった人を、途中で切らない。
   「今月はここまで」と伝えて、来月から戻る。
   会話の途中で切れるのがいちばん悪い。 */

/* ══════════════════════════════════════════════════
   ¥1,980 → ¥2,980 にした
   ══════════════════════════════════════════════════
   売っているものの芯が変わったため。

   前：恋亀と話せる。確カメるは「使えることもある」
   後：相手ごとの記録が続く恋愛の台帳 ＋ 月1回、必ず異性に確カメる

   確カメるを「付与」にすると、使う人の割合が上がる。
   使用率50%の仮定のままだと、付与した瞬間に採算がずれる。
   下の確認は、全員が使う前提（安全側）に変えてある。

   ── まだ1円も受け取っていないうちに動かす ────────
   Stripe は審査待ちで passEnabled は false。
   売り始めたあとの値上げは、既存の人への説明が要る。
   動かすなら、売る前のいま。 */

/** 月額。Stripe の Price ID は環境変数で持つ（コードに書かない） */
export const PASS_YEN = 2980;

/* ── はじめの100人の値段（¥1,980）を、やめた ──────
   創業メンバー価格も、永久割引も作らない。
   一度下げた値段は、上げるときに必ず揉める。

   先着でやるのは、値段を下げることではなく、中身を足すこと。
   特典は lib/pass/periods.ts が持つ（原価のかかるものは
   長いプランにだけ付ける。短いプランに付けると床を割る）。

   期間と払い方（1 / 3 / 6 / 12か月、一括 / 月払い）も、
   そちらが持っている。ここが持つのは1か月ぶんの値段だけ。 */


/**
 * 月に、確カメられる回数。
 *
 * ══════════════════════════════════════════════════
 * 月1回 × 3人 → 月3回 × 1人 にした
 * ══════════════════════════════════════════════════
 * 迷う場面は、月に1度ではない。
 *   このLINEどう見える？
 *   この誘い方は自然？
 *   デート後のこの空気はどう？
 * 3人に一度に聞くより、3つの場面で1人ずつ聞くほうが使える。
 *
 * 原価は、まったく同じ。
 *   前  1回 × 3人 × ¥250 = ¥750
 *   後  3回 × 1人 × ¥250 = ¥750
 *
 * ── 3人のまま3回にすると、成立しない ──────────
 * 月3回 × 3人 = ¥2,250。実際に計算した。
 *   ¥2,980      限界利益率 16.9%
 *   12か月一括  限界利益率 -21.8%（赤字）
 * 月2回 × 3人 でも ¥2,980 で 42.1%。床（50%）を割る。
 *
 * ¥2,980 で床を守れる人への支払いは月 ¥1,263 まで。
 * ¥250の回答者なら 5回ぶん。3回 × 1人 なら余裕がある。
 *
 * ── 人数を売り文句にしない ────────────────────
 * 「3人が読みます」は、多いほどよく見える売り方。
 * 売っているのは人数ではなく、迷ったときに聞けること。
 * 画面に出すのは回数だけにする。
 */
export const HUMAN_PER_MONTH = 3;

/**
 * 1回に何人へ届くか。
 *
 * 月額は1人。単発の商品（3人に見せる）とは別なので、
 * plans.ts の answers とは混ぜない。
 */
export const PANEL_SIZE = 1;
/** 回答者1人あたりの報酬 */
export const PANEL_REWARD = 250;

/**
 * 月に、恋亀と話せる分数。
 *
 * 2〜5分の会話を想定しているので、50分なら月10〜25回。
 * 「ちょっと話す」を妨げない range に置いてある。
 *
 * 増やすときは、下の確認が採算を見る。
 */
export const VOICE_MINUTES_PER_MONTH = 50;

/**
 * 音声の、1分あたりの見込み原価（円）。
 *
 * ══════════════════════════════════════════════════
 * 調べた（2026-10）。［要確認］は外した
 * ══════════════════════════════════════════════════
 * OpenAI Realtime API の speech-to-speech。
 * 行き帰りを混ぜた1分あたりで、
 *
 *   gpt-realtime-mini   $0.02〜0.05／分
 *   gpt-realtime（フル） $0.05〜0.15／分
 *
 * $1=¥150 として、mini が ¥3〜8、フルが ¥8〜22。
 * 仮に置いていた ¥8 は、mini の高いほうとほぼ同じだった。
 * mini を使う前提で、¥8 のまま据え置く。
 *
 * ── フルに変えるなら、分数も一緒に変えること ──────
 * 下の確認が、限界利益率50%を守っている。
 * 音声に使えるのは月 ¥475 までなので、
 *
 *   mini（¥8/分）  月50分 → 限界利益率 53.8%  通る
 *   フル（¥22/分） 月50分 → 限界利益率 17.2%  止まる
 *   フル（¥22/分） 月21分 → ちょうど50%
 *
 * ［要確認］為替は $1=¥150 の概算。
 * 実際の請求が出たら、1か月ぶんを見てここを直す。
 * トークン単価なので、話し方（相づちの多さ）でも動く。
 */
export const VOICE_COST_PER_MIN = 8;

/**
 * どの音声モデルを前提に、上の原価を置いているか。
 *
 * ここと REALTIME_MODEL（lib/koi/session.ts）がずれると、
 * 採算の計算だけ mini のまま、実際はフルを呼ぶ、が起きる。
 */
export const VOICE_MODEL_ASSUMED = "gpt-realtime-mini";

/**
 * 「確カメる」を実際に使う人の割合。採算を見るときだけ使う。
 *
 * ══════════════════════════════════════════════════
 * 付与したものは、全員が使う前提で見る
 * ══════════════════════════════════════════════════
 * 0.5 を置いていた。「使えることもある」扱いだったころの数字。
 *
 * 月1回を付与にすると、使わない理由が無くなる。
 * 使用率を低く見たまま付与すると、使われた月に赤字になる。
 *
 * 1.0 にして、全員が使っても成り立つ形でだけ上限を決める。
 * 実際に使われない月は、そのぶん余るだけで困らない。
 */
const HUMAN_USE_RATE = 1.0;

/** 守りたい限界利益率 */
export const PASS_MARGIN_FLOOR = 0.5;

export type Used = {
  /** 今月、恋亀と話した分数 */
  voiceMinutes: number;
  /** 今月、女性3人へ確カメた回数 */
  humanRequests: number;
};

export type Allowance = {
  voiceLeft: number;
  humanLeft: number;
  voiceOver: boolean;
  humanOver: boolean;
};

export function allowance(used: Used): Allowance {
  const voiceLeft = Math.max(0, VOICE_MINUTES_PER_MONTH - used.voiceMinutes);
  const humanLeft = Math.max(0, HUMAN_PER_MONTH - used.humanRequests);
  return {
    voiceLeft,
    humanLeft,
    voiceOver: voiceLeft === 0,
    humanOver: humanLeft === 0,
  };
}

/** 上限に当たった人に出す言葉。止めるのではなく、知らせる */
export const VOICE_OVER =
  "今月は、ここまでにしとこか。来月また話そ。";
export const HUMAN_OVER =
  "今月のぶんは、もう使ってるみたい。来月からまた聞けるで。";

/** 月額に含まれるもの。画面に出す言葉 */
/* 含まれるもの。
   開いていないものを書かない。
   音声は鍵が入っているときだけ出す（閉じているのに
   「月50分まで」と書くと、申し込めないものを売ることになる）。 */
export const INCLUDED: string[] = [
  "相手ごとに、話したことが残る",
  "前回の続きから、AIに相談できる",
  "今日やることが分かる",
  /* ── 2つ足した ──────────────────────────────────
     「複数人でも散らからない」
       これが買う理由そのもの。1人なら頭で足りる。
       3人4人が同時に進むと足りなくなる。
     「行動した結果まで残る」
       相談だけが並んでいると、相談サービスに見える。
       送った・会った・どうだったか、まで残るのがこちら。 */
  "複数人でも散らからない",
  "行動した結果まで残る",
  ...(koiEnabled ? [`恋亀と声で話す（月${VOICE_MINUTES_PER_MONTH}分まで）`] : []),
  `月${HUMAN_PER_MONTH}回、実在する${advisorWord()}に確カメる`,
];

/* ── 公開の前に止めること ───────────────────────── */
{
  /* 採算が合っていること。
     上限を上げるのは簡単だが、上げた瞬間に赤字になることがある。
     上げたらここで止まる。 */
  const fee = Math.round(PASS_YEN * 0.036);
  const refund = Math.round(PASS_YEN * 0.03);
  const misc = 10;
  const human = PANEL_SIZE * PANEL_REWARD * HUMAN_USE_RATE * HUMAN_PER_MONTH;

  /* ══════════════════════════════════════════════
     音声は、開いているときだけ原価に乗る
     ══════════════════════════════════════════════
     会話は ChatGPT でしてもらう形にした。
     本人が自分の ChatGPT で話し、会話をこちらに貼る。
     こちらが払うのは、整理のAIを1回呼ぶぶんだけ。

     声を自前でつなぐ道（/koi の音声）は、鍵が入っているときだけ開く。
     そのときだけ、月50分ぶんを原価に乗せる。

     これを「常に乗る」としていたころ、
     はじめの100人の値段（¥1,980）が 34.8% で床を割っていた。
     実際には音声を開いていないので、割っていなかった。 */
  const voice = koiEnabled ? VOICE_MINUTES_PER_MONTH * VOICE_COST_PER_MIN : 0;
  /* 整理のAI。会話1回ぶんを数回。声に比べると桁が違うので、
     細かく置かずに丸めてある（misc とは別に見えるようにしておく）。 */
  const ai = 20;
  const variable = fee + refund + misc + human + voice + ai;

  /* 両方の値段で見る。
     安いほうだけが床を割る、が起きる。 */
  for (const [name, yen] of [["月額", PASS_YEN]] as const) {
    const m = (yen - variable) / yen;
    if (m < PASS_MARGIN_FLOOR) {
      throw new Error(
        `${name}の月額（¥${yen}）の限界利益率が ${(m * 100).toFixed(1)}% です（${Math.round(
          PASS_MARGIN_FLOOR * 100,
        )}% 以上）。` +
          (voice ? `音声の上限 ${VOICE_MINUTES_PER_MONTH}分（¥${voice}）か、` : "") +
          `確カメるの回数（¥${Math.round(human)}）を見直してください`,
      );
    }
  }
  const margin = (PASS_YEN - variable) / PASS_YEN;
  if (margin < PASS_MARGIN_FLOOR) throw new Error("採算の計算が壊れています");

  // 使い放題と書かないこと。書かなければ守れる。
  for (const t of [...INCLUDED, VOICE_OVER, HUMAN_OVER]) {
    if (/使い放題|無制限|制限なし|いくらでも/.test(t)) {
      throw new Error(`月額の説明「${t}」が、使い放題になっています`);
    }
  }

  // 上限があることを、含まれるものの中に書くこと。
  // 書いていないと、当たったときに「聞いてない」になる。
  /* 分数は、音声が開いているときだけ書くこと。
     閉じているのに「月50分まで」と書くと、
     申し込めないものを売っていることになる。
     開いているのに書かないと、当たったときに「聞いてない」になる。 */
  {
    const written = INCLUDED.some((t) => t.includes(`${VOICE_MINUTES_PER_MONTH}分`));
    if (koiEnabled && !written) {
      throw new Error("声で話せるのに、月額の説明に分数が書かれていません");
    }
    if (!koiEnabled && written) {
      throw new Error("声で話せないのに、月額の説明に分数が書かれています");
    }
  }
  if (!INCLUDED.some((t) => t.includes(`月${HUMAN_PER_MONTH}回`))) {
    throw new Error("月額の説明に、確カメる回数が書かれていません");
  }

  // 上限に当たったときの言葉が、切る言い方になっていないこと。
  for (const t of [VOICE_OVER, HUMAN_OVER]) {
    if (/できません|停止|エラー|利用不可/.test(t)) {
      throw new Error(`上限の言葉「${t}」が、切る言い方になっています`);
    }
    // 来月戻ることを伝えること。終わったように見せない。
    if (!/来月/.test(t)) {
      throw new Error(`上限の言葉「${t}」に、来月戻ることが書かれていません`);
    }
  }

  // 数えかたが合っていること。
  {
    const a = allowance({ voiceMinutes: 10, humanRequests: 0 });
    if (a.voiceLeft !== VOICE_MINUTES_PER_MONTH - 10) throw new Error("残りの分数が合いません");
    if (a.humanLeft !== HUMAN_PER_MONTH) throw new Error("残りの回数が合いません");
    if (a.voiceOver || a.humanOver) throw new Error("まだ残っているのに、上限に当たっています");
  }
  {
    const a = allowance({ voiceMinutes: 999, humanRequests: 9 });
    if (a.voiceLeft !== 0 || a.humanLeft !== 0) throw new Error("残りが負になっています");
    if (!a.voiceOver || !a.humanOver) throw new Error("使い切ったのに、上限に当たっていません");
  }

  // 「確カメる」が、月額に含まれていること。
  if (HUMAN_PER_MONTH < 1) throw new Error("確カメるが、月額に含まれていません");

  /* ── 人数を固定していた判定を、採算で見る形に変えた ──
     ここは PANEL_SIZE !== 3 で止めていた。
     月1回×3人だったころの数字を、そのまま固定していた。

     月3回×1人に変えたとき、原価は同じ（どちらも ¥750）なのに
     ここだけが止まった。守りたいのは人数ではなく採算。

     人数 × 回数 × 報酬 が、床を守れる範囲に収まっているかを見る。
     下の採算の確認が本番で、ここは早く気づくための前置き。 */
  {
    const human = PANEL_SIZE * PANEL_REWARD * HUMAN_PER_MONTH;
    const budget = PASS_YEN * (1 - PASS_MARGIN_FLOOR) - (PASS_YEN * 0.066 + 30);
    if (human > budget) {
      throw new Error(
        `人に払うのが月 ¥${human}（${PANEL_SIZE}人 × ${HUMAN_PER_MONTH}回）で、` +
          `床を守れる上限 ¥${Math.round(budget)} を超えています`,
      );
    }
  }
  if (PANEL_SIZE < 1) {
    throw new Error(`確カメる人数が ${PANEL_SIZE} 人です`);
  }
}
