/* ══════════════════════════════════════════════════
   運営者が行ったことのある国・地域
   ══════════════════════════════════════════════════

   ── 事実として使えるのは、国・地域の名前だけ ────
   確認できているのは「行ったことがある」ところまで。

   都市、訪問時期、旅行回数、一人旅だったかどうか、
   資格、語学力は、いずれも未確認。

   だから、ここには国・地域の名前しか持たない。
   持たないものは、画面にも出ない。
   書こうとしたら、下の判定が止める。

   ── 「詳しい」と言わない ────────────────────────
   行ったことがあることと、詳しいことは別。
   15か国のどこかに行ったからといって、
   その国の全域や最新の事情を知っているわけではない。

   名乗るのは「実体験を話せる、身近な旅経験者」まで。
   専門家でも、現地在住者でも、プロガイドでもない。

   ── 対応できるかは、買う前に確かめる ────────────
   行ったことがある国でも、相談の中身によっては
   答えられない。だから一覧は「ここなら必ず答えられる」
   の一覧ではなく、「まず聞いてみる目安」として出す。 */

export const BEEN: string[] = [
  "韓国",
  "台湾",
  "香港",
  "マカオ",
  "ベトナム",
  "マレーシア",
  "フィリピン",
  "オーストラリア",
  "アメリカ",
  "イギリス",
  "フランス",
  "インド",
  "ケニア",
  "エジプト",
  "タイ",
];

/** 名乗り方。ここから外れた言い方を、判定が止める */
export const STANCE =
  "実際に行ったことのある、身近な旅経験者です。旅行の専門家でも、現地在住者でも、ガイドでもありません。";

/** 一覧の下に必ず置く断り */
export const BEEN_NOTE =
  "行ったことがある国・地域です。その国のすべてに詳しいわけではありません。相談の中身によってはお答えできないので、買う前に都市・日程・相談したいことを教えてください。";

/* ── 公開の前に止めること ───────────────────────── */
{
  if (BEEN.length !== 15) {
    throw new Error(
      `行った国・地域が ${BEEN.length} 個です（確認できているのは15）。` +
        `増やすときは、本当に行ったところだけにしてください`,
    );
  }
  if (new Set(BEEN).size !== BEEN.length) throw new Error("国・地域が重なっています");

  /* ── 国・地域の名前だけであること ──────────────
     都市名・年・回数が混ざると、確認できていないことを
     書いたことになる。 */
  for (const b of BEEN) {
    if (/\d/.test(b)) {
      throw new Error(`「${b}」に数字が入っています。時期や回数は確認できていません`);
    }
    if (b.length > 8) {
      throw new Error(`「${b}」が長すぎます。国・地域の名前だけにしてください`);
    }
    /* 空白・区切りで、何かを足していないこと。
       「韓国 ソウル」は、長さでも語でも引っかからずに通ってしまった。
       国・地域の名前に、区切りは入らない。 */
    if (/[\s　・,、/／(（]/.test(b)) {
      throw new Error(
        `「${b}」に区切りが入っています。足せるのは国・地域の名前だけです（都市・時期・回数は未確認）`,
      );
    }
    for (const w of ["市", "州", "島の", "回", "年", "度目", "在住", "滞在"]) {
      if (b.includes(w)) {
        throw new Error(`「${b}」に「${w}」が入っています。確認できているのは国・地域の名前だけです`);
      }
    }
  }

  /* ── 詳しい、と言わないこと ────────────────────
     行ったことと、詳しいことは別。 */
  for (const [t, where] of [[STANCE, "名乗り"], [BEEN_NOTE, "一覧の断り"]] as const) {
    for (const w of ["精通", "詳しい人", "熟知", "全域", "最新事情", "専門家です", "プロ", "ガイドです"]) {
      if (t.includes(w)) {
        throw new Error(`${where} に「${w}」が入っています。行ったことがある、までが事実です`);
      }
    }
  }
  /* 名乗りが、何でないかを言っていること。
     ここが抜けると、読む人は勝手に専門家だと思う。 */
  for (const w of ["専門家", "在住", "ガイド"]) {
    if (!STANCE.includes(w)) {
      throw new Error(`名乗りに「${w}ではない」ことが書かれていません`);
    }
  }
  /* 断りが、3つとも言っていること。 */
  for (const [re, what] of [
    [/すべてに詳しいわけでは|全部に詳しいわけでは/, "全部に詳しいわけではないこと"],
    [/お答えできない/, "答えられないことがあること"],
    [/買う前|申し込む前|先に/, "買う前に確かめること"],
  ] as const) {
    if (!re.test(BEEN_NOTE)) throw new Error(`一覧の断りに、${what}が書かれていません`);
  }

  /* ── 人数を、多く見せないこと ──────────────────
     対応するのは運営者1人。
     「専門家が待機」のような書き方にしない。 */
  for (const w of ["たち", "チーム", "スタッフ", "待機", "複数の"]) {
    if (STANCE.includes(w)) {
      throw new Error(`名乗りに「${w}」が入っています。対応するのは1人です`);
    }
  }
}
