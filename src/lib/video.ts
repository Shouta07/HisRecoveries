// トップに置く30秒の動画（YouTube ショート）。
//
// ══════════════════════════════════════════════════
// 置き方
// ══════════════════════════════════════════════════
// YouTube にショートを上げたら、URL の最後の部分を id に入れる。
//   https://youtube.com/shorts/AbCdEfGhIjk  →  id: "AbCdEfGhIjk"
// id が空のあいだは、節ごと出さない。
// 押しても何も起きない枠を先に置くのが、いちばん悪い。
//
// ══════════════════════════════════════════════════
// 開いた時点では YouTube を読まない
// ══════════════════════════════════════════════════
// 埋め込みをそのまま置くと、見ない人にも YouTube の読み込みと
// Cookie が付く。このサイトは Web フォントさえ積んでいない。
// 表紙はこちらの画像で出し、押されたときにだけ youtube-nocookie を開く。
//
// ══════════════════════════════════════════════════
// 字幕を足さない
// ══════════════════════════════════════════════════
// 動画の中の大きな文字が、読み上げと1字違わず字幕を兼ねている。
// YouTube 側で字幕ファイルを上げたり自動字幕を出したりすると、
// 同じ言葉が二重に出る。cc_load_policy=0 で既定は出さない。

export const SHORT = {
  /** YouTube の動画ID。空なら出さない */
  id: "",
  /** 読み上げ用。iframe の title にも使う */
  title: "30秒で分かる、タシカメ",
  /** 押す前に出す表紙。動画の1コマ目 */
  poster: "/img/short-cover.jpg",
};

/* ── 公開の前に止めること ───────────────────────── */
{
  if (SHORT.id && !/^[A-Za-z0-9_-]{11}$/.test(SHORT.id)) {
    throw new Error(
      `動画のIDが YouTube の形ではありません（${SHORT.id}）。URL の最後の11文字だけを入れてください`,
    );
  }
  if (!SHORT.poster.startsWith("/img/")) {
    throw new Error("動画の表紙は public/img/ の下に置いてください");
  }
}
