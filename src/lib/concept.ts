/* ── 公開の前に止めること ───────────────────────── */
{
  /* ── 構想のあいだ、売る口を開けないこと ────────────
     ここが開くと、無いものを売ることになる。 */
  if (STATUS !== "concept") {
    throw new Error(
      "STATUS が concept ではなくなっています。" +
        "売る口を開けるなら、実際に提供できるもの（宿・機材・提携）を先に用意してください",
    );
  }

  /* 売り文句の側。ここに円が出たら、商品として読まれる */
  const offer = [
    DEFINITION, HERO_A, HERO_B, HERO_LEAD, STATUS_LINE, TALK_LEAD,
    END_USER.who, END_USER.detail, BUYER.who, BUYER.detail, PROBLEM, SOLUTION,
    MARKET.city, MARKET.first, MARKET.why, ...MARKET.areas, MVP.line, MVP.note,
    ICP.owner, ...NOT_FOR,
    ...JOURNEY.flatMap((s) => [s.when, s.title, s.point, ...s.body]),
    ...NOT_THIS.flatMap((n) => [n.no, n.but]),
    ...NOT_BUILT,
    ...TALK_TO.flatMap((t) => [t.who, t.why]),
    ...LOOP.flatMap((l) => [l.en, l.ja]),
  ].join("\n");
  const all = offer + "\n" + ICP.lines.join("\n");

  /* ── 値段を、どこにも書かないこと ──────────────────
     構想に値段が付いた瞬間、商品として読まれる。
     数字そのものではなく、通貨の記号と単位を見る。 */
  for (const re of [/[0-9][0-9,.]*\s*万?\s*円/, /¥\s*[0-9]/, /JPY/i, /[0-9]+\s*ドル/]) {
    if (re.test(offer)) {
      throw new Error(
        `構想の面に値段が書かれています（${offer.match(re)?.[0]}）。` +
          `まだ売れるものがありません`,
      );
    }
  }
  /* ── ICP の円は、宿の単価だと分かる形でだけ許す ────
     「1.5万〜4万円」が単独で出ると、こちらの料金に見える。
     同じ文に「1泊」か「単価」が無ければ止める。 */
  for (const l of ICP.lines) {
    if (/円/.test(l) && !/1泊|単価|ADR/.test(l)) {
      throw new Error(
        `ICP の「${l}」に円が入っていますが、宿の単価だと分かる言葉（1泊・単価）がありません`,
      );
    }
  }

  /* ── 申し込みの言葉を、使わないこと ────────────────
     「予約」は流れの説明に出てくる（宿を予約する）ので、
     そこは通す。禁じるのは、こちらへの申し込みを促す形。 */
  for (const w of ["お申し込み", "申し込む", "今すぐ", "ご購入", "購入する", "カートに"]) {
    if (all.includes(w)) {
      throw new Error(`構想の面に「${w}」が入っています。まだ売っていません`);
    }
  }

  /* ── 無いものを、無いと書いていること ──────────────
     この面でいちばん効く判定。 */
  if (NOT_BUILT.length < 3) {
    throw new Error(
      `まだ無いものの一覧が ${NOT_BUILT.length} 件です。` +
        `構想として出す以上、何が無いかを書いてください`,
    );
  }
  if (!/まだ提供していません|まだ.*ありません/.test(STATUS_LINE)) {
    throw new Error(`上に出す1行が、まだ提供していないことを言っていません（${STATUS_LINE}）`);
  }
  /* 「宿」と「機材」が無いことは、必ず書く。
     この2つが無いなら、体験そのものが1つも起きない。 */
  for (const [re, what] of [
    [/提携している宿|宿は、まだ/, "提携している宿が無いこと"],
    [/機材/, "客室の機材が無いこと"],
  ] as [RegExp, string][]) {
    if (!NOT_BUILT.some((t) => re.test(t))) {
      throw new Error(`まだ無いものの一覧に、${what}が書かれていません`);
    }
  }

  /* ── 持っていない実績を、書かないこと ────────────── */
  for (const w of ["導入実績", "導入店舗", "提携ホテル", "採用されて", "利用者数", "満足度", "お客様の声"]) {
    if (all.includes(w)) {
      throw new Error(`構想の面に「${w}」が入っています。まだ何も動いていません`);
    }
  }

  /* ── 一日の流れが、途切れていないこと ──────────────
     8段で1周する。抜けると、宿に戻るところが浮く。 */
  JOURNEY.forEach((s, i) => {
    if (s.n !== i + 1) throw new Error(`流れの番号がずれています（${s.n} が ${i + 1} 番目）`);
    if (s.body.length === 0) throw new Error(`流れの ${s.n} に中身がありません`);
    if (!s.point) throw new Error(`流れの ${s.n} に、ねらいが書かれていません`);
  });
  if (JOURNEY.length !== 8) {
    throw new Error(`一日の流れが ${JOURNEY.length} 段です（旅の前からチェックアウトまでで8段）`);
  }
  /* 宿に戻る段が、いちばんの山であること。
     ここが抜けると、ただの観光アプリになる。 */
  if (!JOURNEY.some((s) => /部屋が、今日の旅を覚えている/.test(s.title))) {
    throw new Error("流れに、部屋がその日を組み直す段がありません。そこがこの構想の芯です");
  }

  /* ── ひとめぐりが、閉じていること ────────────────── */
  if (LOOP.length !== 7) throw new Error(`ひとめぐりが ${LOOP.length} 歩です（7歩）`);
  if (!/また/.test(LOOP[LOOP.length - 1].ja)) {
    throw new Error("ひとめぐりの最後が、次につながっていません");
  }

  /* ── 不安で売らないこと ──────────────────────────── */
  for (const w of ["危険", "危ない", "万が一", "一人では無理", "後悔しない"]) {
    if (all.includes(w)) {
      throw new Error(`構想の面に「${w}」が入っています。怖がらせて売らないでください`);
    }
  }

  /* ── 市場が、1つに絞れていること ──────────────────
     「全国のホテル」に戻ると、最初の1件が作れない。 */
  if (!MARKET.city || !MARKET.first) throw new Error("最初の市場が書かれていません");
  if (!MARKET.areas.includes(MARKET.first.split("・")[0])) {
    throw new Error(`最初の検証エリア「${MARKET.first}」が、候補の街に入っていません`);
  }
  if (!/1エリア.*1宿.*1室/.test(MVP.line)) {
    throw new Error(`最初に作るものの大きさが、1エリア×1宿×1室の形になっていません（${MVP.line}）`);
  }
  /* 誰のためか、両側が書かれていること。
     片方だけだと、旅行者向けアプリか、ホテルの設備に見える。 */
  if (!END_USER.who || !BUYER.who) throw new Error("旅行者側か、宿側か、どちらかが空です");
  if (!/宿泊/.test(BUYER.who)) throw new Error("宿側の相手に「宿泊」が入っていません");
  if (!/旅行者/.test(END_USER.who)) throw new Error("旅行者側の相手に「旅行者」が入っていません");
  if (NOT_FOR.length < 3) throw new Error("最初に声をかけない相手が、書かれていません");

  /* ── 話したい相手が、書かれていること ──────────────
     売る口を置かない代わりに、ここが入口になる。
     空にすると、読んだ人の行き先が無くなる。 */
  if (TALK_TO.length < 2) {
    throw new Error("話したい相手が書かれていません。売る口が無いぶん、ここが入口になります");
  }
}
