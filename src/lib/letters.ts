import { STOP_AFTER_QUIET } from "./nudge";

// お便りの約束。
//
// ── なぜ「送らないもの」を先に決めるか ─────────────────
// 公式アカウントの通知は、たいてい送る側の都合で増える。
// 開封率が落ちれば頻度を上げ、反応が鈍れば煽りを強くする。
// その結果、登録した人にとっては「通知が邪魔なもの」になり、
// ブロックされて終わる。
//
// ここで売りにできるのは、中身の豪華さではなく、静かさのほうだと考えている。
// ただし「うるさくしません」は言うだけならタダなので、
// 上限の数と、止める条件を、先に数字で決めて公開する。
//
// ── 数字を1か所に置く ────────────────────────────
// 止める回数は nudge.ts の判定と同じ定数を使う。
// 表示と判定で別々に持つと、片方だけ変えたときに
// 「書いてあることが嘘になる」形で壊れる。

