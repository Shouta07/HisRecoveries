/**
 * 受付番号。
 * 本人を特定しないが、本人だけが知っている文字列になる。
 * 読み上げや書き写しで壊れにくい文字だけを使う（0/O、1/I を除く）。
 */
const ALPHABET = "23456789ABCDEFGHJKLMNPQRSTUVWXYZ";

export function makeTicket(rand: () => number): string {
  let out = "";
  for (let i = 0; i < 8; i++) out += ALPHABET[Math.floor(rand() * ALPHABET.length)];
  return `${out.slice(0, 4)}-${out.slice(4)}`;
}

/** 受付番号の形が正しいか（問い合わせを受けたときの照合用） */
export function isTicket(s: string): boolean {
  return /^[23456789ABCDEFGHJKLMNPQRSTUVWXYZ]{4}-[23456789ABCDEFGHJKLMNPQRSTUVWXYZ]{4}$/.test(s);
}
