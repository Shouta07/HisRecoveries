// 取材の受け皿。
//
// ── なぜ街頭ではなくここか ─────────────────────────
// この領域は「人前で言わないから検索されている」。
// 街で聞けるのは、人前で話せる人だけになる。
// いちばん書きたい相手——誰にも言えないまま夜中に調べている人——は、
// 声をかけられても答えない。集めた数だけ、ずれに気づきにくくなる。
//
// 代わりに、いちばん自己開示の敷居が下がる瞬間に置く。
// 診断を5問終えて、自分の順番が出て、
// 「いまはやらなくていい」と言われた直後。
// 答える人が当事者であることが、経路として保証される。
//
// ── 先に約束を出す ──────────────────────────────
// 健康・身体のことを聞く以上、これは要配慮個人情報にあたる。
// 同意は最後のチェックボックスではなく、
// 「何を聞くか」「何を載せるか」「何を載せないか」「どう取り消すか」を
// 先に全部出したうえで取る。順番を逆にしない。
//
// ── 受付番号 ────────────────────────────────
// 名前も連絡先も必須にしないので、あとから「あれを消してほしい」と
// 言うための手がかりが要る。送信時に受付番号を出して、
// それだけで取り消せるようにする。
// 本人を特定せずに、本人の権利だけを残す形。

/**
 * 聞くこと。
 *
 * ── 直したこと ──────────────────────────────
 * 最初に置いた4問は、よくある取材の型だった（きっかけ／試したこと／
 * 困っていること／言えないこと）。読み返して、3つ問題があった。
 *
 * ① このサイトが検証したいことを、1つも聞いていなかった。
 *    売っているのは「順番」で、診断はその順番を出す。
 *    だったら最初に聞くべきは「その順番は合っていましたか」のはず。
 *    答える人は直前にそれを見ているので、いちばん答えやすくもある。
 *
 * ② 例示が答えを誘導していた。
 *    「（写真を見たとき、人に言われたとき、など）」と書くと、
 *    ほとんどの人がそのどちらかを選んで書く。
 *    ばらつきが消えると、質的に聞く意味がなくなる。例示を外した。
 *
 * ③「試したことと、やめたこと」を1問で聞いていた。
 *    2つ聞くと、答えやすいほう（試したこと）だけが返る。
 *    ほしいのは、やめたほう。だから分けた。
 *
 * ④「誰にも言っていないことがあれば」を落とした。
 *    いちばん重いものを差し出させておいて、
 *    「引用することがあります」と続くのは、こちらの都合が良すぎる。
 *    答える側の負担に対して、返せるものが釣り合っていない。
 *
 * ── 並び ────────────────────────────────
 * 答えやすい順に置く。上から埋めていって、疲れたところでやめられる。
 * 必須は1問目だけ。
 */
export const QUESTIONS: { id: string; q: string; hint: string; required: boolean }[] = [
  {
    id: "order_fit",
    q: "出てきた順番は、いまの実感と合っていましたか",
    hint: "違っていたら、そのほうが助かります。自分ならどれが先だと思うか、まで書けそうなら",
    required: true,
  },
  {
    id: "moment",
    q: "気になり始めたのは、どんなときでしたか",
    hint: "その場面のことを、覚えている範囲で",
    required: false,
  },
  {
    id: "quit",
    q: "始めたけれど、やめたことはありますか",
    hint: "やめた理由まで書けると、いちばん助かります。続かなかった話ほど、どこにも書かれていません",
    required: false,
  },
  {
    id: "wasted",
    q: "お金を使って、いま思えば要らなかったものはありますか",
    hint: "金額は書かなくて構いません。何にいくら、が書ければそのまま使わせてください",
    required: false,
  },
  {
    id: "stuck",
    q: "いま、いちばん決められずにいることは何ですか",
    hint: "費用、順番、どこに行けばいいか、そもそも必要かどうか——何でも",
    required: false,
  },
];

/** 載せるもの */
export const WILL_PUBLISH: string[] = [
  // もとは「要約せずにそのまま引く（言い回しを整えることはありません）」だけ書いていた。
  // 一方で下では「特定できる細かい事情は落とします」と言っていて、
  // 落とすなら手を入れているので、両方は成り立たない。
  // 何を触って何を触らないかを、分けて書く。
  "書いてもらった内容を、そのまま引くことがあります。言い回しを整えたり、要約したりはしません",
  "ただし個人が特定できそうな部分は、その一文ごと落とします（言い換えて残すことはしません）",
  "何人がどう答えたか、という数の整理",
  "その結果、サイトの順番をどう書き換えたか（更新記録に残します）",
];

