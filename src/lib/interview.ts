/** 同意の版。文面を変えたら上げる。古い版で得た同意を新しい約束に使わない */
export const CONSENT_VERSION = "2026-08-04";

assertNoPromoWords([...WILL_PUBLISH, ...WONT_PUBLISH, ...CONSENT_POINTS], "取材の約束");

if (QUESTIONS.filter((q) => q.required).length > 1) {
  throw new Error("必須の設問は1つまで。増やすほど、答える人が途中でやめます");
}

// 設問は増やしたくなる。1問足すたびに、最後まで書く人は減る。
// 足すときは、代わりに1問落とすかどうかを考える場所をここに作っておく。
if (QUESTIONS.length > 5) {
  throw new Error("設問は5問まで。足すなら、どれかを落としてください");
}

// 例示は答えを誘導する。「（Aのとき、Bのとき、など）」と書くと、
// ほとんどの人がAかBを選んで書き、ばらつきが消える。
for (const q of QUESTIONS) {
  if (/（[^）]*、[^）]*など）/.test(q.hint)) {
    throw new Error(`設問「${q.id}」のヒントが答えを例示しています（回答が例に寄ります）`);
  }
}

/**
 * 受付番号。
 * 本人を特定しないが、本人だけが知っている文字列になる。
 * 読み上げや書き写しで壊れにくい文字だけを使う（0/O、1/I を除く）。
 */
const ALPHABET = "23456789ABCDEFGHJKLMNPQRSTUVWXYZ";

export function makeTicket(rand: () => number): string {
  let out = "";
  for (let i = 0; i < 8; i++) out += ALPHABET[Math.floor(rand() * ALPHABET.length)];
  return `${out.slice(0, 4)}-${out.slice(4)}`;
}

/** 受付番号の形が正しいか（問い合わせを受けたときの照合用） */
export function isTicket(s: string): boolean {
  return /^[23456789ABCDEFGHJKLMNPQRSTUVWXYZ]{4}-[23456789ABCDEFGHJKLMNPQRSTUVWXYZ]{4}$/.test(s);
}
