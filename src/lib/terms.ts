// ══════════════════════════════════════════════════
// なぜ、いま作るか
// ══════════════════════════════════════════════════
// 無かった。特商法の表記（/legal）と、
// 安全のページ（/safety）と、個人情報（/privacy）はあったが、
// 「誰と誰のあいだに、どんな契約が成立するのか」を
// 書いた文書が、どこにも無かった。
//
// これが無いと、いちばん大事なことが決まらない。
//   お金を受け取るのは誰か
//   届けなかったときに責任を負うのは誰か
//   答えた女性は、売主なのか
//
// ══════════════════════════════════════════════════
// 売主は当社。女性ではない
// ══════════════════════════════════════════════════
// この製品は、女性が自分の商品を出して売る場所ではない。
//
//   買う人 → 当社（バイタリティデザイン合同会社）に代金を払う
//   当社   → タシカメという相談サービスとして届ける
//   当社   → 提供の一部を、業務委託した女性に依頼する
//   当社   → 女性へ、当社から報酬を払う
//
// 買う人と女性のあいだに、売買は無い。
// 女性は値段を決めないし、買う人から直接お金を受け取らない。
//
// ここを曖昧に書くと、実態は当社が売っているのに
// 文書の上では女性が売主に見える、という食い違いが起きる。
// 決済（Stripe）にも、その食い違いのまま説明することになる。
//
// ══════════════════════════════════════════════════
// 女性の反応を、こちらで作らない
// ══════════════════════════════════════════════════
// AIがやるのは、相談の整理・要約・論点の並べ替え・読みやすくすること。
// 「女性がどう感じたか」は、女性が書いたものしか出さない。
// ここを混ぜたら、この製品は何も売っていないことになる。
//
// ══════════════════════════════════════════════════
// 読める長さにする
// ══════════════════════════════════════════════════
// 読まれない規約は、無いのと同じ。
// 条ごとに、まず1行で何の話かを書く。

