/* ── 公開の前に止めること ───────────────────────── */
{
  ARTICLES.forEach((a, i) => {
    if (a.n !== i + 1) throw new Error(`規約の条番号がずれています（第${a.n}条が${i + 1}番目）`);
    if (a.body.length === 0) throw new Error(`第${a.n}条（${a.title}）に本文がありません`);
    if (!a.lead) throw new Error(`第${a.n}条（${a.title}）に1行の説明がありません`);
  });

  const bodies = ARTICLES.flatMap((a) => a.body).join("\n") + TERMS_INTRO.join("\n");
  const all = ARTICLES.flatMap((a) => [a.title, a.lead, ...a.body]).join("\n") + bodies;

  if (!bodies.includes(CO)) {
    throw new Error("規約の本文に、運営している会社名が書かれていません");
  }

  /* ── 構想であることが、本文に書いてあること ────────
     この規約でいちばん大事。
     lead は見出しなので、本文で言い切っていることを見る。 */
  for (const [re, why] of [
    [/当社が検討している構想です/, "掲載内容が構想であること"],
    [/提供しておらず/, "いま提供していないこと"],
    [/契約は成立しません/, "閲覧で契約が成立しないこと"],
    [/販売しておらず/, "販売していないこと"],
    [/実在する設備または役務を表すものではありません/, "実在の設備を表さないこと"],
  ] as [RegExp, string][]) {
    if (!re.test(bodies)) throw new Error(`規約の本文に、${why}が書かれていません`);
  }

  /* ── 連絡の扱いが、書いてあること ──────────────────
     宿や自治体から、未公開の情報を含む連絡が来る。
     扱いを先に書いていないと、受け取れない。 */
  for (const [re, why] of [
    [/公開されていない情報/, "未公開の情報を含む連絡の扱い"],
    [/第三者に開示せず/, "第三者へ開示しないこと"],
    [/特定できる形で公開しません/, "連絡元を特定できる形で公開しないこと"],
  ] as [RegExp, string][]) {
    if (!re.test(bodies)) throw new Error(`規約の本文に、${why}が書かれていません`);
  }

  /* ── 売っていた頃の条文が、残っていないこと ──────── */
  for (const w of [
    "代金", "お申し込み時", "クーリング・オフ", "返金", "自動更新",
    "対象期間", "回答者", "音声通話", "オンライン相談", "LINE",
  ]) {
    if (all.includes(w)) {
      throw new Error(`規約に「${w}」が残っています。いま売っているものはありません`);
    }
  }

  /* ── 値段が、入っていないこと ────────────────────── */
  for (const re of [/[0-9][0-9,]*\s*円/, /¥\s*[0-9]/]) {
    if (re.test(all)) throw new Error(`規約に金額が書かれています（${all.match(re)?.[0]}）`);
  }

  /* ══════════════════════════════════════════════
     売り始めたら、ここで止まる
     ══════════════════════════════════════════════
     この規約は、売っていないことを前提に書いてある。
     商品が決まったら、足すのではなく書き直すこと
     （契約の成立・代金・提供時期・解除の条件が要る）。 */
  if (canCharge()) {
    throw new Error(
      "売れる形になっていますが、この規約は売っていないことを前提に書かれています。" +
        "契約の規約を書き直してください",
    );
  }
}
