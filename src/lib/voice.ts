// このサービスが名乗る言葉。
//
// ══════════════════════════════════════════════════
// 1つだけにする
// ══════════════════════════════════════════════════
// 前の版は、トップだけで4つ名乗っていた。
//   男性の恋愛を、みんなでサポート
//   送る前に、女性の本音を。
//   これ、今送っていい？
//   相談じゃない。実際の女性が答える。
//
// どれも悪くない。ただ4つあること自体が曖昧さになる。
// 読んだ人は「で、これは何のサービス？」を自分で組み立てることになる。
//
// 残したのは「これ、今送っていい？」。
// 理由は、これだけが運営の説明ではなく、使う人自身の言葉だから。
//
// ══════════════════════════════════════════════════
// 説明は名乗りではない
// ══════════════════════════════════════════════════
// 「答えるのは実際の女性です」は説明。名乗りの位置には置かない。
// 名乗りの位置（ロゴの下・ヒーローの上・最後のCTA）には
// ONE_LINER しか置かない。

export const ONE_LINER = "これ、今送っていい？";

/** 名乗りの下に1行だけ添えてよい説明 */
export const SUB = "迷ったら、相手に近い人へ聞く。";

/**
 * 引退させた名乗り。
 * 良い文なので、うっかり戻ってきやすい。ビルドで弾く。
 */
export const RETIRED = [
  "男性の恋愛を、みんなでサポート",
  "送る前に、女性の本音を。",
  "相談じゃない。実際の女性が答える。",
  "本番の前に、人で確かめる。",
  "決める前に、人で確かめる。",
  "相手に近い人に、聞く",
];

/**
 * 名乗りの位置に置いてよいかを確かめる。
 * 画面のコピーを組み立てるときに通す。
 */
export function assertOneLiner(text: string): string {
  const hit = RETIRED.find((r) => text.includes(r));
  if (hit) {
    throw new Error(
      `名乗りに引退した文「${hit}」が入っています。名乗りは ONE_LINER だけにしてください`,
    );
  }
  return text;
}

/* ── 公開の前に止めること ───────────────────────── */
{
  if (!ONE_LINER) throw new Error("名乗りが空です");
  if (RETIRED.includes(ONE_LINER)) throw new Error("引退した文を名乗りにしています");
  // 名乗りが長いと、名乗りとして機能しない。
  if (ONE_LINER.length > 16) throw new Error(`名乗りが長すぎます（${ONE_LINER.length}文字）`);
  // 添える説明も1行に収まること。
  if (SUB.length > 24) throw new Error(`説明が長すぎます（${SUB.length}文字）`);
  assertOneLiner(ONE_LINER);
  assertOneLiner(SUB);

  // 引退した文が、フッターや肩書きに戻ってこないようにする。
  // 「著作権表示だから」「ロゴの下だから」で1つ増えると、
  // そこからまた4つに戻る。名乗る場所は h1 だけ。
  for (const r of RETIRED) {
    if (r === ONE_LINER) throw new Error("引退した文を名乗りにしています");
  }
}
