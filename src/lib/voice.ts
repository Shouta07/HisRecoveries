/**
 * 回答する側を指しているのに、中立な言葉で濁していないか。
 *
 * 買う人の画面では「女性」と書く。
 * 「審査を通った5人」「相手に近い5人」「実在の人」だけでは、
 * 誰が読むのか分からない。分からないものに値段は付かない。
 */
export function assertWhoReads(text: string, where: string): string {
  const VAGUE = [
    "審査を通った5人",
    "審査を通った人",
    "審査を通った方",
    "相手に近い5人",
    "相手に近い人",
    "実在の人",
    "実在する人",
  ];
  const hit = VAGUE.find((v) => text.includes(v));
  if (hit && !text.includes(advisorWord()) && !text.includes("異性")) {
    throw new Error(
      `${where} の「${hit}」が誰を指すのか分かりません。買う人の画面では「女性」と書いてください`,
    );
  }
  return text;
}

