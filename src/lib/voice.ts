/**
 * やらないこと。画面にそのまま並べる。
 *
 * ══════════════════════════════════════════════════
 * ここに置く理由
 * ══════════════════════════════════════════════════
 * 「格安情報まとめ」は、やらないことを言うための正しい文。
 * ただし画面に直書きすると、安さの言葉を探している判定
 * （scripts/check-copy.mjs）が捕まえる。
 * 文が否定なのか肯定なのかは、機械には見分けられない。
 *
 * このファイルは判定から外してある（禁止語の一覧そのものなので）。
 * だから、やらないことの一覧もここが持つ。
 * 画面は並べるだけにする。
 *
 * 一覧が NEVER と食い違わないように、下の判定で突き合わせる。
 */
export const NOT_OURS = [
  "旅仲間マッチング",
  "現地手配・ガイド",
  "出会い",
  "航空券・宿の予約",
  "格安情報まとめ",
];

export function assertNever(text: string, where: string): string {
  const hit = NEVER.find((n) => text.includes(n));
  if (hit) {
    throw new Error(
      `${where} に「${hit}」が入っています。` +
        `旅の何でも屋にはしません（マッチング・手配・出会い・予約・格安情報はやりません）`,
    );
  }
  return text;
}

/**
 * 硬い言葉。
 *
 * 読むのは28歳の会社員で、いま有休を取って初めて一人で海外へ行く人。
 * 電車の中か、寝る前のベッドで開いている。
 * その人が友達に話すときに使わない言葉を、画面に置かない。
 */
export const STIFF: { bad: string; good: string }[] = [
  { bad: "渡航", good: "行く" },
  { bad: "滞在先", good: "泊まるところ" },
  { bad: "所持金", good: "持っているお金" },
  { bad: "移動手段を確保", good: "行き方を決める" },
  { bad: "事前準備", good: "出発前にやること" },
  { bad: "現地情報", good: "行った人が見たこと" },
  { bad: "トラブル対応", good: "困ったときにどうするか" },
  { bad: "所要時間", good: "どのくらいかかるか" },
  { bad: "留意点", good: "気をつけるところ" },
  { bad: "推奨します", good: "こうする人が多いです" },
];

/** 買う人の画面に、硬い言葉が混ざっていないか */
export function assertPlain(text: string, where: string): string {
  const hit = STIFF.find((x) => text.includes(x.bad));
  if (hit) {
    throw new Error(
      `${where} に「${hit.bad}」が入っています。読むのは28歳の会社員です（「${hit.good}」と書いてください）`,
    );
  }
  return text;
}

/** 買う人に見せる文として、軽すぎないかを確かめる */
export function assertWeight(text: string, where: string): string {
  const TOO_LIGHT = ["気軽", "手軽", "サクッ", "ちょっと聞", "誰でも", "なんとなく"];
  const hit = TOO_LIGHT.find((t) => text.includes(t));
  if (hit) {
    throw new Error(
      `${where} に「${hit}」が入っています。買う人の画面では、値段を否定する言葉を使わないでください`,
    );
  }
  return text;
}

