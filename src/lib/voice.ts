/** 怖がらせて売っていないか */
export function assertNotScary(text: string, where: string): string {
  const hit = SCARE.find((c) => text.includes(c));
  if (hit) {
    throw new Error(
      `${where} に「${hit}」が入っています。怖がらせて売らないでください（渡すのは決めるための材料で、決めないと大変だという脅しではありません）`,
    );
  }
  return text;
}

