/** 買う人の画面に、硬い言葉が混ざっていないか */
export function assertPlain(text: string, where: string): string {
  const hit = STIFF.find((x) => text.includes(x.bad));
  if (hit) {
    throw new Error(
      `${where} に「${hit.bad}」が入っています。読むのは28歳の会社員です（「${hit.good}」と書いてください）`,
    );
  }
  return text;
}

/** 買う人に見せる文として、軽すぎないかを確かめる */
export function assertWeight(text: string, where: string): string {
  const TOO_LIGHT = ["気軽", "手軽", "サクッ", "ちょっと聞", "誰でも", "なんとなく"];
  const hit = TOO_LIGHT.find((t) => text.includes(t));
  if (hit) {
    throw new Error(
      `${where} に「${hit}」が入っています。買う人の画面では、値段を否定する言葉を使わないでください`,
    );
  }
  return text;
}

