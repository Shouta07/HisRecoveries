// タシカメが名乗る言葉。
//
// ══════════════════════════════════════════════════
// 名前
// ══════════════════════════════════════════════════
// 「His Recoveries」をやめた。
//
// Recovery は「回復」。回復すべき何かがある、と言っている。
// この製品を使う人は壊れていない。送る直前のふつうの人で、
// 名前がその人に「君には治すところがある」と言うのは、
// 商品の立ち位置と正反対だった。
//
// 複数形の Recoveries は、旧サイトの6領域（髪・肌・体・心…）から来ている。
// その6領域はもう商品にない。
//
// そして「ヒズリカバリーズ」は8モーラで、口で言えない。
// 友達に勧められない名前は、それだけで広がらない。
//
// タシカメは4モーラ。言える。意味が通る。
// 「それ、タシカメた？」が、そのまま動詞になる。
//
// His Recoveries は運営の事業名として残す（会社・記事・旧サービス）。
//
// ══════════════════════════════════════════════════
// 誰が読むのかを、濁さない
// ══════════════════════════════════════════════════
// 「人」「実在の人」「審査を通った方」と書くと、中立で上品に見える。
// しかし売っているものがぼやける。
//
// この製品が渡しているのは「人の目」ではない。
//   相手本人には聞けない
//   友達の女性は、あなたを知っているから気を使う
//   AIは女性ではない
// だから「相手と同じ側に立つ、あなたを知らない女性の目」を渡している。
// それ以外のものでは代わりにならない。
//
// 「人」と書いた瞬間、誰でもよくなる。誰でもよければ値段は付かない。
// 回答する側を指すときは、必ず女性と書く。
//
// （回答する側に向けた画面は別。あちらでは「あなた」と呼ぶ。
//   自分の属性を商品として読まされるのは、気持ちのいいことではない。）
//
// ══════════════════════════════════════════════════
// 「聞く」をやめて「通す」にした
// ══════════════════════════════════════════════════
// 「5人に聞く」は、無料のアンケートと同じ形をしている。
// 同じ形のものに 2,980円 を付けると、高く見えるのは当たり前だった。
//
// 主語を変える。自分が聞くのではなく、相手側に読まれる。
//   聞く   自分 → 相手      軽い。答えてもらう
//   通す   相手 → 自分      重い。読まれる。本番の予行になる
//
// 結婚相談所で、お見合いの前にプロフィールを見てもらうのは軽くない。
// あれと同じ工程を売っている。

export const NAME = "タシカメ";

/** 運営の事業名。会社・記事・旧サービス側に残す */
export const OPERATOR = "His Recoveries";

export const ONE_LINER = "失敗する前に、相談できる。";

/** 名乗りの下に1行だけ添えてよい説明 */
export const SUB = "送る前のLINE、アプリの自己紹介文。実在の女性の反応が返ります。";

/**
 * 引退させた名乗り。
 * 良い文なので、うっかり戻ってきやすい。ビルドで弾く。
 */
export const RETIRED = [
  "男性の恋愛を、みんなでサポート",
  "送る前に、女性の本音を。",
  "相談じゃない。実際の女性が答える。",
  "本番の前に、人で確かめる。",
  "決める前に、人で確かめる。",
  "相手に近い人に、聞く",
  "これ、今送っていい？",
];

/**
 * 入口の言葉は「相談」でよい。
 *
 * 「評価される」「診断される」は、押す前に身構える。
 * 「ちょっと相談する」のほうが、手が伸びる。
 *
 * ただし、売っているものは相談ではない。
 *   入口の言葉  相談
 *   買う理由    失敗したくない
 *   渡すもの    実在の女性の、一次反応
 *   体験        本番前のテスト
 *
 * だから「相談できます」で止めない。
 * その隣に、何が返ってくるかを必ず書く。
 */
export const ENTRY_WORD = "相談";

/**
 * 買う人の画面に出してはいけない言葉。
 *
 * ── なぜ ──────────────────────────────────────────
 * 「気軽」「手軽」「サクッと」「2分で」は、
 * それ自体が値段を否定する。軽いものに 2,980円 は払えない。
 *
 * 「ふつうの人が答えます」も同じ。
 * 誰でも答えられるなら、その回答に値段は付かない。
 * 実際には審査を通った人だけが答えているのだから、そう書く。
 *
 * 「空いた2分で180円」は、答える人を集めるための言葉。
 * 買う人の画面に出すと「2分の作業に2,980円」に見える。
 * 同じ事実でも、向ける相手を間違えると価値が消える。
 */
export const TOO_LIGHT = [
  "気軽", "手軽", "サクッ", "ちょっと聞", "カジュアル", "お手軽",
  "ふつうの人", "専門家ではありません", "誰でも",
  "空いた2分", "2分で180", "スキマ時間",
  "とりあえず聞", "なんとなく",
];

/**
 * 回答する側を指しているのに、中立な言葉で濁していないか。
 *
 * 買う人の画面では「女性」と書く。
 * 「審査を通った5人」「相手に近い5人」「実在の人」だけでは、
 * 誰が読むのか分からない。分からないものに値段は付かない。
 */
export function assertWhoReads(text: string, where: string): string {
  const VAGUE = [
    "審査を通った5人",
    "審査を通った人",
    "審査を通った方",
    "相手に近い5人",
    "相手に近い人",
    "実在の人",
    "実在する人",
  ];
  const hit = VAGUE.find((v) => text.includes(v));
  if (hit && !text.includes("女性")) {
    throw new Error(
      `${where} の「${hit}」が誰を指すのか分かりません。買う人の画面では「女性」と書いてください`,
    );
  }
  return text;
}

/**
 * この製品が絶対に名乗らないもの。
 *
 * 恋愛攻略・モテ塾・女性心理の解読。
 * 売っているのは「モテる方法」ではなく、
 * 大事な相手とのチャンスを、自分の判断ミスで失わないこと。
 *
 * 根拠の無い数字も同じ。「成功率」「失敗確率」は数えられない。
 * 数えられるのは「5人中3人」だけ。
 */
export const NEVER = [
  "モテる", "モテ塾", "攻略", "落とす", "落とし方", "ナンパ",
  "女心", "女性心理を", "女性のすべて", "女性はみんな", "女性全体",
  "成功率", "失敗確率", "必ず成功", "絶対に成功",
  "完全に理解", "誰でもできる", "これさえ",
];

export function assertNever(text: string, where: string): string {
  const hit = NEVER.find((n) => text.includes(n));
  if (hit) {
    throw new Error(
      `${where} に「${hit}」が入っています。この製品は、モテる方法でも女性心理の解読でもありません`,
    );
  }
  return text;
}

/**
 * 硬い言葉。
 *
 * ══════════════════════════════════════════════════
 * 誰が読むのかを思い出す
 * ══════════════════════════════════════════════════
 * 読むのは29歳の会社員で、いまLINEの下書きを前に止まっている人。
 * 電車の中か、寝る前のベッドの中で開いている。
 *
 * その人が友達に話すときに使わない言葉を、画面に置かない。
 *   一次反応      → 実際にどう思ったか
 *   所見          → 感想
 *   模擬電話      → 電話の練習
 *   回答する女性  → 答えてくれる女性
 *   依頼を送る    → お願いする
 *   〜の箇所      → 〜のところ
 *   局面          → 場面
 *   経路          → 仕組み
 *   総意          → みんながそう思う
 *
 * 硬い言葉は、書いている側には正確に見える。
 * 読む側には「自分向けじゃない」に見える。
 */
export const STIFF: { bad: string; good: string }[] = [
  { bad: "一次反応", good: "実際にどう思ったか" },
  { bad: "所見", good: "感想" },
  { bad: "模擬電話", good: "電話の練習" },
  { bad: "模擬チャット", good: "メッセージの練習" },
  { bad: "回答する女性", good: "答えてくれる女性" },
  { bad: "回答者", good: "答えてくれる女性" },
  { bad: "依頼をお送り", good: "お願い" },
  { bad: "箇所", good: "ところ" },
  { bad: "局面", good: "場面" },
  { bad: "経路", good: "仕組み" },
  { bad: "総意", good: "みんながそう思う" },
  { bad: "機会損失", good: "損をする" },
  { bad: "判断ミス", good: "選び間違い" },
  { bad: "所要時間", good: "どのくらいで返るか" },
  { bad: "事前確認", good: "送る前に見てもらう" },
  { bad: "総点検", good: "まとめて見てもらう" },
  { bad: "預ける", good: "出す" },
  { bad: "粗探し", good: "悪いところ探し" },
];

/** 買う人の画面に、硬い言葉が混ざっていないか */
export function assertPlain(text: string, where: string): string {
  const hit = STIFF.find((x) => text.includes(x.bad));
  if (hit) {
    throw new Error(
      `${where} に「${hit.bad}」が入っています。読むのは29歳の会社員です（「${hit.good}」と書いてください）`,
    );
  }
  return text;
}

/** 名乗りの位置に置いてよいかを確かめる */
export function assertOneLiner(text: string): string {
  const hit = RETIRED.find((r) => text.includes(r));
  if (hit) {
    throw new Error(
      `名乗りに引退した文「${hit}」が入っています。名乗りは ONE_LINER だけにしてください`,
    );
  }
  return text;
}

/** 買う人に見せる文として、軽すぎないかを確かめる */
export function assertWeight(text: string, where: string): string {
  const hit = TOO_LIGHT.find((t) => text.includes(t));
  if (hit) {
    throw new Error(
      `${where} に「${hit}」が入っています。買う人の画面では、値段を否定する言葉を使わないでください`,
    );
  }
  return text;
}

/* ── 公開の前に止めること ───────────────────────── */
{
  if (!NAME) throw new Error("名前が空です");
  if (NAME.length > 6) throw new Error(`名前が長すぎます（${NAME.length}文字）`);
  if (!ONE_LINER) throw new Error("名乗りが空です");
  if (ONE_LINER.length > 16) throw new Error(`名乗りが長すぎます（${ONE_LINER.length}文字）`);
  if (SUB.length > 40) throw new Error(`説明が長すぎます（${SUB.length}文字）`);
  if (RETIRED.includes(ONE_LINER)) throw new Error("引退した文を名乗りにしています");

  assertOneLiner(ONE_LINER);
  assertOneLiner(SUB);
  assertWeight(ONE_LINER, "名乗り");
  assertWeight(SUB, "名乗りの説明");
  assertWhoReads(SUB, "名乗りの説明");
  assertNever(ONE_LINER, "名乗り");
  assertNever(SUB, "名乗りの説明");
  assertPlain(ONE_LINER, "名乗り");
  assertPlain(SUB, "名乗りの説明");

  // 言い換え先が、言い換え元を含んでいないこと（直したつもりで直っていない）
  for (const x of STIFF) {
    if (x.good.includes(x.bad)) {
      throw new Error(`「${x.bad}」の言い換えが、同じ言葉を含んでいます`);
    }
  }

  // 説明の中で、誰が読むのかが言えていること。
  if (!SUB.includes("女性")) {
    throw new Error("名乗りの説明に、誰が読むのかが書かれていません");
  }

  // 入口の言葉に「相談」を使うのは構わない。
  // ただし、名乗りが「相談できます」だけで終わらないこと。
  // 何のための相談なのかが無いと、無料の相談所と同じ形になる。
  if (/^相談/.test(ONE_LINER) || (ONE_LINER as string) === `${ENTRY_WORD}できる。`) {
    throw new Error("名乗りが相談だけで終わっています（何のための相談かを書いてください）");
  }
  // 説明のほうに、何が返ってくるかが書かれていること。
  if (!/反応|通す|確認/.test(SUB)) {
    throw new Error("名乗りの説明に、何が返ってくるかが書かれていません");
  }
}
