// タシカメが名乗る言葉。
//
// ══════════════════════════════════════════════════
// 名前
// ══════════════════════════════════════════════════
// 「His Recoveries」をやめた。
//
// Recovery は「回復」。回復すべき何かがある、と言っている。
// この製品を使う人は壊れていない。送る直前のふつうの人で、
// 名前がその人に「君には治すところがある」と言うのは、
// 商品の立ち位置と正反対だった。
//
// 複数形の Recoveries は、旧サイトの6領域（髪・肌・体・心…）から来ている。
// その6領域はもう商品にない。
//
// そして「ヒズリカバリーズ」は8モーラで、口で言えない。
// 友達に勧められない名前は、それだけで広がらない。
//
// タシカメは4モーラ。言える。意味が通る。
// 「それ、タシカメた？」が、そのまま動詞になる。
//
// His Recoveries は運営の事業名として残す（会社・記事・旧サービス）。
//
// ══════════════════════════════════════════════════
// 誰が読むのかを、濁さない
// ══════════════════════════════════════════════════
// 「人」「実在の人」「審査を通った方」と書くと、中立で上品に見える。
// しかし売っているものがぼやける。
//
// この製品が渡しているのは「人の目」ではない。
//   相手本人には聞けない
//   友達の女性は、あなたを知っているから気を使う
//   AIは女性ではない
// だから「相手と同じ側に立つ、あなたを知らない女性の目」を渡している。
// それ以外のものでは代わりにならない。
//
// 「人」と書いた瞬間、誰でもよくなる。誰でもよければ値段は付かない。
// 回答する側を指すときは、必ず女性と書く。
//
// （回答する側に向けた画面は別。あちらでは「あなた」と呼ぶ。
//   自分の属性を商品として読まされるのは、気持ちのいいことではない。）
//
// ══════════════════════════════════════════════════
// 「聞く」をやめて「通す」にした
// ══════════════════════════════════════════════════
// 「5人に聞く」は、無料のアンケートと同じ形をしている。
// 同じ形のものに 2,980円 を付けると、高く見えるのは当たり前だった。
//
// 主語を変える。自分が聞くのではなく、相手側に読まれる。
//   聞く   自分 → 相手      軽い。答えてもらう
//   通す   相手 → 自分      重い。読まれる。本番の予行になる
//
// 結婚相談所で、お見合いの前にプロフィールを見てもらうのは軽くない。
// あれと同じ工程を売っている。

export const NAME = "タシカメ";

/** 運営の事業名。会社・記事・旧サービス側に残す */
export const OPERATOR = "His Recoveries";

export const ONE_LINER = "勘で、出さない。";

/** 名乗りの下に1行だけ添えてよい説明 */
export const SUB = "送る前に、相手に近い女性5人の目を通す。";

/**
 * 引退させた名乗り。
 * 良い文なので、うっかり戻ってきやすい。ビルドで弾く。
 */
export const RETIRED = [
  "男性の恋愛を、みんなでサポート",
  "送る前に、女性の本音を。",
  "相談じゃない。実際の女性が答える。",
  "本番の前に、人で確かめる。",
  "決める前に、人で確かめる。",
  "相手に近い人に、聞く",
  "これ、今送っていい？",
];

/**
 * 買う人の画面に出してはいけない言葉。
 *
 * ── なぜ ──────────────────────────────────────────
 * 「気軽」「手軽」「サクッと」「2分で」は、
 * それ自体が値段を否定する。軽いものに 2,980円 は払えない。
 *
 * 「ふつうの人が答えます」も同じ。
 * 誰でも答えられるなら、その回答に値段は付かない。
 * 実際には審査を通った人だけが答えているのだから、そう書く。
 *
 * 「空いた2分で180円」は、答える人を集めるための言葉。
 * 買う人の画面に出すと「2分の作業に2,980円」に見える。
 * 同じ事実でも、向ける相手を間違えると価値が消える。
 */
export const TOO_LIGHT = [
  "気軽", "手軽", "サクッ", "ちょっと聞", "カジュアル", "お手軽",
  "ふつうの人", "専門家ではありません", "誰でも",
  "空いた2分", "2分で180", "スキマ時間",
  "とりあえず聞", "なんとなく",
];

/**
 * 回答する側を指しているのに、中立な言葉で濁していないか。
 *
 * 買う人の画面では「女性」と書く。
 * 「審査を通った5人」「相手に近い5人」「実在の人」だけでは、
 * 誰が読むのか分からない。分からないものに値段は付かない。
 */
export function assertWhoReads(text: string, where: string): string {
  const VAGUE = [
    "審査を通った5人",
    "審査を通った人",
    "審査を通った方",
    "相手に近い5人",
    "相手に近い人",
    "実在の人",
    "実在する人",
  ];
  const hit = VAGUE.find((v) => text.includes(v));
  if (hit && !text.includes("女性")) {
    throw new Error(
      `${where} の「${hit}」が誰を指すのか分かりません。買う人の画面では「女性」と書いてください`,
    );
  }
  return text;
}

/** 名乗りの位置に置いてよいかを確かめる */
export function assertOneLiner(text: string): string {
  const hit = RETIRED.find((r) => text.includes(r));
  if (hit) {
    throw new Error(
      `名乗りに引退した文「${hit}」が入っています。名乗りは ONE_LINER だけにしてください`,
    );
  }
  return text;
}

/** 買う人に見せる文として、軽すぎないかを確かめる */
export function assertWeight(text: string, where: string): string {
  const hit = TOO_LIGHT.find((t) => text.includes(t));
  if (hit) {
    throw new Error(
      `${where} に「${hit}」が入っています。買う人の画面では、値段を否定する言葉を使わないでください`,
    );
  }
  return text;
}

/* ── 公開の前に止めること ───────────────────────── */
{
  if (!NAME) throw new Error("名前が空です");
  if (NAME.length > 6) throw new Error(`名前が長すぎます（${NAME.length}文字）`);
  if (!ONE_LINER) throw new Error("名乗りが空です");
  if (ONE_LINER.length > 16) throw new Error(`名乗りが長すぎます（${ONE_LINER.length}文字）`);
  if (SUB.length > 26) throw new Error(`説明が長すぎます（${SUB.length}文字）`);
  if (RETIRED.includes(ONE_LINER)) throw new Error("引退した文を名乗りにしています");

  assertOneLiner(ONE_LINER);
  assertOneLiner(SUB);
  assertWeight(ONE_LINER, "名乗り");
  assertWeight(SUB, "名乗りの説明");
  assertWhoReads(SUB, "名乗りの説明");

  // 説明の中で、誰が読むのかが言えていること。
  if (!SUB.includes("女性")) {
    throw new Error("名乗りの説明に、誰が読むのかが書かれていません");
  }

  // 名乗りが「聞く」で終わっていないこと。
  // 聞くと書いた瞬間に、無料のアンケートと同じ形になる。
  if (/聞く$|聞ける$/.test(ONE_LINER)) {
    throw new Error("名乗りが「聞く」で終わっています（通す・確かめる、で書いてください）");
  }
}
