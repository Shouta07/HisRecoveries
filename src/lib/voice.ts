/**
 * 怖がらせて売らない。
 *
 * ══════════════════════════════════════════════════
 * 旅では、ここがいちばん危ない
 * ══════════════════════════════════════════════════
 * 「知らないと危険」「ぼったくられます」「最悪の場合」は、
 * 書けばその日の1件は売れる。
 *
 * ただし、それで買った人に残るのは安心だけ。
 * 良いものが届いても「危なかった」で終わり、次には来ない。
 *
 * そして一人旅は、ただでさえ家族に反対される。
 * こちらが不安を煽ると、行くのをやめる方向に押すことになる。
 * この製品が渡したいのは、その反対側。
 *
 * ── 事実は書いてよい ────────────────────────────
 * 「スクンビットは夜も人通りがある」は、行った人が見たこと。
 * 止めるのは、こちらが結末を断定する書き方のほう。
 */
export const SCARE = [
  "危険です", "危ないです", "必ずトラブル", "絶対にやめ",
  "取り返しがつか", "手遅れ", "最悪の場合", "命に関わ",
  "騙されます", "ぼったくられます", "狙われています",
  "知らないと損", "日本人は狙われ",
];

/** 怖がらせて売っていないか */
export function assertNotScary(text: string, where: string): string {
  const hit = SCARE.find((c) => text.includes(c));
  if (hit) {
    throw new Error(
      `${where} に「${hit}」が入っています。怖がらせて売らないでください` +
        `（渡すのは決めるための材料で、行くのをやめさせるためのものではありません）`,
    );
  }
  return text;
}

/** 安さを売りにしていないか */
export function assertNotCheap(text: string, where: string): string {
  const hit = CHEAP.find((c) => text.includes(c));
  if (hit) {
    throw new Error(
      `${where} に「${hit}」が入っています。安さで売らないでください` +
        `（原価は答える人への支払いで、値段を下げるとそこを下げることになります）`,
    );
  }
  return text;
}

/**
 * 答える側を指しているのに、中立な言葉で濁していないか。
 *
 * 「経験者」「詳しい人」だけでは、誰が答えるのか分からない。
 * 分からないものに値段は付かない。
 *
 * ── 求める言い方が、前の仕組みのものだった ──────
 * ここは「行ったばかりの人」と書いてあるかを見ていた（who.ts）。
 * 同じ都市へ90日以内に行った人を集めて答えてもらう版の言い方。
 *
 * いまは当社の担当者が答える。
 * 言えるのは「実際にその地へ行ったことがある」まで。
 * 時期（ばかり）は確認できていないので、求めてはいけない。
 */
export function assertWhoReads(text: string, where: string): string {
  const VAGUE = ["経験者", "詳しい人", "旅のプロ", "現地在住", "ガイド"];
  const hit = VAGUE.find((v) => text.includes(v));
  if (hit && !/行ったことのある|行ったことがある|行った人/.test(text)) {
    throw new Error(
      `${where} の「${hit}」が誰を指すのか分かりません。` +
        `「行ったことのある人」と書いてください（在住者やプロではありません）`,
    );
  }
  return text;
}

