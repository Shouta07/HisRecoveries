// 更新記録。
//
// トップに「順番が変わったら、変わった記録を残します」と書いた。
// 書いた以上、記録が置かれる場所が要る。無いままだと、
// このサイトでいちばん強い約束が、いちばん確かめられない約束になる。
//
// ── 何を載せるか ──────────────────────────────
// 記事の追加や誤字の修正は載せない。載せるのは、
// 読む人が受け取る「判断」が変わったときだけ。
//   順番 … どれを先にやるかが変わった
//   方針 … 何を書く／書かないの線が動いた
//   導線 … どこへ送る／送らないが変わった
//
// ── 書き方 ────────────────────────────────
// 「改善しました」と書かない。前がどうで、いまがどうで、
// なぜ変えたのかを書く。前を消さないのが記録の意味なので、
// before は必ず残す。
//
// ── 日付 ──────────────────────────────────
// 公開した日。git の履歴と一致している。

