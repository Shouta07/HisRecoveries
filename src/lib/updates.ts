/**
 * 新しい順。
 *
 * 同じ日付のときは 0 を返して、UPDATES に書いた順を保つ。
 * ここで -1 を返していたら、同日のものが配列と逆順に並んだ。
 * 1日に何件も動く日があるので、その日のいちばん大きい変更が
 * 下のほうに沈む。並び順は編集の判断なので、機械に崩させない。
 */
export const updatesByNewest = [...UPDATES].sort((a, b) =>
  a.date === b.date ? 0 : a.date < b.date ? 1 : -1,
);

export const LAST_UPDATED = updatesByNewest[0]?.date ?? "";

// 記録が空のまま「記録を残します」と書くことになっていないか。
// 約束の側ではなく、ビルドの側で止める。
if (UPDATES.length === 0) {
  throw new Error("更新記録が空です。トップで「記録を残します」と書いている以上、空では出せません");
}
