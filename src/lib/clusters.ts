export function clustersByArea(areaId: string): ClusterArticle[] {
  return clusters.filter((c) => c.areaId === areaId);
}

export function getCluster(areaId: string, slug: string): ClusterArticle | undefined {
  return clusters.find((c) => c.areaId === areaId && c.slug === slug);
}
