/* ══════════════════════════════════════════════════
   録る前に、両方から同意を取る
   ══════════════════════════════════════════════════

   ── なぜコードで止めるのか ──────────────────────
   プライバシー方針に「双方が、その通話ごとに同意された場合にのみ
   行います」と書いた。書いたからには、書いたとおりに止める。

   運用で気をつける形にすると、急いでいる日に飛ばされる。
   飛ばしたことは、あとから見ても分からない。

   文字起こしを始める前に、必ずここを通す。
   片方でも同意していなければ、始めない。

   ── 断れることが要る ────────────────────────────
   断ったら使えない、にしない。
   同意しなくても通話はできる。できるのは、整理されないだけ。

   断れない同意は、同意ではない。

   ── 通話ごとに取る ──────────────────────────────
   一度同意したら以後ずっと、にしない。
   相手も話す内容も毎回違う。前回の同意を今回に使わない。 */

export type Consent = {
  user: boolean;
  reviewer: boolean;
};

/** 文字起こしを始めてよいか */
export function mayTranscribe(c: Consent): boolean {
  return c.user === true && c.reviewer === true;
}

/** 始められないとき、何が足りないか */
export function whyNotTranscribe(c: Consent): string | null {
  if (mayTranscribe(c)) return null;
  if (!c.user && !c.reviewer) return "お二人とも、まだ同意されていません";
  if (!c.user) return "ご相談者の同意がまだです";
  return "回答者の同意がまだです";
}

/* ══════════════════════════════════════════════════
   同意を取るときに、必ず見せること
   ══════════════════════════════════════════════════
   「同意しますか」とだけ聞いて押させるのは、同意を取ったことにならない。
   何をして、どこへ行き、いつ消えるのかを、押す前に出す。 */

export const CONSENT_TITLE = "この通話を、文字にして整理します";

/* ── 「録らない」ではなく「使わずに消す」と書く ──────
   Workspace の議事録が自動で作られる設定になっている。
   会議ごとに止められるかは、まだ確かめられていない。

   止められない前提で書く。
   止められないのに「同意が無ければ録りません」と書くと、
   守れない約束になる。

   実際にできるのは「作られたものを、使わずに消す」こと。
   意味が違うので、そう書く。ごまかすと、あとで効いてくる。

   会議ごとに止められることが確かめられたら、
   そのときに「作成しません」へ戻す（そちらのほうが強い約束）。 */
export const CONSENT_POINTS: string[] = [
  "話した内容を文字に書き起こし、どこまで進んだか・次にすることを取り出します。",
  "通話の記録は、会議の仕組みによって自動的に作成されます。同意されない場合、作成されたものは使用せず、通話の終了後ただちに削除します。",
  "音声そのものは保存しません。",
  "整理が終わったら、書き起こした文章も消します。",
  "残るのは、整理された内容だけです。あとから見て、消すこともできます。",
  "同意されない場合も、通話はそのまま行えます。整理が行われないだけです。",
];

/** 押す場所の言葉。何に同意するのかが、押す場所に書いてあること */
export const AGREE_LABEL = "文字にすることに同意して進む";
export const DECLINE_LABEL = "同意せずに通話する";

/* ── 公開の前に止めること ───────────────────────── */
{
  // 片方だけでは始めないこと。ここが抜けると、
  // 方針に書いたことと、実際にやることが食い違う。
  if (mayTranscribe({ user: true, reviewer: false })) {
    throw new Error("回答者が同意していないのに、文字起こしが始まります");
  }
  if (mayTranscribe({ user: false, reviewer: true })) {
    throw new Error("相談者が同意していないのに、文字起こしが始まります");
  }
  if (mayTranscribe({ user: false, reviewer: false })) {
    throw new Error("どちらも同意していないのに、文字起こしが始まります");
  }
  if (!mayTranscribe({ user: true, reviewer: true })) {
    throw new Error("両方が同意しても、文字起こしが始まりません");
  }

  // 足りないものが分かること。黙って止まると、原因が追えない。
  if (whyNotTranscribe({ user: true, reviewer: false }) === null) {
    throw new Error("始められない理由が出ていません");
  }

  // 押す前に見せることに、4つが入っていること。
  // ここを削ると、同意を取ったことにならなくなる。
  const all = CONSENT_POINTS.join("");
  const MUST: [RegExp, string][] = [
    [/文字に書き起こ/, "何をするか"],
    [/音声そのものは保存しません/, "音声を残さないこと"],
    [/書き起こした文章も消します/, "書き起こしも消すこと"],
    [/同意されない場合も、通話はそのまま行えます/, "断っても通話できること"],
    // 自動で作られる前提で書いているあいだは、ここを必ず出す。
    // 「録りません」と書いて実際は録られている、が最悪。
    [/使用せず、通話の終了後ただちに削除/, "断ったときに消すこと"],
  ];
  for (const [re, what] of MUST) {
    if (!re.test(all)) throw new Error(`同意の説明に、${what}が書かれていません`);
  }

  // 断る側の選択肢が、ちゃんとあること。
  // 「同意する」しか無い画面は、同意を取る画面ではない。
  if (!DECLINE_LABEL) throw new Error("断る選択肢がありません");
  if (!/同意せずに/.test(DECLINE_LABEL)) {
    throw new Error("断る選択肢が、断ると分かる言葉になっていません");
  }

  // 押す場所に、何に同意するのかが書いてあること。
  // 「同意する」だけのボタンは、何に同意したのか残らない。
  if (!/文字にする/.test(AGREE_LABEL)) {
    throw new Error("同意のボタンに、何に同意するのかが書かれていません");
  }
}
