/** 引用している全 slug（重複除去） */
export function citedSlugs(): string[] {
  const set = new Set<string>();
  for (const s of GUIDE) for (const p of s.parts) for (const c of p.cites) set.add(c.slug);
  return [...set];
}

/**
 * この一本に収録していない記事。
 * 「全部の順番」と言っている以上、漏れは自分で申告する。
 * 記事が増えたら、ここに出てくる。
 */
export function uncited() {
  const cited = new Set(citedSlugs());
  return clusters.filter((a) => !cited.has(a.slug));
}

/** 引用が実在するか。存在しない slug を書いたらビルドを落とす */
export function assertCites() {
  const known = new Set(clusters.map((a) => a.slug));
  const bad = citedSlugs().filter((s) => !known.has(s));
  if (bad.length > 0) {
    throw new Error(`orderGuide: 存在しない記事を引用しています → ${bad.join(", ")}`);
  }
}
