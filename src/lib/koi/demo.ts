import { MIND_READING } from "../ask/model";
import { FIRST_LINE } from "./prompt";
import { advisorWord } from "../who";

/* ══════════════════════════════════════════════════
   トップに出す、恋亀との会話
   ══════════════════════════════════════════════════

   ── 説明より先に、会話を見せる ──────────────────
   「話すだけで整理されます」と書いても、伝わらない。
   実際のやりとりを見せたほうが早い。

   そのあとに、話した結果できたもの（EP）を出す。
   順番は、会話 → できたもの → 次にやること。

   ── 見本であることを隠さない ────────────────────
   実在の誰かのやりとりではない。
   札は、この部品の外（page.tsx）で必ず付ける。

   ── 長くしない ──────────────────────────────────
   6往復まで。読むのに時間がかかると、スクロールで飛ばされる。
   恋亀の返事は2文まで（人格の決まりと同じ）。 */

export type Turn = { who: "koi" | "me"; say: string };

/* 7往復あったものを5往復にした。
   看板で見せたいのは「話すだけで残る」で、会話の面白さではない。
   読むのに時間がかかると、下のEPまで届かない。

   残したのは、EPを作るのに要る4つだけ。
     2回目だった ／ よかった ／ 水族館の提案 ／ 日程はまだ */
export const DEMO_TALK: Turn[] = [
  { who: "koi", say: "Aさん今日2回目やったよね。どうやった？" },
  { who: "me", say: "めっちゃよかった" },
  { who: "koi", say: "お、何が一番よかった？" },
  { who: "me", say: "向こうから水族館行きたいって言われた" },
  { who: "koi", say: "次回予告きてるやん。日程は？" },
];

/** 会話のあとにできるもの */
export const DEMO_EP = {
  person: "Aさん",
  app: "with",
  number: 3,
  title: "2回目デート",
  /* ── 会話に出ていないことを、書かない ──────────────
     3行あったが、3行目は「気になる：返信が少し遅い」だった。
     会話のどこにも返信の話は出ていない。

     「話しただけで、ここまで残る」の見本なので、
     話していないことが残っていたら、それは嘘の見本になる。
     下の判定で、全部の行が会話から来ていることを見る。 */
  rows: [
    { mark: "✨", label: "よかったこと", body: "向こうから水族館の提案が出た" },
    { mark: "❤️", label: "自分", body: "また会いたいと思っている" },
  ],
  next: "水族館の日程を決める",
};

/* ══════════════════════════════════════════════════
   2回目。前回の続きから始まる
   ══════════════════════════════════════════════════
   ここが月額の理由そのもの。

   1回目は「話しただけでできてる」。
   2回目は「覚えてる」。

   覚えていることを見せないと、
   月額が「AIの利用料」にしか見えない。

   利用者は名前を言うだけ。状況を説明しない。
   説明させた時点で、覚えている意味が無くなる。 */
/* 4往復あったものを2往復にした。
   ここで見せたいのは「覚えている」の1点だけ。
   利用者が名前を言う → 恋亀が前回の続きを出す。それで足りる。

   3往復目以降は会話の続きで、覚えていることの証明にはなっていなかった。 */
export const DEMO_AGAIN: Turn[] = [
  { who: "me", say: "Aさんなんやけど" },
  { who: "koi", say: "前回、水族館の日程を決めるところやったよね。どうなった？" },
];

/** そのあと、人に聞くことを提案する一言 */
export const DEMO_ASK = `これ、実際の${advisorWord()}にも聞いてみる？`;

/* ── 公開の前に止めること ───────────────────────── */
{
  // 恋亀から始まること。利用者に最初の一言を考えさせない。
  if (DEMO_TALK[0].who !== "koi") {
    throw new Error("会話が、利用者から始まっています");
  }

  // 恋亀の返事が短いこと。人格の決まり（2文まで）と同じ。
  for (const t of DEMO_TALK) {
    if (t.who !== "koi") continue;
    const sentences = t.say.split(/[。？！]/).filter(Boolean).length;
    if (sentences > 2) {
      throw new Error(`恋亀の返事「${t.say}」が ${sentences} 文あります（2文まで）`);
    }
    // 1回に質問は1つまで。
    const q = (t.say.match(/？/g) ?? []).length;
    if (q > 1) throw new Error(`恋亀の返事「${t.say}」に、質問が ${q} つあります`);
  }

  // 相手の気持ちを当てる言い方をしないこと。
  for (const t of [...DEMO_TALK.map((x) => x.say), DEMO_ASK, DEMO_EP.next,
    ...DEMO_EP.rows.map((r) => r.body)]) {
    if (MIND_READING.test(t)) {
      throw new Error(`会話の見本「${t}」が、相手の気持ちの判定になっています`);
    }
  }

  // 長くしないこと。読むのに時間がかかると、飛ばされる。
  if (DEMO_TALK.length > 8) {
    throw new Error(`会話の見本が ${DEMO_TALK.length} 往復あります（8まで）`);
  }

  /* できたものに、利用者が入力していない項目が入っていること。
     「話しただけなのに全部できてる」がこの見本の役目なので、
     会話に出ていないことが埋まっていると、嘘になる。

     会話に出ているのは
       2回目だった / よかった / 水族館の提案 / 日程はまだ
     それ以外を書かない。 */
  const said = DEMO_TALK.map((t) => t.say).join("");
  if (!said.includes("水族館")) {
    throw new Error("会話に出ていないことが、EPに入っています（水族館）");
  }
  if (!said.includes("2回目")) {
    throw new Error("会話に出ていないことが、EPに入っています（2回目）");
  }

  /* ══════════════════════════════════════════════
     相手の振る舞いを、話していないのに書かない
     ══════════════════════════════════════════════
     上の2つは「水族館」「2回目」を名指しで見ていた。
     名指しなので、それ以外の行はいくらでも書けた。

     実際に書かれていた。
       🤔 気になる：返信が少し遅い
     会話のどこにも、返信の話は出ていない。

     「話しただけで、ここまで残る」の見本なので、
     話していないことが残っていたら、嘘の見本になる。

     ── 言い換えまでは止めない ──────────────────────
     最初は「行の語が会話に出ているか」で見たが、
     「また会いたいと思っている」まで止まった。
     あれは本人の「めっちゃよかった」の言い換えで、捏造ではない。

     止めたいのは、相手が何をしたかを勝手に書くほう。
     本人の気持ちの言い換えは通す。
     だから、相手の振る舞いを指す語だけを見る。 */
  {
    /** 相手が何をしたか、を指す語。書くなら会話に出ていること */
    const BEHAVIOR = /返信|既読|連絡|電話|誘|会ってくれ|ドタキャン|遅刻|返事/;
    for (const r of [...DEMO_EP.rows.map((x) => x.body), DEMO_EP.next]) {
      const m = r.match(BEHAVIOR);
      if (m && !said.includes(m[0])) {
        throw new Error(
          `EPの「${r}」に、会話で話していない相手の振る舞い（${m[0]}）が入っています`,
        );
      }
    }
  }

  // 次にやることが1つだけであること。
  if (/[、,]|および/.test(DEMO_EP.next)) {
    throw new Error(`次にやることが1つになっていません（${DEMO_EP.next}）`);
  }

  // 点数・率を出さないこと。恋愛をゲームにしない。
  for (const r of DEMO_EP.rows) {
    if (/\d+%|点|レベル|偏差値|勝率/.test(r.body)) {
      throw new Error(`EPの「${r.body}」が、点数になっています`);
    }
  }

  // 人に聞くことを、押し売りにしないこと。問いの形であること。
  if (!DEMO_ASK.endsWith("？")) {
    throw new Error("人に聞く提案が、問いになっていません");
  }

  /* ── 2回目は、説明させないこと ────────────────────
     ここが崩れると、月額の理由が消える。 */
  {
    // 利用者から始まること。恋亀から聞き直さない。
    if (DEMO_AGAIN[0].who !== "me") {
      throw new Error("2回目が、恋亀から始まっています（前回を聞き直しています）");
    }
    // 利用者の最初の一言が短いこと。説明させていない証拠。
    if (DEMO_AGAIN[0].say.length > 12) {
      throw new Error(`2回目の最初の一言が ${DEMO_AGAIN[0].say.length} 字あります（説明させています）`);
    }
    // 恋亀が、前回の続きを自分から出すこと。
    const koiFirst = DEMO_AGAIN.find((t) => t.who === "koi")?.say ?? "";
    if (!/前回/.test(koiFirst)) {
      throw new Error("2回目に、恋亀が前回を持ち出していません");
    }
    // 1回目で決めた「次にやること」と、つながっていること。
    // つながっていないと、覚えている見本にならない。
    if (!koiFirst.includes(DEMO_EP.next.slice(0, 4))) {
      throw new Error("2回目が、1回目の「次にやること」とつながっていません");
    }
    // 恋亀の返事は、ここでも2文まで。
    for (const t of DEMO_AGAIN) {
      if (t.who !== "koi") continue;
      const n = t.say.split(/[。？！]/).filter(Boolean).length;
      if (n > 2) throw new Error(`2回目の恋亀の返事「${t.say}」が ${n} 文あります`);
    }
  }

  /* 最初のひとことの長さは、ここで見ない。
     同じことを prompt.ts でも見ていて、数字が違っていた（24 と 90）。
     名乗りと入口3つを足して長くしたとき、こちらだけが止まった。

     持ち主は prompt.ts。あちらが長さも中身（名乗り・入口）も見る。
     ここで見るのは、画面の見本が人格と食い違っていないかだけ。 */
  if (!FIRST_LINE) {
    throw new Error("最初のひとことがありません");
  }
}
