/* ══════════════════════════════════════════════════
   恋亀と、いま話せるか
   ══════════════════════════════════════════════════

   ── 見出しが、実態より先に行かないようにする ──────
   「恋亀に話すだけ。」と1画面目に書いたとき、
   押しても話せないなら、それは嘘になる。

   このセッションで何度も直してきたのと同じ種類の間違い。
     女性1人しか売っていないのに「女性3人」と書いてあった
     審査を通った人が0人なのに、架空の4人を出していた

   同じことを見出しでやらない。

   ── 鍵が入ったら、ひとりでに変わる ──────────────
   環境変数が入れば true になり、画面の言葉もそちらへ変わる。
   入っていないあいだは、いまできること（確カメる）を出す。

   手で書き換えないので、入れ忘れ・戻し忘れが起きない。 */

const KEY = process.env.REALTIME_API_KEY;

/** 恋亀と、いま話せるか */
export const koiEnabled = Boolean(KEY);

/** 話せないとき、何が足りないか（運営画面に出す） */
export function whyKoiDisabled(): string | null {
  if (koiEnabled) return null;
  return "音声の鍵（REALTIME_API_KEY）が入っていません";
}

/* ══════════════════════════════════════════════════
   1画面目の、2行目
   ══════════════════════════════════════════════════
   いちばん軽い動作を1つだけ書く。
   できることが変われば、ここも変わる。 */

/** 恋亀と話せるとき */
const SUB_KOI = "恋亀に話すだけ。";
/** まだ話せないとき。いまできること */
/* ── 1画面目の2行目を、判断疲れに寄せた ──────────
   前は「迷ったら、実在する異性に確カメる。」だった。

   実在の異性は強いが、それを2行目に置くと
   「単発の相談サービス」に見える。月額の理由がぼける。

   先に言うのは、複数の相手を1つにまとめること。
   実在の異性は、そのあとの節で出す。 */
const SUB_NOW = "複数人のマッチ後を、1つに整理。";

export const heroSub = koiEnabled ? SUB_KOI : SUB_NOW;

/* ── 公開の前に止めること ───────────────────────── */
{
  // 2つとも、短いこと。見出しの下に置くので、折り返すと弱くなる。
  for (const t of [SUB_KOI, SUB_NOW]) {
    /* 20字まで、から18字までに縮めた。
       この行は 18px で出る。390px の本文幅は 350px なので、
       全角19字（342px）が上限。20字だと最後の1字が
       2行目に落ちて、「る。」だけが残っていた。
       携帯で読めない折り返しは、字数のほうで止める。 */
    if (t.length > 18) throw new Error(`1画面目の2行目「${t}」が長すぎます（18字まで）`);
    /* 何をすればいいかが、書いてあること。

       最初「〜る。」で終わるかだけ見ていたが、
       「恋亀に話すだけ。」が落ちた。書き方のほうが狭かった。

       見たいのは終わり方ではなく、動作の名前が入っているか。 */
    /* 「まとめる」「整理」を足した。
       製品の芯が「話を聞く」から「1か所にまとめる」へ移ったので、
       動作の名前もそちらが主になった。 */
    if (!/話す|確カメる|聞く|見てもらう|まとめる|整理/.test(t)) {
      throw new Error(`1画面目の2行目「${t}」に、何をするかが書かれていません`);
    }
  }

  /* 話せないのに、話せると書かないこと。
     ここが逆になっていたら、1画面目から嘘になる。 */
  if (!koiEnabled && heroSub.includes("恋亀に話す")) {
    throw new Error("恋亀と話せないのに、1画面目で話せることになっています");
  }
  if (koiEnabled && heroSub !== SUB_KOI) {
    throw new Error("恋亀と話せるのに、1画面目がそうなっていません");
  }

  // 足りないものが分かること。黙って出ないと、原因が追えない。
  if (!koiEnabled && !whyKoiDisabled()) {
    throw new Error("恋亀が使えない理由が、出ていません");
  }
}
