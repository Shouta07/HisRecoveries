/* ══════════════════════════════════════════════════
   旅亀と、いま話せるか
   ══════════════════════════════════════════════════

   ── 見出しが、実態より先に行かないようにする ──────
   「旅亀に話すだけ。」と1画面目に書いたとき、
   押しても話せないなら、それは嘘になる。

   このセッションで何度も直してきたのと同じ種類の間違い。
     女性1人しか売っていないのに「女性3人」と書いてあった
     審査を通った人が0人なのに、架空の4人を出していた

   同じことを見出しでやらない。

   ── 鍵が入ったら、ひとりでに変わる ──────────────
   環境変数が入れば true になり、画面の言葉もそちらへ変わる。
   入っていないあいだは、いまできること（確カメる）を出す。

   手で書き換えないので、入れ忘れ・戻し忘れが起きない。 */

const KEY = process.env.REALTIME_API_KEY;

/** 旅亀と、いま話せるか */
export const koiEnabled = Boolean(KEY);

/** 話せないとき、何が足りないか（運営画面に出す） */
export function whyKoiDisabled(): string | null {
  if (koiEnabled) return null;
  return "音声の鍵（REALTIME_API_KEY）が入っていません";
}

/* ══════════════════════════════════════════════════
   1画面目の、2行目
   ══════════════════════════════════════════════════
   いちばん軽い動作を1つだけ書く。
   できることが変われば、ここも変わる。 */

/** 旅亀と話せるとき */
const SUB_KOI = "旅亀に話すだけ。";

/* ══════════════════════════════════════════════════
   1画面目の2行目は、場面で言う
   ══════════════════════════════════════════════════
   「一人旅の不安をまとめます」と書いても、読んだ人が
   自分の画面を思い浮かべられない。「不安」が抽象的すぎる。

   起きる順番に4つ並べる。
     準備、空港、初日の夜、その次まで。
   自分がいまどこで止まっているかが、読みながら分かる。

   「準備」で止まっている人も、「空港からどう行くか」で
   止まっている人も、この1行の中に自分を見つけられる。 */
const SUB_NOW_1 = "準備、空港、初日の夜、その次まで。";
const SUB_NOW_2 = "一人旅の不安を、ひとつに。";
const SUB_NOW = SUB_NOW_1 + SUB_NOW_2;

export const heroSub = koiEnabled ? SUB_KOI : SUB_NOW;

/** 1画面目で折る位置。画面はこちらを行ごとに出す */
export const heroSubLines: string[] = koiEnabled ? [SUB_KOI] : [SUB_NOW_1, SUB_NOW_2];

/* ── 公開の前に止めること ───────────────────────── */
{
  // 2つとも、短いこと。見出しの下に置くので、折り返すと弱くなる。
  for (const t of [SUB_KOI, SUB_NOW]) {
    if (!t) throw new Error("1画面目の2行目が空です");
    /* 何をすればいいかが、書いてあること。

       最初「〜る。」で終わるかだけ見ていたが、
       「旅亀に話すだけ。」が落ちた。書き方のほうが狭かった。

       見たいのは終わり方ではなく、動作の名前が入っているか。 */
    /* 「まとめる」「整理」を足した。
       製品の芯が「話を聞く」から「1か所にまとめる」へ移ったので、
       動作の名前もそちらが主になった。 */
    /* ══════════════════════════════════════════════
       動詞の一覧だけで見るのを、やめた
       ══════════════════════════════════════════════
       ここは 話す／確カメる／聞く／見てもらう／まとめる／整理 の
       どれかが入っていることだけを見ていた。

       「複数人のマッチ後を、ひとつに。」で落ちた。
       この文は何をするかを言えている。動詞の形をしていないだけ。
       「ひとつに」は結果の言い方で、意味は「まとめる」と同じ。

       1画面目の2行目には、2つの形がありうる。
         ① 本人がやること      旅亀に話すだけ。
         ② 持ちものに起きること 複数人のマッチ後を、ひとつに。
       どちらかであればよい。

       ②は、対象と結果の両方が要る。片方だけだと止まる。
         「恋愛を、もっと自由に。」   対象はあるが、何も起きない
         「ぜんぶ、ひとつに。」       起きるが、何がなのか分からない
       どちらも1画面目に置けない文で、これが止めたかったもの。 */
    const DOES = /話す|確カメる|聞く|見てもらう|まとめる|整理/;
    const ABOUT = /旅|一人|空港|出発|準備|帰国|現地|不安/;
    const RESULT = /まとめ|整理|ひとつに|1つに|1か所|残る/;
    if (!DOES.test(t) && !(ABOUT.test(t) && RESULT.test(t))) {
      throw new Error(
        `1画面目の2行目「${t}」に、何をするかが書かれていません` +
          `（本人がやることを書くか、何がどうなるかを書いてください）`,
      );
    }
  }

  /* 話せないのに、話せると書かないこと。
     ここが逆になっていたら、1画面目から嘘になる。 */
  if (!koiEnabled && heroSub.includes("旅亀に話す")) {
    throw new Error("旅亀と話せないのに、1画面目で話せることになっています");
  }
  if (koiEnabled && heroSub !== SUB_KOI) {
    throw new Error("旅亀と話せるのに、1画面目がそうなっていません");
  }

  // 足りないものが分かること。黙って出ないと、原因が追えない。
  if (!koiEnabled && !whyKoiDisabled()) {
    throw new Error("旅亀が使えない理由が、出ていません");
  }

  /* ══════════════════════════════════════════════
     折る場所が、元の文と合っていること
     ══════════════════════════════════════════════
     片方だけ直すと、画面では読めない行が出る（型では捕まらない）。 */
  if (heroSubLines.join("") !== heroSub) {
    throw new Error(
      `1画面目の2行目を折る場所が、元の文と合っていません（${heroSubLines.join("")} ≠ ${heroSub}）`,
    );
  }
  /* 折った1行が、携帯で1行に入ること。
     この行は 18px で出る。390px の本文幅は 350px なので、
     全角19字（342px）が上限。
     20字あったときは、最後の1字だけが2行目に落ちていた。 */
  for (const line of heroSubLines) {
    if (line.length > 18) {
      throw new Error(`1画面目の2行目「${line}」が長すぎます（${line.length}字／18字まで）`);
    }
  }
}
