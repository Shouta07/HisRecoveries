import { STAGES } from "../talk/shape";
import { MIN_CONFIDENCE } from "../talk/shape";

/* ══════════════════════════════════════════════════
   話したことを、構造にする
   ══════════════════════════════════════════════════

   ── ここが、入口と出口のあいだ ──────────────────
   入口   声 → 文字起こし（Realtime API）
   ここ   文字起こし → 構造（TalkUpdate）
   出口   構造 → カード（koi/card.ts）

   入口と出口はできていた。ここだけ無かった。

   ── 恋亀とは、別の呼び出しにする ────────────────
   話している最中の恋亀は、速さが要る（声で返す）。
   整理は、終わったあとに1回でよく、速さより正確さが要る。

   同じ呼び出しに混ぜると、話の途中で整理に引っ張られて、
   相づちが固くなる。分ける。

   ── 作り話をさせない ────────────────────────────
   いちばん危ないのは、話していないことが記録に残ること。
   「話しただけで、ここまで残る」が売りなので、
   残ったものが嘘なら、製品ごと信用を失う。

   事実には、本人が実際に言った言葉（引用）を必ず付けさせる。
   引用の無いものは、受け取る側（talk/shape.ts）が捨てる。
   ここで強く言っておくと、捨てる量が減る。

   ── 相手の気持ちを、当てさせない ────────────────
   「脈あり」「本命」は書かせない（利用規約 第12条）。
   相手がどう受け取ったかは、実在の異性に聞く。
   混ぜると、AIが気持ちを当てる製品になる。 */

/**
 * 整理に使うモデル。
 *
 * ［要確認］名前は OpenAI 側で変わる。環境変数で差し替えられる。
 * 声と違って1回しか呼ばないので、安いもので足りる。
 */
export const STRUCTURE_MODEL = process.env.STRUCTURE_MODEL ?? "gpt-4o-mini";

/** 呼ぶ口。変わったときに差し替えられるようにしておく */
export const STRUCTURE_URL =
  process.env.STRUCTURE_URL ?? "https://api.openai.com/v1/chat/completions";

/**
 * 整理のときの、言いつけ。
 *
 * 恋亀の人格（prompt.ts）とは別物。
 * あちらは話す人、こちらは整理する人。混ぜない。
 */
export function buildStructurePrompt(): string {
  return [
    "あなたは、恋愛の相談の会話を、記録のための構造に直す係です。",
    "話し手は相談者、もう一方はAI（恋亀）です。",
    "",
    "次のJSONだけを返してください。説明も前置きも付けないでください。",
    "",
    "{",
    '  "facts": [{"body": "起きたこと", "quote": "本人が実際に言った言葉"}],',
    '  "feelings": ["本人が自分について言った気持ち"],',
    '  "opinions": ["本人が述べた考え"],',
    '  "inferences": [{"body": "あなたの見立て", "confidence": 0.0〜1.0}],',
    `  "stageUpdate": {"from": "段階", "to": "段階", "confidence": 0.0〜1.0} または null,`,
    '  "nextDateUpdate": {"date": "YYYY-MM-DD または null", "status": "confirmed|proposed|none"} または null,',
    '  "concernsAdd": ["本人が気にしていること"],',
    '  "signalsAdd": ["本人がよかったと言ったこと"],',
    '  "topicsToConfirm": ["本人が確かめたいと言ったこと"],',
    '  "nextAction": "次にやること。1つだけ",',
    '  "summary": "ひとことで現在地"',
    "}",
    "",
    "段階は、次のどれかだけです。ほかの言葉は使わないでください。",
    STAGES.join(" / "),
    "",
    "必ず守ること。",
    "・facts には、本人が実際に言った言葉を quote に入れること。",
    "　言っていないことは facts に入れないこと。推測は inferences へ。",
    `・inferences には confidence を付けること。自信が無いものは ${MIN_CONFIDENCE} 未満にすること。`,
    "・相手の気持ちを決めつけないこと。「脈あり」「本命」「嫌われている」は使わないこと。",
    "　相手がどう受け取ったかは、あなたには分かりません。",
    "　それは topicsToConfirm に入れてください。",
    "・nextAction は1つだけ。複数を「、」でつながないこと。",
    "・本人が話していないことを、どの欄にも足さないこと。",
    "・分からない欄は、空の配列か null にすること。埋めるために作らないこと。",
  ].join("\n");
}

/* ── 公開の前に止めること ───────────────────────── */
{
  const p = buildStructurePrompt();

  /* 引用を必ず求めること。
     ここが抜けると、話していないことが事実として残る。 */
  if (!/quote/.test(p) || !/本人が実際に言った言葉/.test(p)) {
    throw new Error("整理の言いつけに、引用を求めることが書かれていません");
  }
  if (!/言っていないことは facts に入れない/.test(p)) {
    throw new Error("整理の言いつけに、話していないことを入れない旨がありません");
  }

  /* 相手の気持ちを当てさせないこと（利用規約 第12条）。
     禁じる語を、名指しで書いていること。 */
  for (const w of ["脈あり", "本命", "決めつけ"]) {
    if (!p.includes(w)) {
      throw new Error(`整理の言いつけに「${w}」を禁じる記述がありません`);
    }
  }
  if (!/topicsToConfirm に入れて/.test(p)) {
    throw new Error("相手の受け取り方を、確かめたいことへ回す指示がありません");
  }

  /* 段階が、こちらの一覧から来ていること。
     手で書くと、schema.sql と食い違う。 */
  for (const s of STAGES) {
    if (!p.includes(s)) throw new Error(`整理の言いつけに、段階「${s}」がありません`);
  }

  // 確からしさの線が、受け取る側と同じであること。
  if (!p.includes(String(MIN_CONFIDENCE))) {
    throw new Error("整理の言いつけに、確からしさの線が入っていません");
  }

  // 次にやることが1つだけ、と言っていること。
  if (!/nextAction は1つだけ/.test(p)) {
    throw new Error("整理の言いつけに、次にやることを1つに絞る指示がありません");
  }

  // 埋めるために作らせないこと。
  if (!/埋めるために作らない/.test(p)) {
    throw new Error("整理の言いつけに、埋めるために作らない旨がありません");
  }

  /* JSONだけを返させること。
     前置きが付くと、受け取る側が落ちる。 */
  if (!/JSONだけ/.test(p)) {
    throw new Error("整理の言いつけに、JSONだけを返す指示がありません");
  }

  // 長すぎないこと。言いつけが長いと、守られる割合が落ちる。
  if (p.length > 1600) {
    throw new Error(`整理の言いつけが ${p.length} 字あります（1600字まで）`);
  }
}
