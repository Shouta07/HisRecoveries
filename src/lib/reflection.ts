import type { Entry } from "./relationship";
import type { StageId } from "./journey";

// 振り返り（§14）。
//
// ── 答えを返さない ────────────────────────────────
// 返すのは問いだけ。相性・脈・おすすめ行動は出さない。
// 相手の気持ちは、こちらには分からない。分かるふりをした瞬間に、
// このサービスは占いになる。
//
// ── 「AIが選んでいる」を感じさせない ────────────────
// 選び方はここに全部書いてある。書いた内容から規則で1つ選ぶだけ。
// 画面には、ただ問いが1つ置いてあるように見せる。
//
// ── 問いは1つ ─────────────────────────────────
// 3つ並べると、答えやすいものだけが選ばれて、残りは読まれない。
// いちばん引っかかりそうなものを1つだけ出す。

export type Question = {
  /** 画面に出す問い。「？」で終える。命令にしない */
  q: string;
  /** なぜいまこれを聞くのか。出さないこともある */
  why?: string;
};

/**
 * その記録に対して返す問いを1つ選ぶ。
 * 上から順に見て、最初に当たったものを返す。並び順が優先順位。
 */
export function questionFor(e: Entry): Question {
  // 「もう一度会いたい」。理由が書かれていないときは、そこを聞く。
  if (e.feel === "again" && !e.note && !e.noticed) {
    return {
      q: "もう一度会いたいと思ったのは、どんなところでしたか？",
      why: "理由のほうが先に薄れます。",
    };
  }
  if (e.feel === "again") {
    return { q: "次に会うなら、何をもう少し知りたいですか？" };
  }

  // 「少し違った」。ここで相手の欠点を数え始めないよう、主語を自分に戻す。
  if (e.feel === "off") {
    return {
      q: "違和感があったのは、相手のことでしたか。それとも、そのときの自分のことでしたか？",
    };
  }

  // 自然体でいられなかった日。
  if (e.natural === "little") {
    return { q: "話していて、無理をしている感じはありましたか？" };
  }
  if (e.natural === "some") {
    return { q: "どんなときに、少し構えてしまいましたか？" };
  }

  if (e.feel === "unsure") {
    return {
      q: "いま決められないのは、相手のことが分からないからですか。自分がどうしたいか決まっていないからですか？",
    };
  }

  if (e.feel === "fun") {
    return { q: "楽しかったのは、どんな時間でしたか？" };
  }

  return { q: "その日のことで、あとから思い出したことはありますか？" };
}

/**
 * 次に考えること（§15）。
 *
 * 「次の一手」にしない。前に進むことだけを正解にしない。
 * 待つ・もう少し知る・やめる、を同じ重さで並べる。
 * ここで並び順に意味を持たせないよう、段階ごとに固定の文面を持つ。
 */
export const NEXT_BY_STAGE: Record<StageId, string[]> = {
  prepare: [
    "気になっている場所と、先に手をつける場所を分けて考えてみる",
    "いま気にしていないものは、そのままにしておく",
  ],
  meet: ["実物と離れすぎていないか、写真を見直してみる", "まだ動かず、様子を見る"],
  talk: ["会う話を、自分から出すかどうかを決める", "返事の間隔は、そのままにしておく"],
  date: [
    "会う前に、自分が何を知りたいのかを1つ決めておく",
    "決めずに行って、あとで書き残す",
  ],
  again: [
    "もう一度会いたいかどうかを、自分の側だけで決める",
    "決まるまで、誘わずに待つ",
    "今回はここまでにする",
  ],
  know: [
    "自然体でいられた日と、そうでない日を分けて読み返す",
    "まだ分からないことを、分からないままにしておく",
  ],
  consider: [
    "何が決まれば決められるのかを、1つ書き出す",
    "いまは決めない、を今日の選択にする",
    "この関係を続けないことも、選択肢に入れて考えてみる",
  ],
  grow: ["最初のころと変わったことを、1つ書き残す", "変わったままにしておく"],
};

// ── 公開の前に止めること ───────────────────────────
// 断定・命令・攻略・確率。どれか1つでも通ると、問いが助言に変わる。
const BANNED = [
  "脈あり", "脈なし", "確率", "成功率", "相性", "％", "%", "点",
  "落とす", "攻略", "テクニック", "必ず", "絶対",
  "してください", "すべき", "おすすめ", "正解",
  "相手はこう思って", "相手の気持ちは", "間違いありません",
];

function check(texts: string[], where: string) {
  for (const t of texts) {
    const hit = BANNED.find((b) => t.includes(b));
    if (hit) throw new Error(`${where}の文面に「${hit}」が入っています（問いを助言にしない）`);
  }
}

// 問いの候補を、実際に起こりうる記録に通して全部確かめる。
// 文面だけ見て回ると、分岐の奥にあるものを見落とす。
{
  const feels = [undefined, "fun", "again", "unsure", "off"] as const;
  const naturals = [undefined, "yes", "some", "little"] as const;
  const texts: string[] = [];
  for (const f of feels) {
    for (const n of naturals) {
      for (const withNote of [false, true]) {
        const e: Entry = {
          id: "x",
          date: "2026-01-01",
          ...(f ? { feel: f } : {}),
          ...(n ? { natural: n } : {}),
          ...(withNote ? { note: "…" } : {}),
        };
        const q = questionFor(e);
        texts.push(q.q, q.why ?? "");
        if (!q.q.endsWith("？")) {
          throw new Error(`振り返りの文「${q.q}」が問いになっていません`);
        }
      }
    }
  }
  check(texts, "振り返りの問い");
}

check(Object.values(NEXT_BY_STAGE).flat(), "次に考えること");

// 「進む」だけを正解にしない（§15）。
// 迷いがいちばん濃い3段階には、進まない選択肢を必ず1つ持たせる。
const STAY_WORDS = ["待つ", "そのまま", "しておく", "決めない", "ここまで", "続けない", "様子"];
for (const s of ["again", "know", "consider"] as const) {
  if (!NEXT_BY_STAGE[s].some((t) => STAY_WORDS.some((w) => t.includes(w)))) {
    throw new Error(`段階「${s}」の次に考えることが、進む話だけになっています`);
  }
}
