/* ══════════════════════════════════════════════════
   貼られた文から、個人の情報を落とす
   ══════════════════════════════════════════════════
   会話をこちらに貼ってもらう作りなので、
   宿名・便名・予約番号・電話番号が混ざって届く。

   外へ出す前（整理のAIへ渡す前・保存する前）に、必ず通す。
   画面側でも落とすが、ブラウザは書き換えられるので、
   サーバーでもう一度かける。

   ── 旅で特に出るもの ────────────────────────────
   便名（TG641）、予約番号、パスポート番号、
   クレジットカード、宿の部屋番号。

   街区（スクンビット）は残す。そこが無いと相談にならない。 */

export type Masked = { text: string; found: number };

const RULES: { re: RegExp; to: string }[] = [
  // 便名。2文字の航空会社コード＋数字
  { re: /\b[A-Z]{2}\s?\d{2,4}\b/g, to: "［便名］" },
  // パスポート番号（日本は英字2＋数字7）
  { re: /\b[A-Z]{2}\d{7}\b/g, to: "［旅券番号］" },
  // カード番号らしい並び
  { re: /\b(?:\d[ -]?){13,16}\b/g, to: "［カード番号］" },
  // 電話番号
  { re: /\b0\d{1,4}[-\s]?\d{1,4}[-\s]?\d{3,4}\b/g, to: "［電話番号］" },
  { re: /\+\d{1,3}[-\s]?\d[\d-\s]{7,}/g, to: "［電話番号］" },
  // メール
  { re: /[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}/g, to: "［メール］" },
  // 予約番号・確認番号
  { re: /(予約|確認)番号[：:]?\s*[A-Za-z0-9-]{4,}/g, to: "［予約番号］" },
  // 部屋番号
  { re: /\d{3,4}号室/g, to: "［部屋番号］" },
];

export function mask(text: string): Masked {
  let out = text;
  let found = 0;
  for (const r of RULES) {
    out = out.replace(r.re, () => {
      found += 1;
      return r.to;
    });
  }
  return { text: out, found };
}

/* ── 公開の前に止めること ───────────────────────── */
{
  const cases: [string, string][] = [
    ["TG641で行きます", "［便名］"],
    ["予約番号: ABC123 です", "［予約番号］"],
    ["090-1234-5678 に連絡", "［電話番号］"],
    ["a.b@example.com まで", "［メール］"],
    ["301号室でした", "［部屋番号］"],
  ];
  for (const [input, want] of cases) {
    const r = mask(input);
    if (!r.text.includes(want)) {
      throw new Error(`「${input}」が伏せられていません（${r.text}）`);
    }
  }
  // 街区は残すこと。落とすと相談にならない
  if (mask("スクンビットに泊まります").found !== 0) {
    throw new Error("街区まで伏せています。そこが無いと相談になりません");
  }
  if (mask("バンコクは暑かった").found !== 0) {
    throw new Error("都市名を伏せています");
  }
}
