import { TIERS } from "../economics";

// 答える側の位置づけと、約束。
//
// ══════════════════════════════════════════════════
// なぜコードに置くか
// ══════════════════════════════════════════════════
// この製品は、女性が「自分の感覚を安全に価値へ変える」ことで成り立つ。
// そこが崩れると供給が止まり、男性側の商品も同時に消える。
//
// だから「何をしてもらうか」「何はしないか」を、募集の文と
// 同じ場所に置いて、ビルド時に見張る。
// 画面の文を書き換えるだけで、約束をこっそり緩められないようにする。
//
// ══════════════════════════════════════════════════
// 位置づけ
// ══════════════════════════════════════════════════
// 恋愛の先生ではない。正解を教える人ではない。
// 接客でもない。相手を喜ばせる人でもない。
//
// 送る前のものを読んで、自分が実際にどう受け取ったかを返す人。
// 言い換えると、恋愛の場面における実際の読み手。
//
// ══════════════════════════════════════════════════
// 声で話す商品を足したときに、何を変えたか
// ══════════════════════════════════════════════════
// もとは「相手と直接つながることはありません」と約束していた。
// 15分・30分の通話は1対1で直接やりとりするので、その文のままでは嘘になる。
//
// 変えたのは書き方で、守るものは変えていない。
//   渡さない   名前・電話番号・SNS・メール（渡す仕組みを作らない）
//   出さない   顔（通話は声だけ。映像は作っていない）
//   残さない   録音・文字起こし（録る口を作っていない）
//   延ばさない 時間が来たらサーバー側で切る
//
// ここを緩めたいときは、登録済みの人に先に伝えること。
// 黙って書き換えると、聞いていない約束で働かせることになる。

export const STANDING = {
  is: "送る前のものを読んで、自分が実際にどう受け取ったかを返す人",
  isNot: ["恋愛の先生", "アドバイザー", "接客", "疑似恋愛", "相手を喜ばせる役"],
  why: "正解を教える場所ではありません。あなたが実際にどう感じたかが、そのまま価値になります。",
};

/* ══════════════════════════════════════════════════
   しないこと
   ══════════════════════════════════════════════════
   「禁止事項」を小さく並べるのではなく、
   登録する前に読める場所に、はっきり書く。
   ここが曖昧なサービスには、安心して登録できない。 */

export type Never = { what: string; why: string };

export const NEVER: Never[] = [
  {
    what: "顔を出すことも、写真を出すことも求めません",
    why: "読まれるのはあなたの言葉です。顔は要りません",
  },
  {
    what: "性的なやりとりはありません",
    why: "扱うのは送る前の文面と、その印象だけです",
  },
  {
    // 声で話す商品を作ったので、ここの書き方を変えた。
    // 変える前は「相手と直接つながることはありません」だった。
    // 通話は1対1で直接やりとりするので、その文のままでは嘘になる。
    // 守っているのは「連絡先を渡さない」のほう。そちらは仕組みで守る。
    what: "連絡先を渡すことはありません",
    why: "名前も電話番号もSNSも、相手に渡す仕組みを作っていません",
  },
  {
    what: "話すのは、時間を決めたときだけです",
    why: "時間が来ると自動で切れます。録音もしません。途中でやめても構いません",
  },
  {
    what: "外部のサービスへ誘導することはできません",
    why: "やりとりはすべてこの中で終わります",
  },
  {
    what: "ノルマも、期限も、指名もありません",
    why: "届いた相談のうち、答えたいものだけ選べます",
  },
];

/* ══════════════════════════════════════════════════
   答え方
   ══════════════════════════════════════════════════
   自由に書いてもらうと、返ってくるものがばらつく。
   買う人は「何が返るか」を決めて払っているので、
   何を書くかの型だけ決めて、言い方は人それぞれに任せる。 */

export const FORMAT: { step: string; ask: string }[] = [
  { step: "第一印象", ask: "読んですぐ、どう思いましたか" },
  { step: "このままでOKか", ask: "このままでOK / 少し気になる / 変えた方がいい" },
  { step: "気になったところ", ask: "引っかかったのはどこですか" },
  { step: "なぜそう感じたか", ask: "自分の言葉で。整えなくて構いません" },
  { step: "どう直すとよいか", ask: "思いつけば。無ければ書かなくて大丈夫です" },
];

/* ══════════════════════════════════════════════════
   段
   ══════════════════════════════════════════════════
   回答の「数」ではなく「質」で上がる。
   単価は economics.ts の TIERS が持つ（金額をここに書き写さない）。 */

export const LADDER = TIERS.map((t) => ({
  id: t.id,
  label: t.label,
  yen: t.quickYen,
  can: t.can,
}));

/* ══════════════════════════════════════════════════
   顔の出し方
   ══════════════════════════════════════════════════
   出したい人だけ出す。出さなくても、相談する側には
   「確認の済んだ実在の人が読んでいる」ことが伝わるようにする
   （本人確認は裏側で行い、その内容は相談する側に見せない）。 */

export const FACE_CHOICES = [
  { id: "none", label: "出さない", note: "イラストのアイコンになります" },
  { id: "mood", label: "雰囲気だけ", note: "顔が写っていない写真" },
  { id: "photo", label: "出す", note: "顔の写真" },
] as const;

/* ── 公開の前に止めること ─────────────────────────
   募集の文が、いつのまにか別の商売の文体になっていないかを見る。
   ここが滑ると、来てほしい人が来なくなり、
   来てほしくない目的の人が来る。 */
{
  // 接客・疑似恋愛の商売で使われる言葉。1つでも入ったら落とす。
  const WRONG_TRADE =
    /チャットレディ|キャバ|風俗|色気|セクシー|甘え|癒やし|癒し|お客様|接客|疑似恋愛|ドキドキ|男性を喜ば|好意を持たせ|会話を盛り上げ/;

  // STANDING.isNot は「これではない」と並べた側なので、判定から外す。
  // ここを混ぜると、否定しているだけで落ちる。
  const texts = [
    STANDING.is,
    STANDING.why,
    ...NEVER.flatMap((n) => [n.what, n.why]),
    ...FORMAT.flatMap((f) => [f.step, f.ask]),
    ...LADDER.map((l) => `${l.label} ${l.can}`),
    ...FACE_CHOICES.flatMap((f) => [f.label, f.note]),
  ];
  for (const t of texts) {
    const hit = t.match(WRONG_TRADE);
    if (hit) {
      throw new Error(
        `答える側の文に「${hit[0]}」が入っています。この製品は接客でも疑似恋愛でもありません（${t}）`,
      );
    }
  }

  // 約束が消えていないか。1つでも欠けたら落とす。
  // 「録音」は声で話す商品を作ったときに足した。
  // 録音しないことは、ここに書いてある限り実装でも守る（call/ に録る口は無い）。
  const must = ["顔", "性的", "連絡先", "外部", "ノルマ", "録音", "自動で切れ"];
  for (const m of must) {
    if (!NEVER.some((n) => n.what.includes(m) || n.why.includes(m))) {
      throw new Error(`答える側の約束から「${m}」の話が消えています`);
    }
  }

  // 顔出しを必須にしない。
  if (!FACE_CHOICES.some((f) => f.id === "none")) {
    throw new Error("顔を出さない選択肢が消えています");
  }

  // 段は、上に行くほど高くなること。下がる段があると、質で上がる話が嘘になる。
  for (let i = 1; i < LADDER.length; i++) {
    if (LADDER[i].yen <= LADDER[i - 1].yen) {
      throw new Error(
        `段「${LADDER[i].label}」が「${LADDER[i - 1].label}」より高くありません`,
      );
    }
  }

  if (FORMAT.length < 4) throw new Error("答え方の型が少なすぎます");
}
