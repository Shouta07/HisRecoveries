/* ══════════════════════════════════════════════════
   Meet に入るときの、表示名
   ══════════════════════════════════════════════════

   ── なぜコードで持つのか ────────────────────────
   Meet は、ゲストとして入れば好きな表示名を入力できる。
   ログインしたまま入ると、Googleアカウントの表示名が出る。
   Meet の中だけで名前を変える機能は無い。

   つまり匿名かどうかは、入る人が毎回正しく操作するかで決まる。
   1回でも忘れたら本名が相手に渡り、渡ったら取り消せない。

   「気をつける」で支えると、いつか必ず外れる。
   だから、こちらで決めた名前を画面に出して、
   押せばコピーできるようにする。入る人は考えない。

   ── 名前に意味を持たせない ──────────────────────
   「みさき」のような人名にはしない。実在の人に見える。
   番号も通し番号にしない（何人目かが相手に分かる）。

   通話ごとに決まる、意味の無い1文字。
   同じ通話のあいだは変わらないので、途中で入り直しても同じ名前になる。 */

/** 表示名に使う文字。見間違えやすいもの（I・O）は外す */
const LETTERS = "ABCDEFGHJKLMNPQRSTUVWXYZ";

export type Side = "asker" | "reviewer";

/**
 * その通話で使う表示名。
 *
 * token から決めるので、何度呼んでも同じ。
 * サーバーでも画面でも同じ名前が出る。
 */
export function alias(token: string, side: Side): string {
  // token から1文字ぶんの数を作る。中身は推測されても困らない
  let n = 0;
  for (const ch of token) n = (n * 31 + ch.charCodeAt(0)) % LETTERS.length;
  const letter = LETTERS[n];
  return side === "reviewer" ? `回答者${letter}` : `相談者${letter}`;
}

/* ══════════════════════════════════════════════════
   入る前に、確かめてもらうこと
   ══════════════════════════════════════════════════
   Meet の仕様に合わせた手順。守らないと本名が出る。

   並び順に意味がある。
   ログアウトが先。名前の入力は、ゲストとして入ったあとにしか出ない。 */

export const BEFORE_JOIN: { step: string; why: string }[] = [
  {
    step: "Googleからログアウトするか、シークレットウィンドウで開く",
    why: "ログインしたまま入ると、Googleアカウントの名前がそのまま出ます",
  },
  {
    step: "表示名の欄に、下の名前をそのまま貼る",
    why: "Meetの中だけで名前を変えることはできません。入る前にしか決められません",
  },
  {
    step: "カメラを切ってから入る",
    why: "顔は出さない取り決めです。入ったあとで切ると、一瞬映ります",
  },
];

/** 回答者に伝える、守れなかったときに起きること */
export const IF_YOU_FORGET =
  "ログインしたまま入ると、お名前が相談者に表示されます。表示されたあとで消すことはできません。気づいたときは、いったん退出してから入り直してください。";

/* ── 公開の前に止めること ───────────────────────── */
{
  // 同じ通話なら、何度呼んでも同じ名前であること。
  // 入り直すたびに名前が変わると、相手から見て別人が入ってきたことになる。
  const t = "t".repeat(32);
  if (alias(t, "reviewer") !== alias(t, "reviewer")) {
    throw new Error("同じ通話で、表示名が変わっています");
  }

  // 相談者と回答者が、同じ名前にならないこと。
  if (alias(t, "asker") === alias(t, "reviewer")) {
    throw new Error("相談者と回答者が、同じ表示名になっています");
  }

  // 人名に見えないこと。実在の人に見えると、架空の人を出したのと同じになる。
  for (const side of ["asker", "reviewer"] as const) {
    const a = alias(t, side);
    if (!/^(回答者|相談者)[A-Z]$/.test(a)) {
      throw new Error(`表示名「${a}」が、決めた形になっていません`);
    }
  }

  // 見間違えやすい文字を使わないこと。
  // 貼り付けではなく手で打つ人がいる。I と 1、O と 0 は取り違える。
  if (/[IO]/.test(LETTERS)) {
    throw new Error("表示名に、見間違えやすい文字が入っています");
  }

  // ログアウトが先であること。
  // 順番を入れ替えると、名前を入れる欄がそもそも出ない。
  if (!BEFORE_JOIN[0].step.includes("ログアウト")) {
    throw new Error("入る前の手順で、ログアウトが最初に来ていません");
  }

  // 守れなかったときに何が起きるかを、必ず伝えること。
  // 手順だけ書いても、なぜ要るのかが分からないと飛ばされる。
  if (!IF_YOU_FORGET.includes("表示されたあとで消すことはできません")) {
    throw new Error("守れなかったときに起きることが、書かれていません");
  }

  // 手順は3つまで。増やすと読まれない。
  if (BEFORE_JOIN.length > 3) {
    throw new Error(`入る前の手順が ${BEFORE_JOIN.length} 個あります（3つまで）`);
  }
  // どの手順にも、なぜ要るのかを付ける。
  for (const b of BEFORE_JOIN) {
    if (!b.why) throw new Error(`手順「${b.step}」に、理由がありません`);
  }
}
