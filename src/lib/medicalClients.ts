// 制作を受託している医療機関の名簿と、編集面との遮断。
//
// ── なぜ要るか ────────────────────────────────
// 医療機関からは、患者さまのご紹介に連動した報酬を受け取らない。
// 一方で、医療機関ご自身の発信（自院サイトの記事、患者向けの説明資料）の
// 制作は受託する。対価は制作物に対するもので、患者数とは連動しない。
// だから医療広告ガイドラインでいう誘引性は発生しない。
//
// ただし、それは「編集面で扱わない」ことが守られている間だけの話。
// 受託先の医療機関を His Recoveries の記事で紹介したら、
// 受け取っているお金は、実質的にご紹介の対価と同じものになる。
// 名前を出した時点で特定性は満たされ、対価があるので誘引性も立つ。
//
// ── だから約束ではなく、機械に置く ────────────────────
// 受託先が増えるのは、たいてい忙しい時期で、
// そのとき記事を書く人と契約を結ぶ人が同じとは限らない。
// 「気をつける」では守れないので、記事に名前が出たらビルドを落とす。
//
// ── 使い方 ────────────────────────────────────
// 受託が決まったら、ここに医療機関名を足す。
// 表記ゆれ（正式名称・略称・院名だけ）も全部並べる。
// 並べ忘れたぶんは検査できないので、迷ったら多めに書く。

/**
 * 制作を受託している医療機関。
 * 名称は、記事本文に出たら止めたい表記をすべて並べる。
 */
export const MEDICAL_CLIENTS: { name: string; aliases: string[] }[] = [
  // 現時点で0件。受託が決まったらここに足す。
];

/** 検査の対象にする文字列（名称＋表記ゆれ） */
function allNames(): string[] {
  return MEDICAL_CLIENTS.flatMap((c) => [c.name, ...c.aliases]).filter((s) => s.trim().length > 0);
}

/**
 * 受託先の医療機関名が記事に出ていないかを確かめる。
 * 出ていたら、その記事か、その受託かのどちらかをやめる。
 */
export function assertNoClientInArticles() {
  const names = allNames();
  if (names.length === 0) return;

  for (const a of clusters) {
    const haystack = [
      a.title,
      a.lead,
      ...a.summary,
      ...a.sections.flatMap((s) => [s.h, s.body]),
    ].join("\n");

    for (const n of names) {
      if (haystack.includes(n)) {
        throw new Error(
          `記事「${a.title}」に、制作を受託している医療機関「${n}」が出ています。` +
            `受託先を編集面で扱うと、受け取っている制作費が、実質的にご紹介の対価になります。` +
            `記事から外すか、受託を終えてから書いてください。`,
        );
      }
    }
  }
}

/** 受託しているかどうか（開示ページで現在の状態を出すのに使う） */
export const HAS_MEDICAL_CLIENTS = MEDICAL_CLIENTS.length > 0;
