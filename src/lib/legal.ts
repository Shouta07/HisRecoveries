/** まだ埋まっていない必須項目 */
export function missingLegal(): LegalField[] {
  return LEGAL.filter((f) => f.required && !f.value);
}

/**
 * 決済してよいか。
 *
 * 特商法の表記が揃っていて、かつ Stripe の鍵があること。
 * どちらか欠けていたら、決済は始めない。
 */
export function canCharge(): boolean {
  return missingLegal().length === 0 && Boolean(process.env.STRIPE_SECRET_KEY);
}

/** なぜ決済できないか。画面と API で同じ言葉を使う */
export function whyCannotCharge(): string | null {
  const miss = missingLegal();
  if (miss.length > 0) {
    return `特定商取引法に基づく表記が未完成です（${miss.map((m) => m.label).join("・")}）`;
  }
  if (!process.env.STRIPE_SECRET_KEY) return "決済の設定が入っていません";
  return null;
}

/* ── 公開の前に止めること ─────────────────────────
   表記の項目そのものを減らせないようにする。
   減らすと、揃っていないことに気づけなくなる。 */
{
  const need = [
    "seller", "rep", "address", "tel", "email", "price",
    "extra", "pay_method", "pay_time", "delivery", "refund",
    /* cancel_call を外した。声で話す商品を売っていない。
       expiry は残す。買い切りで自動更新が無いことを言う欄になった。 */
    "expiry",
  ];
  for (const k of need) {
    const f = LEGAL.find((x) => x.key === k);
    if (!f) throw new Error(`特商法の表記から「${k}」が抜けています`);
    if (!f.required) throw new Error(`特商法の「${f.label}」は必須です`);
  }
  // 「準備中」「未定」で埋めた気にならないようにする。
  for (const f of LEGAL) {
    if (f.value && /準備中|未定|TBD|調整中|追って/.test(f.value)) {
      throw new Error(`特商法の「${f.label}」が実質空欄です（${f.value}）`);
    }
  }

  /* ── 空にするだけで、決めたことにしない ────────────
     REFUND_OPEN を空配列にすれば、返品・キャンセルの欄は埋まり、
     決済も開く。だが条件の文を書かずに空にしたなら、
     書いていない条件で運用することになる。

     3つとも、本文に書かれてから閉じること。 */
  if (REFUND_OPEN.length === 0) {
    for (const [re, what] of [
      [/お返事[^。]*(あと|後)|開始後|返信後/, "最初のお返事のあとのキャンセル"],
      [/中止|延期|振り替え|振替/, "旅行そのものが中止・延期になった場合"],
      [/お届けできなかった|お返事できなかった|返信できなかった/, "期間中にお返事できなかった場合"],
    ] as const) {
      if (!re.test(REFUND_SETTLED)) {
        throw new Error(
          `返品・キャンセルの条件に「${what}」が書かれていません。` +
            `REFUND_OPEN を空にする前に、本文へ書いてください`,
        );
      }
    }
  }

  /* 決まっていない条件があるなら、決済が開いていないこと。
     ここが逆になると、条件を決める前にお金を受け取る。 */
  if (REFUND_OPEN.length > 0 && missingLegal().every((f) => f.key !== "refund")) {
    throw new Error("返金の条件が決まっていないのに、返品・キャンセルの欄が埋まっています");
  }
}

  /* ── 月額の商品は、もう無い ────────────────────────
     ここは「月額を開いているなら、定期購入として書くべきことが
     全部あるか」を見る判定だった（改正特商法）。

     月額はやめて、1旅行ごとの買い切りだけにした。
     表記からも、自動更新・更新日・解約の条文を外した。

     ただし Stripe 側に古い月額の Price（STRIPE_PASS_PRICE_ID）が
     残っていると、決済は月額として通ってしまう。
     表記は買い切りのまま、請求は毎月。いちばんまずい形になる。

     なので逆向きに見る。
     月額が設定されていたら、それ自体を公開前に止める。 */
  {
    const all = LEGAL.map((f) => f.value ?? "").join("");
    if (passEnabled) {
      throw new Error(
        "Stripe に月額の Price が設定されていますが、月額の商品はもうありません。" +
          "STRIPE_PASS_PRICE_ID を消してください（表記は買い切りのまま、請求だけ毎月になります）",
      );
    }
    if (/自動的に更新/.test(all)) {
      throw new Error("買い切りなのに、特商法に自動更新のことが書かれています");
    }
  }
