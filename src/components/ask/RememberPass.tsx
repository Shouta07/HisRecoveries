"use client";

import { useEffect } from "react";

// 買った5回パスの鍵を、この端末に覚えておく。
//
// ══════════════════════════════════════════════════
// なぜ端末に置くか
// ══════════════════════════════════════════════════
// 会員登録が無いので、鍵を知っていること自体が持ち主の証。
// 相談の鍵と同じやり方で、新しい仕組みを増やさない。
//
// ══════════════════════════════════════════════════
// 消えることがある
// ══════════════════════════════════════════════════
// 端末を変えた、履歴を消した、私用ウィンドウで開いた。
// どれでも消える。だから消えても困らないように、
// 相談の結果そのものは相談の鍵（URL）から見られる。
//
// 消えたときに残りを取り戻す方法は、まだ無い。
// メールで送る仕組みを作るまでは、この面に出ている鍵が頼り。

export default function RememberPass({ token }: { token: string }) {
  useEffect(() => {
    try {
      localStorage.setItem("hr_pass", token);
    } catch {
      // 使えない端末。次の相談では、また決済の画面が出る
    }
  }, [token]);

  return null;
}
