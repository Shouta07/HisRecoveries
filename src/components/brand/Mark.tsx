// タシカメの記号。
//
// ══════════════════════════════════════════════════
// 亀を描かない。甲羅だけにする
// ══════════════════════════════════════════════════
// 頭・手足・顔を入れると、16px では全部つぶれて
// 「何か緑の塊」にしかならない。
//
// 残すのは、亀だと分かるいちばん強い形＝六角の甲羅。
// そこに「確かめた」を1つだけ入れる。
//
//   甲羅  タシカメ（亀）
//   ✓     確かめる
//
// ══════════════════════════════════════════════════
// 16px で成立させるための決まり
// ══════════════════════════════════════════════════
//   線は使わない（細い線は小さくすると消える）
//   面と抜きだけで作る
//   色は2つまで
//   甲羅の模様は入れない
//   グラデーションに頼らない
//
// ══════════════════════════════════════════════════
// 絵の亀とは役割が違う
// ══════════════════════════════════════════════════
// Tashikame.tsx の絵は、大きく出すときの顔。
// こちらは、小さく出すときの記号。
//
// ── タブとホーム画面は、恋亀の顔にした ────────────
// 前はここの形を icon.svg にも写していて、
// 「片方だけ直さないこと」と書いてあった。
//
// タブ・ホーム画面は恋亀の顔（絵）に変えたので、
// 写す相手は無くなった。icon.svg は消してある。
//   src/app/icon.png        タブ・ブックマーク
//   src/app/favicon.ico     16/32/48 を1つに
//   src/app/apple-icon.png  ホーム画面（地は白）
// どれも public/img/tashikame-192.png の顔から切っている。
//
// この記号は、画面の中（ヘッダー・料金・結果）で使う。
// 名前（タシカメ）がすぐ横にある場所なので、
// 何の店かは文字が言う。記号は小さく効けばよい。

/** 甲羅の緑。ok-text と同じ（この製品で「確かめた」を示す色） */
const SHELL = "#15803D";
/** 抜きの白 */
const CUT = "#FFFFFF";

/**
 * 六角の甲羅に、チェックを抜く。
 *
 * viewBox は 32。16px に縮めても、
 * 角の丸みとチェックの太さが残る大きさ。
 */
export function markPath() {
  return {
    /**
     * 甲羅。横長のドーム。
     *
     * 最初は角を丸めた六角形にしていた。
     * 16px にすると、よくある「認証済みバッジ」と見分けが付かなかった。
     * 亀の甲羅は縦より横が長く、下が平ら。
     * その形にすると、小さくてもバッジには見えない。
     */
    shell:
      "M3 20a13 13 0 0 1 26 0v3a3 3 0 0 1-3 3H6a3 3 0 0 1-3-3Z",
    /** チェック。太く短く。細いと小さいときに消える */
    check: "M10.6 17.4l3.9 3.9 7-7.4",
  };
}

export default function Mark({
  size = 28,
  className = "",
  title,
}: {
  size?: number;
  className?: string;
  /** 読み上げ用。飾りのときは省く */
  title?: string;
}) {
  const p = markPath();
  return (
    <svg
      viewBox="0 0 32 32"
      width={size}
      height={size}
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
      className={`shrink-0 ${className}`}
    >
      <path d={p.shell} fill={SHELL} />
      <path
        d={p.check}
        fill="none"
        stroke={CUT}
        strokeWidth="3.6"
        strokeLinecap="round"
        strokeLinejoin="round"
      />
    </svg>
  );
}

/* ── 公開の前に止めること ───────────────────────── */
{
  const p = markPath();

  // 甲羅とチェックの2つだけ。増やすと16pxでつぶれる。
  if (Object.keys(p).length !== 2) {
    throw new Error("記号の形が2つを超えています（16pxでつぶれます）");
  }

  // チェックの線の太さ。3未満にすると、16pxで消える。
  // （32のviewBoxで線幅3.6は、16px表示で1.8px相当）
  const W = 3.6;
  if (W < 3) throw new Error("チェックが細すぎます（小さくすると消えます）");

  // 甲羅が、面で描かれていること。
  // 線で描くと、小さくしたときに中身が抜けて何か分からなくなる。
  if (!p.shell.startsWith("M") || !p.shell.includes("Z")) {
    throw new Error("甲羅が閉じた面になっていません");
  }

  // 色は2つまで。
  if (new Set([SHELL, CUT]).size > 2) throw new Error("記号の色が多すぎます");
}
