/* 恋亀の顔。会話の吹き出しの横に置く。
 *
 * ══════════════════════════════════════════════════
 * 絵文字をやめた
 * ══════════════════════════════════════════════════
 * 吹き出しの横は、ずっと 🐢 の絵文字だった。
 * 絵文字は端末が描くので、こちらの恋亀とは別の亀が出る。
 *   iPhone   のっぺりした横向きの亀
 *   Android  別の形の亀
 *   Windows  また別の亀
 * 話している相手が、見る人の端末ごとに違う顔になっていた。
 *
 * 恋亀は、この製品で唯一ずっと出てくる相手なので、
 * そこだけは同じ顔にする。
 *
 * ══════════════════════════════════════════════════
 * 顔だけを切ってある
 * ══════════════════════════════════════════════════
 * 全身の絵（tashikame-192）は、28px にすると緑の染みになる。
 * 虫めがねも、小さくすると顔の横の点にしか見えない。
 * public/img/koi-head-128.png は、顔だけを切ったもの。
 * タブとホーム画面のアイコンも、同じ切り方。
 *
 * ══════════════════════════════════════════════════
 * 少しだけ動かす
 * ══════════════════════════════════════════════════
 * 止まっている絵だと、貼り付けた画像に見える。
 * ほんの少し上下に揺らして、奥行きを付けて傾ける。
 *
 * やりすぎない。読むのは吹き出しの中の文で、顔ではない。
 *   振れ幅   2px
 *   周期     3.6秒（心拍より遅い。急かさない）
 *   傾き     3度
 *
 * 動きを切っている人には、動かさない（globals.css の
 * prefers-reduced-motion が、この animation を止める）。
 */

export default function KoiFace({
  size = 34,
  /** 少し動かすか。並べてたくさん出すときは止める */
  alive = true,
  /* 揺れ始めをずらす秒数。
     同じ画面に5つ出て、全部が同じ拍で揺れると、
     生きている相手ではなく、機械の部品に見える。
     吹き出しの順番から少しずつずらす。 */
  delay = 0,
  className = "",
}: {
  size?: number;
  alive?: boolean;
  delay?: number;
  className?: string;
}) {
  return (
    /* ── 丸く切らない ──────────────────────────────
       最初は白い丸の中に入れて影を付けていた（絵文字の
       置き換えなので、同じ見た目にしたかった）。

       28px の丸に収めると、顔の上と横が切れて、
       緑の塊にしか見えなかった。実測して分かった。

       丸をやめて、絵をそのまま置く。
       吹き出しの横に、恋亀がいるように見える。 */
    <span
      aria-hidden
      className={`inline-flex shrink-0 items-center justify-center ${
        alive ? "koi-alive" : ""
      } ${className}`}
      style={{
        width: size,
        height: size,
        ...(alive && delay ? { animationDelay: delay + "s" } : {}),
      }}
    >
      {/* next/image を使わない。飾りとして小さく置くだけ */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img
        src="/img/koi-head-128.png"
        alt=""
        width={size}
        height={size}
        decoding="async"
        loading="lazy"
        className="select-none"
        style={{ width: size, height: size }}
      />
    </span>
  );
}
