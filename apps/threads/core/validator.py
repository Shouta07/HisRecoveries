# 布教・啓蒙表現
_NG_EVANGELISM = ["あなたも変われる", "誰でもできる", "あなたも", "僕にできたから", "簡単に"]

# 商業・宣伝表現
_NG_COMMERCIAL = ["おすすめです", "ぜひ", "詳しくはこちら"]

# カジュアル・バズ語彙（Nagi v2 禁止）
_NG_CASUAL_BUZZ = ["ぶっちゃけ", "ガチで", "神", "最強"]

# リアクション誘導表現（内密な読者: 反応を求めない）
